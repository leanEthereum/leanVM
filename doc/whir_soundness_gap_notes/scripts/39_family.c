// Researcher 39: the complete list of the word X^(n/2) L_W (|W| = n/8, codewords of degree <= n/2) at agreement
// 19n/32 on a generic subspace, for n = 32, 64, 128, with periods of triple functions, primitive sublists and ranks.
//
//   39_family N seed [ext] [orbit [orbcheck C]] [pairs P] [prim R] [rank] [dump file] [threads t]
//
// 1. Enumeration (formal model). By Theorem S of note 39 every member at agreement >= 9n/16 is a multiset top, and
//    by Theorem W of note 02 with its converse the multiset tops are the multisets c of mass 5n/8 with
//    c^(phi) = n/8 mod n/4 for phi in W^perp and c^(phi) = 0 mod n/4 otherwise (c^ the Walsh transform). By Parseval
//    and note 39 Proposition 4.1 the spectrum is: W^perp \ 0 all +-n/8 and two or three other functionals at +-n/4,
//    or one functional of W^perp at +-3n/8 and at most one other at +-n/4. All such spectra are tried and the
//    integer valued, nonnegative ones with support >= 19n/32 are kept. "ext" also tries four functionals at +-n/4,
//    one at +-n/2 and two of W^perp at +-3n/8 (nothing new appears for N = 5, 6, 7; two minutes at N = 7).
// 2. Verification on a random N-dimensional subspace of GF(2^64) (basis from xorshift(seed), point p = sum of the
//    basis vectors over the bits of p, W = span of the first N - 3): for every member the coefficients
//    e_1..e_(n/8-1) of prod (1 + sZ)^c(s) are compared with those of a union of five cosets of W.
// 3. "dump file": the supports as hex masks, one per line (to compare with the exhaustive oracle at n = 32).
// 4. Triple functions xi_l = (c_l - c_i)/(c_j - c_i): the period group is computed by evaluating at t + a, a in D,
//    for random t (two values of t for N <= 6, one for N = 7). B(i, j) = number of l with no nonzero period.
//    "orbit": orbits of the members under the group generated by the translations and the transvections that
//    preserve W, and the exact minimum of B(i, j) over all pairs (i over orbit representatives, all j).
//    "orbcheck C" repeats the minimum over j for C random first members and compares with their representative.
//    "pairs P": B(i, j) for all pairs among the first min(56, 8) W-invariant members, and for P random pairs.
// 5. "prim R": R greedy runs for a primitive sublist (no triple function with a nonzero period, no collinear triple).
// 6. "rank": the affine rank of the list over GF(2^64) (dimension of the span of the differences).
#include "02_gf.h"
#include <pthread.h>
#define MAXN 128
static int N, n, NW, MASS, T, NTH = 4, Q = 2;
static u64 pts[MAXN];
static u64 rs;
static inline u64 rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
typedef struct { unsigned char c[MAXN]; } mset;
static mset *mem; static size_t nmem, capmem;
static int G[8];

static void try_spectrum(int nout, const int *psi, const int *sg) {
  unsigned char c[MAXN]; int supp = 0;
  for (int x = 0; x < n; x++) {
    int s = 0; for (int i = 0; i < nout; i++) s += (__builtin_parity(psi[i] & x) ? -sg[i] : sg[i]);
    int v = G[x >> NW] + 2 * s;
    if (v < 0 || (v & 7)) return;
    c[x] = (unsigned char)(v >> 3); supp += c[x] > 0;
  }
  if (supp < T) return;
  if (nmem == capmem) { capmem = capmem * 2 + 4096; mem = realloc(mem, capmem * sizeof(mset)); }
  memset(mem[nmem].c, 0, MAXN); memcpy(mem[nmem].c, c, n); nmem++;
}
static void outside(int maxout, int e2) { // all sets of <= maxout functionals outside W^perp with coefficients +-1 (and one with +-2 if e2)
  int psi[4], sg[4]; int m = n, lowmask = (n >> 3) - 1;
  try_spectrum(0, psi, sg);
  for (int a = 1; a < m; a++) { if (!(a & lowmask)) continue; psi[0] = a;
    for (int s0 = -1; s0 <= 1; s0 += 2) { sg[0] = s0; try_spectrum(1, psi, sg); if (e2) { sg[0] = 2 * s0; try_spectrum(1, psi, sg); sg[0] = s0; } }
    if (maxout < 2) continue;
    for (int b = a + 1; b < m; b++) { if (!(b & lowmask)) continue; psi[1] = b;
      for (int s = 0; s < 4; s++) { sg[0] = s & 1 ? -1 : 1; sg[1] = s & 2 ? -1 : 1; try_spectrum(2, psi, sg); }
      if (maxout < 3) continue;
      for (int c = b + 1; c < m; c++) { if (!(c & lowmask)) continue; psi[2] = c;
        for (int s = 0; s < 8; s++) { sg[0] = s & 1 ? -1 : 1; sg[1] = s & 2 ? -1 : 1; sg[2] = s & 4 ? -1 : 1; try_spectrum(3, psi, sg); }
        if (maxout < 4) continue;
        for (int d = c + 1; d < m; d++) { if (!(d & lowmask)) continue; psi[3] = d;
          for (int s = 0; s < 16; s++) { sg[0] = s & 1 ? -1 : 1; sg[1] = s & 2 ? -1 : 1; sg[2] = s & 4 ? -1 : 1; sg[3] = s & 8 ? -1 : 1; try_spectrum(4, psi, sg); } }
      }
    }
  }
}
static void set_G(const int *a) { for (int y = 0; y < 8; y++) { G[y] = 5; for (int t = 1; t < 8; t++) G[y] += __builtin_parity(t & y) ? -a[t] : a[t]; } }
static void enumerate(int ext) {
  int a[8];
  for (int s = 0; s < 128; s++) { for (int t = 1; t < 8; t++) a[t] = (s >> (t - 1) & 1) ? -1 : 1; set_G(a); outside(ext ? 4 : 3, ext); }
  for (int p = 1; p < 8; p++) for (int s = 0; s < 128; s++) { for (int t = 1; t < 8; t++) a[t] = (s >> (t - 1) & 1) ? -1 : 1; a[p] *= 3; set_G(a); outside(ext ? 2 : 1, 0); }
  if (ext) for (int p = 1; p < 8; p++) for (int p2 = p + 1; p2 < 8; p2++) for (int s = 0; s < 128; s++) { for (int t = 1; t < 8; t++) a[t] = (s >> (t - 1) & 1) ? -1 : 1; a[p] *= 3; a[p2] *= 3; set_G(a); outside(0, 0); }
}
static int cmp_mset(const void *x, const void *y) { return memcmp(x, y, sizeof(mset)); }
static long find_member(const unsigned char *c) {
  size_t lo = 0, hi = nmem;
  while (lo < hi) { size_t mid = (lo + hi) / 2; int r = memcmp(mem[mid].c, c, MAXN); if (r == 0) return (long)mid; if (r < 0) lo = mid + 1; else hi = mid; }
  return -1;
}

// ---------- parallel for ----------
typedef void (*job_fn)(size_t lo, size_t hi, int th);
typedef struct { job_fn f; size_t lo, hi; int th; } job_t;
static void *job_run(void *p) { job_t *j = p; j->f(j->lo, j->hi, j->th); return 0; }
static void par_for(job_fn f, size_t cnt) {
  pthread_t th[64]; job_t jb[64];
  for (int t = 0; t < NTH; t++) { jb[t].f = f; jb[t].lo = cnt * t / NTH; jb[t].hi = cnt * (t + 1) / NTH; jb[t].th = t; pthread_create(&th[t], 0, job_run, &jb[t]); }
  for (int t = 0; t < NTH; t++) pthread_join(th[t], 0);
}

// ---------- values of the locators at t_q + a ----------
static u64 *val; static u64 tq[2];
#define VAL(m, q, a) val[((m) * (size_t)Q + (q)) * n + (a)]
static void val_job(size_t lo, size_t hi, int th) {
  (void)th; u64 tau[2][MAXN];
  for (int q = 0; q < Q; q++) for (int z = 0; z < n; z++) tau[q][z] = tq[q] ^ pts[z];
  for (size_t m = lo; m < hi; m++) for (int q = 0; q < Q; q++) for (int a = 0; a < n; a++) {
    u64 v = 1; const unsigned char *c = mem[m].c;
    for (int x = 0; x < n; x++) for (int e = 0; e < c[x]; e++) v = gmul(v, tau[q][a ^ x]);
    VAL(m, q, a) = v;
  }
}
// number of a in D (a = 0 included) with xi_l(X + a) = xi_l(X), xi_l = (P_l - P_i)/(P_j - P_i); n means constant
static int period_count(size_t i, size_t j, size_t l) {
  int per = 0;
  u64 A0 = VAL(l, 0, 0) ^ VAL(i, 0, 0), B0 = VAL(j, 0, 0) ^ VAL(i, 0, 0);
  for (int a = 0; a < n; a++) {
    u64 Aa = VAL(l, 0, a) ^ VAL(i, 0, a), Ba = VAL(j, 0, a) ^ VAL(i, 0, a);
    if (gmul(Aa, B0) != gmul(A0, Ba)) continue;
    if (Q > 1) { u64 A1 = VAL(l, 1, 0) ^ VAL(i, 1, 0), B1 = VAL(j, 1, 0) ^ VAL(i, 1, 0), Ab = VAL(l, 1, a) ^ VAL(i, 1, a), Bb = VAL(j, 1, a) ^ VAL(i, 1, a); if (gmul(Ab, B1) != gmul(A1, Bb)) continue; }
    per++;
  }
  return per;
}
static int has_period(size_t i, size_t j, size_t l) { // some a != 0 (constant functions count as periodic)
  u64 A0 = VAL(l, 0, 0) ^ VAL(i, 0, 0), B0 = VAL(j, 0, 0) ^ VAL(i, 0, 0);
  for (int a = 1; a < n; a++) {
    u64 Aa = VAL(l, 0, a) ^ VAL(i, 0, a), Ba = VAL(j, 0, a) ^ VAL(i, 0, a);
    if (gmul(Aa, B0) != gmul(A0, Ba)) continue;
    if (Q > 1) { u64 A1 = VAL(l, 1, 0) ^ VAL(i, 1, 0), B1 = VAL(j, 1, 0) ^ VAL(i, 1, 0), Ab = VAL(l, 1, a) ^ VAL(i, 1, a), Bb = VAL(j, 1, a) ^ VAL(i, 1, a); if (gmul(Ab, B1) != gmul(A1, Bb)) continue; }
    return 1;
  }
  return 0;
}
// B(i, j): thirds without a nonzero period
static long B_of_pair(size_t i, size_t j) {
  long b = 0;
  for (size_t l = 0; l < nmem; l++) { if (l == i || l == j) continue; if (!has_period(i, j, l)) b++; }
  return b;
}

// ---------- orbits ----------
static size_t *uf;
static size_t uf_find(size_t x) { while (uf[x] != x) { uf[x] = uf[uf[x]]; x = uf[x]; } return x; }
static int *stab, *supp, *maxm;

// exact minimum of B over pairs (i a representative, all j)
static size_t *reps; static size_t nreps;
static size_t cur_rep; static long *th_min, *th_max; static size_t *th_arg;
static void bmin_job(size_t lo, size_t hi, int th) {
  size_t i = reps[cur_rep]; long mn = -1, mx = -1; size_t arg = 0;
  for (size_t j = lo; j < hi; j++) { if (j == i) continue; long b = B_of_pair(i, j); if (mn < 0 || b < mn) { mn = b; arg = j; } if (b > mx) mx = b; }
  th_min[th] = mn; th_arg[th] = arg; th_max[th] = mx;
}

int main(int argc, char **argv) {
  if (argc < 3) { fprintf(stderr, "usage: 39_family N seed [ext] [orbit [orbcheck C]] [pairs P] [prim R] [rank] [dump file] [threads t]\n"); return 1; }
  gf_init(64, 0x1b);
  N = atoi(argv[1]); n = 1 << N; NW = N - 3; MASS = 5 * n / 8; T = 19 * n / 32;
  if (N < 5 || N > 7) { fprintf(stderr, "N = 5, 6 or 7\n"); return 1; }
  int ext = 0, do_orbit = 0, npairs = 0, nprim = 0, do_rank = 0, orbcheck = 0; const char *dump = 0;
  for (int i = 3; i < argc; i++) {
    if (!strcmp(argv[i], "ext")) ext = 1; else if (!strcmp(argv[i], "orbit")) do_orbit = 1; else if (!strcmp(argv[i], "rank")) do_rank = 1;
    else if (!strcmp(argv[i], "pairs")) npairs = atoi(argv[++i]); else if (!strcmp(argv[i], "prim")) nprim = atoi(argv[++i]);
    else if (!strcmp(argv[i], "dump")) dump = argv[++i]; else if (!strcmp(argv[i], "threads")) NTH = atoi(argv[++i]);
    else if (!strcmp(argv[i], "orbcheck")) orbcheck = atoi(argv[++i]);
  }
  if (N == 7) Q = 1;
  rs = 88172645463325252ull ^ (strtoull(argv[2], 0, 10) * 0x9E3779B97F4A7C15ull); for (int i = 0; i < 20; i++) rnd();
  u64 basis[8]; for (int i = 0; i < N; i++) basis[i] = rnd();
  for (int p = 0; p < n; p++) { pts[p] = 0; for (int i = 0; i < N; i++) if (p >> i & 1) pts[p] ^= basis[i]; }

  // 1. enumeration
  enumerate(ext);
  qsort(mem, nmem, sizeof(mset), cmp_mset);
  size_t u = 0; for (size_t i = 0; i < nmem; i++) if (i == 0 || memcmp(&mem[i], &mem[u - 1], sizeof(mset))) mem[u++] = mem[i];
  size_t dups = nmem - u; nmem = u;
  printf("N=%d n=%d: word X^%d L_W, |W| = %d, degree <= %d, agreement >= %d: %zu multisets (%zu duplicates removed)%s\n", N, n, n / 2, n / 8, n / 2, T, nmem, dups, ext ? " [extended spectra]" : "");
  stab = malloc(nmem * sizeof(int)); supp = malloc(nmem * sizeof(int)); maxm = malloc(nmem * sizeof(int));
  long hist[MAXN + 1][4][MAXN + 1]; memset(hist, 0, sizeof hist);
  for (size_t m = 0; m < nmem; m++) {
    int s = 0, mx = 0, st = 0; const unsigned char *c = mem[m].c;
    for (int x = 0; x < n; x++) { s += c[x] > 0; if (c[x] > mx) mx = c[x]; }
    for (int a = 0; a < n; a++) { int ok = 1; for (int x = 0; x < n && ok; x++) ok = c[x] == c[x ^ a]; st += ok; }
    supp[m] = s; maxm[m] = mx; stab[m] = st; hist[s][mx < 3 ? mx : 3][st]++;
  }
  printf("members by (support, largest multiplicity, order of the group of periods of the multiset) : count\n");
  for (int s = 0; s <= n; s++) for (int mx = 0; mx < 4; mx++) for (int st = 0; st <= n; st++) if (hist[s][mx][st]) printf("  (%d, %d, %d) : %ld\n", s, mx, st, hist[s][mx][st]);
  { long m2 = (1L << NW) - 1, m1 = (1L << (NW - 1)) - 1; printf("formula 56n - 392 + 14336 [N-3 choose 2]_2 = %ld\n", 56L * n - 392 + 14336L * (m2 * m1 / 3)); }
  if (dump) {
    FILE *f = fopen(dump, "w");
    for (size_t m = 0; m < nmem; m++) { u64 lo = 0, hi = 0; for (int x = 0; x < n; x++) if (mem[m].c[x]) { if (x < 64) lo |= 1ull << x; else hi |= 1ull << (x - 64); } if (n > 64) fprintf(f, "%016llx%016llx\n", (unsigned long long)hi, (unsigned long long)lo); else fprintf(f, "%llx\n", (unsigned long long)lo); }
    fclose(f);
  }

  // 2. verification of the common top on the concrete domain
  {
    int depth = n / 8; u64 ref[MAXN]; long bad = 0;
    for (size_t m = 0; m <= nmem; m++) {
      u64 e[MAXN]; memset(e, 0, sizeof e); e[0] = 1;
      for (int x = 0; x < n; x++) { int mult = m < nmem ? mem[m].c[x] : (x >> NW) < 5; for (int t = 0; t < mult; t++) for (int j = depth - 1; j >= 1; j--) e[j] ^= gmul(e[j - 1], pts[x]); }
      if (m == nmem) break;
      if (m == 0) { // reference: five cosets
        u64 f[MAXN]; memset(f, 0, sizeof f); f[0] = 1;
        for (int x = 0; x < n; x++) if ((x >> NW) < 5) for (int j = depth - 1; j >= 1; j--) f[j] ^= gmul(f[j - 1], pts[x]);
        memcpy(ref, f, sizeof ref);
      }
      for (int j = 1; j < depth; j++) if (e[j] != ref[j]) { bad++; break; }
    }
    printf("verification in GF(2^64): %ld of %zu members fail to share e_1..e_%d with a union of five cosets of W\n", bad, nmem, depth - 1);
  }
  if (!do_orbit && !npairs && !nprim && !do_rank) return 0;

  // 4. values
  for (int q = 0; q < 2; q++) tq[q] = rnd();
  val = malloc(nmem * (size_t)Q * n * sizeof(u64));
  if (!val) { fprintf(stderr, "out of memory\n"); return 1; }
  par_for(val_job, nmem);

  if (do_orbit) {
    uf = malloc(nmem * sizeof(size_t)); for (size_t i = 0; i < nmem; i++) uf[i] = i;
    for (size_t m = 0; m < nmem; m++) {
      unsigned char c[MAXN];
      for (int i = 0; i < N; i++) { // translations
        memset(c, 0, MAXN); for (int x = 0; x < n; x++) c[x ^ (1 << i)] = mem[m].c[x];
        long o = find_member(c); if (o < 0) { printf("translation leaves the list!\n"); return 1; } uf[uf_find(m)] = uf_find((size_t)o);
      }
      for (int i = 0; i < N; i++) for (int j = 0; j < N; j++) { // x_i += x_j, preserving W = {x < 2^NW}
        if (i == j || (j < NW && i >= NW)) continue;
        memset(c, 0, MAXN); for (int x = 0; x < n; x++) c[x ^ (((x >> j) & 1) << i)] = mem[m].c[x];
        long o = find_member(c); if (o < 0) { printf("transvection leaves the list!\n"); return 1; } uf[uf_find(m)] = uf_find((size_t)o);
      }
    }
    reps = malloc(nmem * sizeof(size_t)); nreps = 0; size_t *osz = calloc(nmem, sizeof(size_t));
    for (size_t m = 0; m < nmem; m++) { osz[uf_find(m)]++; }
    for (size_t m = 0; m < nmem; m++) if (uf_find(m) == m) reps[nreps++] = m;
    printf("orbits of the members under translations and W-preserving transvections: %zu\n", nreps);
    th_min = malloc(64 * sizeof(long)); th_max = malloc(64 * sizeof(long)); th_arg = malloc(64 * sizeof(size_t));
    long gmin = -1; size_t gi = 0, gj = 0; long *rep_min_of = malloc(nreps * sizeof(long));
    for (size_t r = 0; r < nreps; r++) {
      cur_rep = r; par_for(bmin_job, nmem);
      long mn = -1, mx = -1; size_t arg = 0;
      for (int t = 0; t < NTH; t++) { if (th_min[t] >= 0 && (mn < 0 || th_min[t] < mn)) { mn = th_min[t]; arg = th_arg[t]; } if (th_max[t] > mx) mx = th_max[t]; }
      size_t i = reps[r];
      printf("  orbit %zu: size %zu, (support %d, max mult %d, periods %d); B(i, j) over all j: min %ld (at j of type (%d, %d, %d)), max %ld\n", r, osz[i], supp[i], maxm[i], stab[i], mn, supp[arg], maxm[arg], stab[arg], mx);
      fflush(stdout);
      rep_min_of[r] = mn;
      if (gmin < 0 || mn < gmin) { gmin = mn; gi = i; gj = arg; }
    }
    printf("exact minimum over all pairs: B^diff = %ld of %zu thirds (pair types (%d, %d, %d) and (%d, %d, %d))\n", gmin, nmem - 2, supp[gi], maxm[gi], stab[gi], supp[gj], maxm[gj], stab[gj]);
    if (orbcheck) { // the same minimum for random first members that are not representatives (equivariance check)
      long cmin = -1; size_t save = reps[0];
      for (int c = 0; c < orbcheck; c++) {
        reps[0] = rnd() % nmem; cur_rep = 0; par_for(bmin_job, nmem);
        long mn = -1; for (int t = 0; t < NTH; t++) if (th_min[t] >= 0 && (mn < 0 || th_min[t] < mn)) mn = th_min[t];
        long expect = -1; for (size_t r = 0; r < nreps; r++) if (uf_find(reps[0]) == uf_find(r == 0 ? save : reps[r])) expect = rep_min_of[r];
        if (mn != expect) printf("  EQUIVARIANCE FAILS: member %zu has min %ld, its orbit representative %ld\n", reps[0], mn, expect);
        if (cmin < 0 || mn < cmin) cmin = mn;
      }
      reps[0] = save;
      printf("  check: %d random first members (not representatives), all j: min_j B equals that of the orbit representative in every case; smallest %ld\n", orbcheck, cmin);
    }
    long ph[MAXN + 1]; memset(ph, 0, sizeof ph); long bytype[2] = {0, 0};
    for (size_t l = 0; l < nmem; l++) { if (l == gi || l == gj) continue; int p = period_count(gi, gj, l); ph[p]++; if (p > 1) bytype[maxm[l] > 1]++; }
    printf("  for that pair, |Pi(xi_l)| : count ="); for (int p = 1; p <= n; p++) if (ph[p]) printf(" %d:%ld", p, ph[p]); printf("; periodic thirds that are simple sets %ld, with double points %ld\n", bytype[0], bytype[1]);
  }

  if (npairs) {
    size_t winv[64], nw = 0; for (size_t m = 0; m < nmem && nw < 8; m++) if (stab[m] == n / 8) winv[nw++] = m;
    long best = -1, worst = -1;
    for (size_t a = 0; a < nw; a++) for (size_t b = a + 1; b < nw; b++) { long bb = B_of_pair(winv[a], winv[b]); if (best < 0 || bb < best) best = bb; if (bb > worst) worst = bb; }
    printf("pairs among %zu W-invariant members: B(i, j) between %ld and %ld of %zu thirds\n", nw, best, worst, nmem - 2);
    if (nw >= 2) { long ph[MAXN + 1]; memset(ph, 0, sizeof ph); for (size_t l = 0; l < nmem; l++) if (l != winv[0] && l != winv[1]) ph[period_count(winv[0], winv[1], l)]++;
      printf("  first such pair, |Pi(xi_l)| : count ="); for (int p = 1; p <= n; p++) if (ph[p]) printf(" %d:%ld", p, ph[p]); printf("\n"); }
    long mn = -1, mx = -1; double sumfrac = 0;
    for (int p = 0; p < npairs; p++) { size_t i = rnd() % nmem, j = rnd() % nmem; if (i == j) { p--; continue; } long bb = B_of_pair(i, j); if (mn < 0 || bb < mn) mn = bb; if (bb > mx) mx = bb; sumfrac += 1.0 - (double)bb / (nmem - 2); }
    if (npairs > 0) printf("%d random pairs: B(i, j) min %ld, max %ld; mean fraction of thirds with a period %.5f\n", npairs, mn, mx, sumfrac / npairs);
  }

  if (nprim) {
    size_t bestsz = 0; size_t *best = malloc(nmem * sizeof(size_t));
    for (int run = 0; run < nprim; run++) {
      size_t *perm = malloc(nmem * sizeof(size_t)), *ch = malloc(nmem * sizeof(size_t)), nc = 0;
      for (size_t i = 0; i < nmem; i++) perm[i] = i;
      for (size_t i = nmem - 1; i > 0; i--) { size_t j = rnd() % (i + 1); size_t t = perm[i]; perm[i] = perm[j]; perm[j] = t; }
      for (size_t p = 0; p < nmem; p++) {
        size_t l = perm[p]; int ok = 1;
        for (size_t a = 0; a < nc && ok; a++) for (size_t b = a + 1; b < nc && ok; b++) if (has_period(ch[a], ch[b], l)) ok = 0;
        if (ok) ch[nc++] = l;
      }
      long types[3] = {0, 0, 0}; for (size_t a = 0; a < nc; a++) types[maxm[ch[a]] > 1 ? 2 : (stab[ch[a]] == n / 8 ? 0 : 1)]++;
      printf("greedy primitive sublist, run %d: %zu members (W-invariant %ld, other simple %ld, with double points %ld)\n", run, nc, types[0], types[1], types[2]); fflush(stdout);
      if (nc > bestsz) { bestsz = nc; memcpy(best, ch, nc * sizeof(size_t)); }
      free(perm); free(ch);
    }
    // re-verify the best one in full
    long viol = 0; for (size_t a = 0; a < bestsz; a++) for (size_t b = a + 1; b < bestsz; b++) for (size_t c = b + 1; c < bestsz; c++) if (period_count(best[a], best[b], best[c]) > 1) viol++;
    printf("largest primitive sublist found: %zu members (re-check: %ld periodic triples); generalized Singleton bound for k = %d, T = %d: %d members\n", bestsz, viol, n / 2 + 1, T, (n - (n / 2 + 1) - 1) / (T - (n / 2 + 1)));
  }

  if (do_rank) {
    int len = n / 2 + 1, rank = 0, rank_simple = 0; u64 (*bas)[MAXN] = malloc((size_t)len * sizeof *bas); int *pv = malloc(len * sizeof(int));
    u64 P0[MAXN + 1];
    for (int pass = 0; pass < 2; pass++) { // pass 0: members without double points only, pass 1: all
      rank = 0;
      for (size_t m = 0; m < nmem; m++) {
        if (pass == 0 && maxm[m] > 1) continue;
        u64 P[MAXN + 1]; memset(P, 0, sizeof P); P[0] = 1; int d = 0;
        for (int x = 0; x < n; x++) for (int e = 0; e < mem[m].c[x]; e++) { for (int j = d + 1; j >= 1; j--) P[j] = P[j - 1] ^ gmul(P[j], pts[x]); P[0] = gmul(P[0], pts[x]); d++; }
        if (m == 0) { memcpy(P0, P, sizeof P0); if (pass == 1 || maxm[0] <= 1) continue; }
        u64 v[MAXN]; for (int j = 0; j < len; j++) v[j] = P[j] ^ P0[j];
        for (int j = len; j <= MASS; j++) if (P[j] != P0[j]) { printf("degree of a difference exceeds n/2!\n"); return 1; }
        for (int b = 0; b < rank; b++) if (v[pv[b]]) { u64 f = v[pv[b]]; for (int j = 0; j <= pv[b]; j++) v[j] ^= gmul(f, bas[b][j]); }
        int top = len - 1; while (top >= 0 && !v[top]) top--;
        if (top < 0) continue;
        u64 iv = ginv(v[top]); for (int j = 0; j <= top; j++) bas[rank][j] = gmul(v[j], iv); for (int j = top + 1; j < len; j++) bas[rank][j] = 0;
        // keep the basis reduced enough: eliminate against later use only (pivots distinct by construction)
        pv[rank++] = top;
        if (rank == len) break;
      }
      if (pass == 0) rank_simple = rank;
    }
    printf("affine rank over GF(2^64): members without double points %d, whole list %d (polynomials of degree <= %d: at most %d)\n", rank_simple, rank, n / 2, len);
  }
  return 0;
}
