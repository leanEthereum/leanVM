// 44_n32: Conjecture P of note 17 on a generic F_2-subspace, exhaustive for one degree, with a full symmetry reduction.
//
//   cc -O2 -o 44_n32 44_n32.c
//   ./44_n32 N delta part parts [seed]
//
// Every configuration (R0, R1, R2) of pairwise disjoint subsets of D = F_2^N (N = 4 or 5) with |R0| >= |R1| >= |R2|,
// |R0| <= delta, sum = 2 delta + 2, is tested up to the affine group: R2 runs over representatives of the orbits of
// AGL(N, 2) on |R2|-subsets, R1 over representatives of the orbits of (a subgroup H of) the stabilizer of R2 on the
// |R1|-subsets of the complement, R0 over all subsets of the rest. H is generated by random Schreier generators of the
// stabilizer. If H is smaller than the stabilizer there are more representatives, never fewer: coverage does not
// depend on H. The weighted totals (orbit sizes) are printed and must equal the number of configurations.
//
// Test: with y in R2, w_y = 1/(Z_{R1}(y) Z_{R2}'(y)), c_y = w_y Z_{R0}(y), S_m = sum_y c_y y^m, the configuration has a
// solution (u0 + u1 + u2 = 0, deg <= delta, Z_{Ri} | ui) iff the t x t Hankel matrix (S_{i+j}), t = delta - |R0| + 1,
// is singular (note 26 section 6.1). A singular configuration is analysed as in 26_search.c: reduced xi, deg, nu, |Pi|.
// D is the span of N random elements of GF(2^64); nonsingular there implies nonsingular for the generic subspace.
#include "02_gf.h"
#define MAXP 64
#define MAXD 48
static int NN, n;
static u64 pts[MAXP];
static u64 rs = 88172645463325252ull;
static inline u64 rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static void init_pts(int N, u64 seed) {
  NN = N; n = 1 << N; if (seed) rs = seed * 0x9E3779B97F4A7C15ull + 12345;
  for (int i = 0; i < 20; i++) rnd();
  u64 b[8]; for (int i = 0; i < N; i++) b[i] = rnd();
  for (int x = 0; x < n; x++) { u64 v = 0; for (int i = 0; i < N; i++) if (x >> i & 1) v ^= b[i]; pts[x] = v; }
}
static int det_zero(u64 M[][8], int t) {
  for (int c = 0; c < t; c++) {
    int p = -1; for (int i = c; i < t; i++) if (M[i][c]) { p = i; break; }
    if (p < 0) return 1;
    if (p != c) for (int j = c; j < t; j++) { u64 x = M[p][j]; M[p][j] = M[c][j]; M[c][j] = x; }
    u64 piv = M[c][c];
    for (int i = c + 1; i < t; i++) { u64 f = M[i][c]; for (int j = c + 1; j < t; j++) M[i][j] = gmul(M[i][j], piv) ^ gmul(f, M[c][j]); }
  }
  return 0;
}

// ---- analysis of a singular configuration (from 26_search.c) ----
static int pdeg(const u64 *a, int d) { while (d >= 0 && !a[d]) d--; return d; }
static u64 peval(const u64 *a, int d, u64 x) { u64 v = 0; for (int i = d; i >= 0; i--) v = gmul(v, x) ^ a[i]; return v; }
static int pmod(u64 *a, int da, const u64 *b, int db) {
  u64 inv = ginv(b[db]);
  for (int i = da; i >= db; i--) if (a[i]) { u64 f = gmul(a[i], inv); for (int j = 0; j <= db; j++) a[i - db + j] ^= gmul(f, b[j]); }
  return pdeg(a, db - 1);
}
static int pgcd(const u64 *a, int da, const u64 *b, int db, u64 *g) {
  u64 x[MAXD + 2], y[MAXD + 2], tmp[MAXD + 2]; memcpy(x, a, (da + 1) * 8); memcpy(y, b, (db + 1) * 8);
  while (db >= 0) { int dr = pmod(x, da, y, db); memcpy(tmp, x, (dr + 1) * 8); memcpy(x, y, (db + 1) * 8); da = db; memcpy(y, tmp, (dr + 1) * 8); db = dr; }
  memcpy(g, x, (da + 1) * 8); return da;
}
static int pdivexact(const u64 *a, int da, const u64 *b, int db, u64 *q) {
  u64 x[MAXD + 2]; memcpy(x, a, (da + 1) * 8); u64 inv = ginv(b[db]);
  for (int i = da; i >= db; i--) { u64 f = gmul(x[i], inv); q[i - db] = f; if (f) for (int j = 0; j <= db; j++) x[i - db + j] ^= gmul(f, b[j]); }
  return da - db;
}
typedef struct { int deg, nu, npi, dimV, degenerate; } Info;
static Info analyse(const int *A[3], const int r[3], int delta) {
  Info inf = {0, 0, 0, 0, 0};
  int rows = 0, own[MAXD + 4], sh[MAXD + 4]; static u64 M[MAXD + 4][MAXD + 2], C[MAXD + 4][MAXD + 4];
  u64 Z[3][MAXD + 2];
  for (int i = 0; i < 3; i++) {
    memset(Z[i], 0, sizeof Z[i]); Z[i][0] = 1; int d = 0;
    for (int p = 0; p < r[i]; p++) { u64 v = pts[A[i][p]]; for (int j = d + 1; j >= 1; j--) Z[i][j] = Z[i][j - 1] ^ gmul(Z[i][j], v); Z[i][0] = gmul(Z[i][0], v); d++; }
    for (int j = 0; j <= delta - r[i]; j++) { own[rows] = i; sh[rows] = j; for (int c = 0; c <= delta; c++) M[rows][c] = (c >= j && c - j <= r[i]) ? Z[i][c - j] : 0; rows++; }
  }
  for (int i = 0; i < rows; i++) for (int j = 0; j < rows; j++) C[i][j] = (i == j);
  int used[MAXD + 4] = {0};
  for (int c = 0; c <= delta; c++) {
    int p = -1; for (int i = 0; i < rows; i++) if (!used[i] && M[i][c]) { p = i; break; }
    if (p < 0) continue; used[p] = 1; u64 inv = ginv(M[p][c]);
    for (int i = 0; i < rows; i++) if (i != p && M[i][c]) { u64 f = gmul(M[i][c], inv); for (int j = 0; j <= delta; j++) M[i][j] ^= gmul(f, M[p][j]); for (int j = 0; j < rows; j++) C[i][j] ^= gmul(f, C[p][j]); }
  }
  u64 h[3][MAXD + 2]; memset(h, 0, sizeof h);
  for (int i = 0; i < rows; i++) if (!used[i]) { inf.dimV++; u64 w = rnd() | 1; for (int j = 0; j < rows; j++) h[own[j]][sh[j]] ^= gmul(w, C[i][j]); }
  if (!inf.dimV) return inf;
  u64 u[3][MAXD + 2]; int du[3];
  for (int i = 0; i < 3; i++) { memset(u[i], 0, sizeof u[i]); for (int a = 0; a <= delta - r[i]; a++) if (h[i][a]) for (int b = 0; b <= r[i]; b++) u[i][a + b] ^= gmul(h[i][a], Z[i][b]); du[i] = pdeg(u[i], delta); }
  if (du[0] < 0 || du[1] < 0 || du[2] < 0) { inf.degenerate = 1; return inf; }
  u64 g[MAXD + 2], a[MAXD + 2], b[MAXD + 2], c[MAXD + 2]; int dg = pgcd(u[0], du[0], u[1], du[1], g);
  int da = pdivexact(u[0], du[0], g, dg, a), db = pdivexact(u[1], du[1], g, dg, b); int dm = da > db ? da : db;
  for (int i = 0; i <= dm; i++) c[i] = (i <= da ? a[i] : 0) ^ (i <= db ? b[i] : 0);
  int dc = pdeg(c, dm); inf.deg = dm;
  for (int p = 0; p < n; p++) if (!peval(a, da, pts[p]) || !peval(b, db, pts[p]) || !peval(c, dc, pts[p])) inf.nu++;
  for (int s = 0; s < n; s++) { int ok = 1; for (int tr = 0; tr < 2 * dm + 3 && ok; tr++) { u64 yv = rnd(); if (gmul(peval(a, da, yv ^ pts[s]), peval(b, db, yv)) != gmul(peval(a, da, yv), peval(b, db, yv ^ pts[s]))) ok = 0; } inf.npi += ok; }
  return inf;
}
#define HN 40
static long hist[HN][3 * HN][HN]; static long nviol, nsing, ntot, ndegen; static double wtot, wsing;
static void record(unsigned m0, unsigned m1, unsigned m2, int delta, double wgt) {
  int l[3][32]; int r[3] = {0, 0, 0}; unsigned mk[3] = {m0, m1, m2};
  for (int i = 0; i < 3; i++) for (int p = 0; p < n; p++) if (mk[i] >> p & 1) l[i][r[i]++] = p;
  const int *A[3] = {l[0], l[1], l[2]};
  Info f = analyse(A, r, delta); nsing++; wsing += wgt;
  if (f.degenerate || !f.dimV) { ndegen++; printf("DEGENERATE or no solution found: %08x %08x %08x\n", m0, m1, m2); return; }
  if (f.deg < HN && f.npi < HN) hist[f.deg][f.nu][f.npi]++;
  if (f.nu > 2 * f.deg + f.npi) { nviol++; printf("VIOLATION delta=%d deg=%d nu=%d |Pi|=%d sets %08x %08x %08x\n", delta, f.deg, f.nu, f.npi, m0, m1, m2); fflush(stdout); }
}

// ---- affine maps of F_2^N as tables ----
typedef struct { unsigned char t[32]; } Aff;
static Aff aff_mul(const Aff *g, const Aff *h) { Aff r; for (int x = 0; x < n; x++) r.t[x] = g->t[h->t[x]]; return r; } // g after h
static Aff aff_inv(const Aff *g) { Aff r; for (int x = 0; x < n; x++) r.t[g->t[x]] = (unsigned char)x; return r; }
static unsigned aff_pack(const Aff *g) { unsigned p = g->t[0]; for (int i = 0; i < NN; i++) p |= (unsigned)g->t[1 << i] << (5 * (i + 1)); return p; }
static Aff aff_unpack(unsigned p) { Aff r; int c = p & 31; int im[5]; for (int i = 0; i < NN; i++) im[i] = ((p >> (5 * (i + 1))) & 31) ^ c;
  for (int x = 0; x < n; x++) { int v = c; for (int i = 0; i < NN; i++) if (x >> i & 1) v ^= im[i]; r.t[x] = (unsigned char)v; } return r; }
static inline unsigned aff_set(const Aff *g, unsigned S) { unsigned r = 0; while (S) { int x = __builtin_ctz(S); S &= S - 1; r |= 1u << g->t[x]; } return r; }
static int aff_is_id(const Aff *g) { for (int x = 0; x < n; x++) if (g->t[x] != x) return 0; return 1; }

static double binom[40][40];
static long cbin[40][40];
static void init_binom(void) { for (int i = 0; i < 40; i++) { cbin[i][0] = 1; binom[i][0] = 1; for (int j = 1; j <= i; j++) { cbin[i][j] = cbin[i - 1][j - 1] + (j <= i - 1 ? cbin[i - 1][j] : 0); binom[i][j] = (double)cbin[i][j]; } } }
// rank of a k-subset given as a mask of positions 0..m-1 (combinatorial number system)
static inline long rank_mask(unsigned S) { long r = 0; int i = 1; while (S) { int x = __builtin_ctz(S); S &= S - 1; r += cbin[x][i]; i++; } return r; }
static inline unsigned next_comb(unsigned x) { unsigned c = x & -x, r = x + c; return (((r ^ x) >> 2) / c) | r; }

// ---- stage 1: orbits of k-subsets of D under AGL(N,2), with Schreier generators of the stabilizer ----
#define MAXGEN 14
typedef struct { unsigned A; double orb; int ng; Aff gen[MAXGEN]; } RepA;
static Aff Ggen[3];
static void init_G(void) {
  for (int x = 0; x < n; x++) { Ggen[0].t[x] = (unsigned char)(x ^ 1); Ggen[1].t[x] = (unsigned char)(((x << 1) | (x >> (NN - 1))) & (n - 1)); Ggen[2].t[x] = (unsigned char)(x ^ ((x & 1) << 1)); }
}
static int stage1(int k, RepA *out, int maxout) {
  long tot = cbin[n][k]; unsigned char *vis = calloc(tot, 1); unsigned *tr = malloc(tot * sizeof(unsigned));
  unsigned *stack = malloc(tot * sizeof(unsigned)); int cnt = 0;
  unsigned S0 = (k == 32) ? ~0u : ((1u << k) - 1); unsigned lim = (n == 32) ? 0 : (1u << n);
  for (unsigned S = S0;; ) {
    long r = rank_mask(S);
    if (!vis[r]) {
      if (cnt >= maxout) { fprintf(stderr, "too many A reps\n"); exit(1); }
      RepA *R = &out[cnt++]; R->A = S; R->ng = 0; long orb = 0; long sp = 0;
      Aff id; for (int x = 0; x < n; x++) id.t[x] = (unsigned char)x;
      vis[r] = 1; tr[r] = aff_pack(&id); stack[sp++] = S; long seen = 0;
      while (sp) {
        unsigned T = stack[--sp]; orb++; long rT = rank_mask(T); Aff tT = aff_unpack(tr[rT]);
        for (int g = 0; g < 3; g++) {
          unsigned U = aff_set(&Ggen[g], T); long rU = rank_mask(U);
          if (!vis[rU]) { vis[rU] = 1; Aff c = aff_mul(&Ggen[g], &tT); tr[rU] = aff_pack(&c); stack[sp++] = U; }
          else {
            seen++;
            // Schreier generator tU^{-1} g tT, sampled
            if (R->ng < MAXGEN ? (rnd() % 7 == 0) : (rnd() % (seen / 3 + 1) < 2)) {
              Aff tU = aff_unpack(tr[rU]); Aff iu = aff_inv(&tU); Aff c = aff_mul(&Ggen[g], &tT); Aff s = aff_mul(&iu, &c);
              if (!aff_is_id(&s)) { if (aff_set(&s, R->A) != R->A) { fprintf(stderr, "Schreier generator does not fix A\n"); exit(1); }
                int dup = 0; for (int i = 0; i < R->ng; i++) if (!memcmp(&R->gen[i], &s, sizeof(Aff))) dup = 1;
                if (!dup) { if (R->ng < MAXGEN) R->gen[R->ng++] = s; else R->gen[rnd() % MAXGEN] = s; } }
            }
          }
        }
      }
      R->orb = (double)orb;
    }
    if (k == 0) break;
    unsigned nx = next_comb(S); if (lim ? nx >= lim : nx < S) break; S = nx;
  }
  free(vis); free(tr); free(stack); return cnt;
}

// ---- stage 2: orbits of r1-subsets of the complement of A under H = <gen> ----
typedef struct { unsigned B; double orb; } RepB;
static int pos_of[32], pt_of[32];
static inline unsigned to_pos(unsigned S) { unsigned r = 0; while (S) { int x = __builtin_ctz(S); S &= S - 1; r |= 1u << pos_of[x]; } return r; }
static long stage2(const RepA *R, int r1, RepB **outp) {
  int m = 0; for (int x = 0; x < n; x++) if (!(R->A >> x & 1)) { pos_of[x] = m; pt_of[m] = x; m++; }
  long tot = cbin[m][r1]; unsigned char *vis = calloc(tot, 1); long cap = 1024, cnt = 0; RepB *out = malloc(cap * sizeof(RepB));
  long scap = 1 << 16, sp; unsigned *stack = malloc(scap * sizeof(unsigned));
  // byte tables of the generators acting on masks of D
  static unsigned tab[MAXGEN][4][256];
  for (int g = 0; g < R->ng; g++) for (int b = 0; b < 4; b++) for (int v = 0; v < 256; v++) { unsigned im = 0; for (int i = 0; i < 8; i++) if ((v >> i & 1) && 8 * b + i < n) im |= 1u << R->gen[g].t[8 * b + i]; tab[g][b][v] = im; }
  unsigned P0 = (1u << r1) - 1; // positions
  for (unsigned P = P0;; ) {
    long r = rank_mask(P);
    if (!vis[r]) {
      unsigned B = 0; { unsigned q = P; while (q) { int i = __builtin_ctz(q); q &= q - 1; B |= 1u << pt_of[i]; } }
      if (cnt == cap) { cap *= 2; out = realloc(out, cap * sizeof(RepB)); }
      long orb = 0; sp = 0; vis[r] = 1; stack[sp++] = B;
      while (sp) {
        unsigned T = stack[--sp]; orb++;
        for (int g = 0; g < R->ng; g++) {
          unsigned U = tab[g][0][T & 255] | tab[g][1][(T >> 8) & 255] | tab[g][2][(T >> 16) & 255] | tab[g][3][T >> 24];
          long rU = rank_mask(to_pos(U));
          if (!vis[rU]) { vis[rU] = 1; if (sp == scap) { scap *= 2; stack = realloc(stack, scap * sizeof(unsigned)); } stack[sp++] = U; }
        }
      }
      out[cnt].B = B; out[cnt].orb = (double)orb; cnt++;
    }
    if (r1 == 0 || m == r1) break;
    unsigned nx = next_comb(P); if (nx >= (1u << m)) break; P = nx;
  }
  free(vis); free(stack); *outp = out; return cnt;
}

// ---- stage 3: all R0 in the rest ----
static int g_delta, g_k, g_r0, g_t, g_m; static unsigned g_A, g_B; static double g_w;
static u64 g_W[16][16], g_d[32][16], g_prod[20][16]; static int g_rest[32];
static inline void leaf(unsigned R0mask) {
  ntot++; const u64 *z = g_prod[g_r0]; int t = g_t, k = g_k;
  u64 S[16]; if (t > 8) { fprintf(stderr, "t > 8\n"); exit(1); }
  for (int mth = 0; mth <= 2 * (t - 1); mth++) { u64 s = 0; for (int i = 0; i < k; i++) s ^= gmul(g_W[mth][i], z[i]); S[mth] = s; }
  int zero;
  if (t == 1) zero = (S[0] == 0);
  else if (t == 2) zero = (gmul(S[0], S[2]) == gmul(S[1], S[1]));
  else { u64 M[8][8]; for (int i = 0; i < t; i++) for (int j = 0; j < t; j++) M[i][j] = S[i + j]; zero = det_zero(M, t); }
  if (zero) record(R0mask, g_B, g_A, g_delta, g_w);
}
static void dfs(int pos, int chosen, unsigned mask) {
  if (chosen == g_r0) { leaf(mask); return; }
  int need = g_r0 - chosen;
  for (int p = pos; p <= g_m - need; p++) {
    const u64 *d = g_d[p]; const u64 *z = g_prod[chosen]; u64 *zn = g_prod[chosen + 1];
    for (int i = 0; i < g_k; i++) zn[i] = gmul(z[i], d[i]);
    dfs(p + 1, chosen + 1, mask | 1u << g_rest[p]);
  }
}

int main(int argc, char **argv) {
  if (argc < 5) { fprintf(stderr, "usage: 44_n32 N delta part parts [seed]\n"); return 1; }
  int N = atoi(argv[1]), delta = atoi(argv[2]), part = atoi(argv[3]), parts = atoi(argv[4]); u64 seed = argc > 5 ? strtoull(argv[5], 0, 0) : 1;
  gf_init(64, 0x1b); init_pts(N, seed); init_binom(); init_G(); g_delta = delta;
  int nu = 2 * delta + 2; if (nu > n) { printf("2 delta + 2 > n\n"); return 0; }
  long job = 0; double total_expected = 0;
  static RepA repsA[4096];
  for (int k = 2; 3 * k <= nu; k++) {
    int have = 0, nA = 0;
    for (int r1 = k; r1 <= delta; r1++) {
      int r0 = nu - k - r1; if (r0 < r1 || r0 > delta) continue;
      if (!have) { nA = stage1(k, repsA, 4096); have = 1; double s = 0; for (int i = 0; i < nA; i++) s += repsA[i].orb; printf("# |R2| = %d: %d orbits of AGL(%d,2), sizes sum %.0f (binomial %.0f)\n", k, nA, N, s, binom[n][k]); fflush(stdout); }
      double sym = (r0 == r1 && r1 == k) ? 6 : (r0 == r1 || r1 == k) ? 2 : 1;
      // number of ordered-by-size configurations of this shape
      double expect = binom[n][k] * binom[n - k][r1] * binom[n - k - r1][r0];
      total_expected += expect / sym;
      long nB_all = 0; double wsum = 0; long before = ntot, sbefore = nsing;
      for (int ia = 0; ia < nA; ia++) {
        RepB *rb; long nB = stage2(&repsA[ia], r1, &rb); nB_all += nB;
        for (long ib = 0; ib < nB; ib++) {
          double w = repsA[ia].orb * rb[ib].orb; wsum += w * binom[n - k - r1][r0];
          if (job++ % parts != part) continue;
          g_A = repsA[ia].A; g_B = rb[ib].B; g_k = k; g_r0 = r0; g_t = delta - r0 + 1; g_w = w / sym; g_m = 0;
          for (int x = 0; x < n; x++) if (!((g_A | g_B) >> x & 1)) g_rest[g_m++] = x;
          int ys[12], q = 0; for (int x = 0; x < n; x++) if (g_A >> x & 1) ys[q++] = x;
          for (int i = 0; i < k; i++) {
            u64 yy = pts[ys[i]], b = 1;
            for (int x = 0; x < n; x++) if (g_B >> x & 1) b = gmul(b, yy ^ pts[x]);
            for (int j = 0; j < k; j++) if (j != i) b = gmul(b, yy ^ pts[ys[j]]);
            u64 w0 = ginv(b);
            for (int mth = 0; mth <= 2 * (g_t - 1); mth++) { g_W[mth][i] = w0; w0 = gmul(w0, yy); }
            for (int p = 0; p < g_m; p++) g_d[p][i] = yy ^ pts[g_rest[p]];
            g_prod[0][i] = 1;
          }
          long b0 = ntot; dfs(0, 0, 0); wtot += g_w * (double)(ntot - b0);
        }
        free(rb);
      }
      printf("# sizes (%d,%d,%d): %ld orbits of (R2,R1); weighted configurations %.0f, expected %.0f%s; this part tested %ld, singular %ld\n", r0, r1, k, nB_all, wsum, expect, wsum == expect ? "" : "  MISMATCH", ntot - before, nsing - sbefore); fflush(stdout);
    }
  }
  printf("N=%d delta=%d part %d/%d seed %llu: tested %ld configurations (weighted, unordered: %.0f of %.0f), singular %ld (weighted %.0f, degenerate %ld), violations of P %ld\n",
         N, delta, part, parts, (unsigned long long)seed, ntot, wtot, total_expected, nsing, wsing, ndegen, nviol);
  for (int d = 0; d < HN; d++) for (int v = 0; v < 3 * HN; v++) for (int p = 0; p < HN; p++) if (hist[d][v][p]) printf("  (deg, nu, |Pi|) = (%d, %d, %d): %ld\n", d, v, p, hist[d][v][p]);
  return 0;
}
