#!/usr/bin/env python3
"""Tests `pr-report.py` on a throwaway repository: a change that plants one violation per section, which
the report must list, and a clean change, which it must not.

  python3 -I formal/tools/test_pr_report.py
"""
import os
import subprocess
import sys
import tempfile

TOOL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "pr-report.py")
EM, EN, RLO = "—", "–", "‮"
ENV = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", GIT_AUTHOR_NAME="t",
           GIT_AUTHOR_EMAIL="t@t", GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@t")
ENV.pop("GITHUB_STEP_SUMMARY", None)

BASE = {
    "formal/Statement/Theorems.lean": "structure Theorems : Prop where\n  /-- First. -/\n  first : True\n\nend\n",
    "formal/Statement/Foo.lean": ("/-- Kept. -/\ntheorem keep : True := trivial\n\ndef gone := 1\n\n"
                                  "theorem shape (n : Nat) : n = n := rfl\n"),
    "formal/Statement/Lemmas/L.lean": "theorem l : True := trivial\n",
    "formal/statement.tex": "The statement.\n",
    "formal/proj/Proj.lean": "import Proj.A\n",
    "formal/proj/Proj/A.lean": "theorem a : True := by\n  trivial\n",
    "formal/proj/tests/T.lean": "example : True := trivial\n",
    "README.md": "# readme\n",
}
BIG = "theorem big : True := by\n" + "  skip\n" * 120 + "  trivial\n" + "".join(
    f"theorem t{i} : True := trivial\n" for i in range(1500))
PLANTED = {
    "formal/Statement/Foo.lean": ("/-- Kept, its docstring changed. -/\ntheorem keep : True := trivial\n\n"
                                  "theorem shape (n : Nat) (h : 0 < n) : n = n := rfl\n\n"
                                  "theorem fresh : True := trivial\n"),
    "formal/Statement/Theorems.lean": ("structure Theorems : Prop where\n  /-- First. -/\n  first : True\n"
                                       "  /-- Second. -/\n  second : True\n\nend\n"),
    "formal/proj/Proj.lean": "import Proj.A\n#print axioms a\n",
    "formal/proj/tests/T.lean": "example : True := trivial\n#eval 1\n",
    "formal/proj/Proj/A.lean": (
        "set_option maxHeartbeats 400000 in\ntheorem a : True := by\n  trivial\n\n#eval 1 + 1\n\n"
        "#guard_msgs in\n#check a\n\n-- theorem old (n : Nat) : n = n := rfl\n\n/-\ndef hidden := 2\n-/\n\n"
        "-- TODO prove more\n-- the proof used to be slow\n-- a " + EM + " b\n"),
    "formal/proj/Proj/Big.lean": BIG,
    "formal/proj/Proj/Gen.lean": "/- Generated by `gen`; do not edit. -/\n" + BIG,
    "formal/notes.md": "A note " + EN + " here.\n",
    ".claude/skills/x/SKILL.md": "Skill " + EM + " text.\n",
    "README.md": "# readme\n\nRoot " + EM + " prose.\n",
    "crates/x.rs": "let s = \"" + RLO + "\";\n",
}
EXPECTED = [
    "This PR changes what is proved.",
    "`formal/statement.tex` did not change with it.",
    "theorem `fresh` added", "def `gone` removed", "theorem `shape` changed", "theorem `keep` changed",
    "field `Theorems.second` added",
    "+1 / -0 lines.", "Proj/A.lean:1`: budget or suppression: `set_option maxHeartbeats 400000 in`",
    "Proj/A.lean:5`: debug command: `#eval 1 + 1`",
    "Proj/A.lean:10`: commented-out declaration", "Proj/A.lean:13`: commented-out declaration",
    "Proj/A.lean:16`: leftover marker",
    "Proj/A.lean:17`: history or planning word `used to`", "Proj/A.lean:18`: em-dash or en-dash in a comment",
    "Proj/Big.lean:1`: 1622 lines (over 1500)", "Proj/Big.lean:1`: theorem `big` is 122 lines (over 100)",
    "formal/notes.md:1`: em-dash or en-dash", ".claude/skills/x/SKILL.md:1`: em-dash or en-dash",
    "`README.md:3`: em-dash or en-dash", "crates/x.rs:1`: bidirectional or invisible character U+202E",
]
NOT_EXPECTED = ["Proj.lean:2", "tests/T.lean", "A.lean:8", "Gen.lean", "Lemmas/L.lean"]
CLEAN = {"formal/proj/Proj/A.lean": "theorem a : True := by\n  exact trivial\n", "README.md": "# readme\n\nMore.\n"}
CLEAN_EXPECTED = ["No file under `formal/Statement/` changed.", "None added or removed.", "None added.",
                  "No touched file or declaration over the thresholds.", "Nothing found."]


def run(cwd, *args, env=ENV):
    return subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8")


def commit(repo, files, message):
    for path, text in files.items():
        os.makedirs(os.path.join(repo, os.path.dirname(path)), exist_ok=True)
        with open(os.path.join(repo, path), "w", encoding="utf-8") as f:
            f.write(text)
    run(repo, "git", "add", "-A")
    run(repo, "git", "commit", "-qm", message)
    return run(repo, "git", "rev-parse", "HEAD").stdout.strip()


def main():
    failures = []
    with tempfile.TemporaryDirectory() as repo:
        run(repo, "git", "init", "-q")
        base = commit(repo, BASE, "base")
        commit(repo, PLANTED, "planted")
        summary = os.path.join(repo, ".git", "summary.md")
        r = run(os.path.join(repo, "formal", "proj"), sys.executable, "-I", TOOL, "--base", base, "--github",
                env=dict(ENV, GITHUB_STEP_SUMMARY=summary))
        out = r.stdout
        if r.returncode:
            failures.append(f"planted: exit {r.returncode}: {r.stderr}")
        failures += [f"planted: missing {e!r}" for e in EXPECTED if e not in out]
        failures += [f"planted: unexpected {e!r}" for e in NOT_EXPECTED if e in out]
        if out.count("::warning file=") < len(EXPECTED) - 3:
            failures.append("planted: too few ::warning annotations")
        if not os.path.exists(summary) or "# formal/ report" not in open(summary, encoding="utf-8").read():
            failures.append("planted: no step summary")

        run(repo, "git", "checkout", "-q", base)
        commit(repo, CLEAN, "clean")
        r = run(repo, sys.executable, "-I", TOOL, "--base", base, "--github")
        failures += [f"clean: missing {e!r}" for e in CLEAN_EXPECTED if e not in r.stdout]
        if r.returncode or "::warning" in r.stdout or "`: " in r.stdout:
            failures.append(f"clean: reported a finding or failed (exit {r.returncode}):\n{r.stdout}{r.stderr}")

        for args in (["--base", "no-such-ref"], ["--frobnicate"]):
            r = run(repo, sys.executable, "-I", TOOL, *args)
            if r.returncode != 2:
                failures.append(f"{args}: exit {r.returncode}, not 2")
    for f in failures:
        print("FAIL", f)
    if failures:
        print(out)
        return 1
    print(f"pr-report: {len(EXPECTED)} planted findings reported, none on a clean change, usage errors exit 2")
    return 0


if __name__ == "__main__":
    sys.exit(main())
