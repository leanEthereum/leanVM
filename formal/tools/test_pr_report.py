def run(cwd, *args, env=ENV):
    return subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8")


def commit(repo, files, message):
    for path, text in files.items():
        full = os.path.join(repo, path)
        if text is None:
            os.remove(full)
            continue
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)
    run(repo, "git", "add", "-A")
    run(repo, "git", "commit", "-qm", message)
    return run(repo, "git", "rev-parse", "HEAD").stdout.strip()


def main():
    failures, out = [], ""
    with tempfile.TemporaryDirectory() as repo:
        run(repo, "git", "init", "-q")
        run(repo, "git", "config", "diff.noprefix", "true")
        base = commit(repo, BASE, "base")
        summary = os.path.join(repo, ".git", "summary.md")
        for name, files, expected, not_expected in SCENARIOS:
            run(repo, "git", "checkout", "-q", base)
            commit(repo, files, name)
            r = run(os.path.join(repo, "formal"), sys.executable, "-I", TOOL, "--base", base, "--github",
                    env=dict(ENV, GITHUB_STEP_SUMMARY=summary))
            out = r.stdout
            if r.returncode:
                failures.append(f"{name}: exit {r.returncode}: {r.stderr}")
            failures += [f"{name}: missing {e!r}" for e in expected if e not in out]
            failures += [f"{name}: unexpected {e!r}" for e in not_expected if e in out]
            if out.count("::warning file=") < out.count("\n- `"):
                failures.append(f"{name}: fewer ::warning annotations than findings")
            if failures:
                break
        if not os.path.exists(summary) or "# formal/ report" not in open(summary, encoding="utf-8").read():
            failures.append("no step summary")
        for args in (["--base", "no-such-ref"], ["--frobnicate"]):
            r = run(repo, sys.executable, "-I", TOOL, *args)
            if r.returncode != 2:
                failures.append(f"{args}: exit {r.returncode}, not 2")
    for f in failures:
        print("FAIL", f)
    if failures:
        print(out)
        return 1
    print(f"pr-report: {sum(len(s[2]) for s in SCENARIOS)} expected lines in {len(SCENARIOS)} changes, "
          "usage errors exit 2")
    return 0


if __name__ == "__main__":
    sys.exit(main())
