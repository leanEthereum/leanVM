if __name__ == '__main__':
    lemmas = main()
    open(os.path.join(VT_LEAN, 'SharedT.lean'), 'w').write(
        HDR + '\n' + '\n\n'.join(lemmas) + '\n\nend\nend LeanVM.Guest.B1.Tables\n')
