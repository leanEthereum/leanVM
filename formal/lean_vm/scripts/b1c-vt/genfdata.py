# usage: python3 -I genfdata.py  (from this directory, after dump.py)
# Writes VtC/FDataD.lean, the data of VtC/FData.lean for the forms window: `vtAirD` (each table's weight block:
# position, `x`) and `vtFTags` (the window's statements evaluation does not settle, besides the
# reads of `fp_w`: evaluations (0, k), permutations (1, j), weight blocks (3, t)), from vt_ir.txt.
import re, os, textwrap
here = os.path.dirname(os.path.abspath(__file__))
import sys
sys.path.insert(0, here)
from vtanchor import WLO as LO, WHI as HI, CUR, GZN
FPW = 13
ir = {}
for line in open(os.path.join(here, 'vt_ir.txt')):
    k, _, s = line.partition(': ')
    if k == 'params': continue
    ir[int(k)] = s.strip().removesuffix(' ::')
def nums(s): return [int(x) for x in re.findall(r'\.n (\d+)', s)]
def auto(s):
    m = re.match(r'\.atom \(\.(\w+) ', s)
    if not m: return False
    op = m.group(1)
    if op in ('const', 'add', 'copy', 'hint'): return True
    if op == 'mul':
        d, x, y = nums(s)[:3]
        return x < d and y < d
    return False
air = []
for p in range(LO, HI):
    m = re.match(r'\.atom \(\.mul \(\.n %d\) \(\.n (\d+)\) \(\.n (2[8-9]|3[0-3])\)\)$' % GZN, ir[p])
    if m: air.append((p, int(m.group(1)), int(m.group(2)) - 28))
assert [a[2] for a in air] == list(range(6))
evs = {}  # cursor read position -> k
for p in range(LO, HI):
    m = re.match(r'\.atom \(\.load \(\.n \d+\) \(\.n %d\) (\d+)\)$' % CUR, ir[p])
    if m: evs[p] = int(m.group(1))
tags, p = [], LO
airAt = {a[0]: a[2] for a in air}
while p < HI:
    s = ir[p]
    if p in airAt:
        tags.append((3, airAt[p])); p += 5; continue
    if p in evs:
        tags.append((0, evs[p])); p += 1; continue
    if s.startswith('.atom (.keccak'):
        tags.append((1, sum(1 for t in tags if t[0] == 1))); p += 1; continue
    if auto(s) or re.match(r'\.atom \(\.load \(\.n \d+\) \(\.n %d\) \d+\)$' % FPW, s):
        p += 1; continue
    if s.startswith('.atom (.assertInK') and tags and tags[-1][0] == 0:
        p += 1; continue  # part of the evaluation's rest (vtEvRest)
    raise SystemExit(f'unexpected {p}: {s}')
assert sorted(t[1] for t in tags if t[0] == 0) == list(range(153))
f = os.path.join(here, '..', '..', 'LeanVM', 'Guest', 'B1', 'Tables', 'VtC', 'FDataD.lean')
air_text = '  [' + ', '.join(f'({a[0]}, {a[1]})' for a in air) + ']'
tags_text = textwrap.fill(', '.join(f'({a}, {b})' for a, b in tags), 96, initial_indent='    [',
                          subsequent_indent='    ') + ']'
open(f, 'w').write(f"""/-
  LeanVM.Guest.B1.Tables.VtC.FDataD

  The data of `VtC/FData.lean`, from `verify_tables`' body: `vtAirD`, each table's weight block (position, `x`),
  and `vtFTags`, the window's statements evaluation does not settle besides the reads of `fp_w`: evaluations
  `(0, k)`, permutations `(1, j)`, weight blocks `(3, t)`. Generated by `scripts/b1c-vt/genfdata.py`.
-/

module

namespace LeanVM.Guest.B1.Tables

@[expose] public section

/-- The tables' weight blocks: positions and first values. -/
def vtAirD : List (Nat × Nat) :=
{air_text}

/-- The window's statements to settle, in order. -/
def vtFTags : List (Nat × Nat) :=
{tags_text}

end

end LeanVM.Guest.B1.Tables
""")
