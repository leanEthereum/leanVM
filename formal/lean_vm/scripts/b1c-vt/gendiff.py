if __name__ == '__main__':
    out = [HDR, LIB]
    for t in range(6):
        P, Q, D = blocks(0, t), blocks(1, t), DT[t]
        assert len(P) == len(Q) == len(D) and all(len(p) == len(q) == len(d) for p, q, d in zip(P, Q, D))
        out.append(f'\n/-- Table {t}\'s pull blocks less their push twins\'. -/\n'
                   f'def vtDTerms{t} : List (List (List (List ℕ × ℕ))) :=\n  {lit(D)}\n')
    for t in range(6):
        out.append(f'\ntheorem vtPull{t} : vtPullOk vtBTerms0{t} vtBTerms1{t} vtDTerms{t} = true := by\n'
                   f'  decide +kernel\n')
    open(os.path.join(VT_LEAN, 'FormsDiff.lean'), 'w').write(''.join(out) + FTR)
