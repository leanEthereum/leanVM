"""Writing a generator's files, or checking them: shared by the generators of `scripts/core-mode/` and
`scripts/bridge-cert/`.

`sync(files, existing, check)`: `files` maps each path to its text; `existing` lists the paths the generator owns
that are on disk (a glob of what it writes). Writes each file whose text differs and removes each of `existing` not
among `files`, then any directory those removals left empty; under `check`, touches nothing. Returns the stale paths:
those written or removed, or, under `check`, that would be. `fail_if_stale(stale, check, root)` prints them, relative
to `root`, and exits 1 under `check` when there is one. `header(script)` gives the head of the Lean modules
`scripts/<script>` writes, `header(script)(mod, what)`.
"""
import os
import sys


def header(script):
    return lambda mod, what: (f'/-\n  {mod}\n\n  Generated by `scripts/{script}`; do not edit.\n  {what}\n-/\n\n'
                              'module\n\n')


def read(path):
    """The file's text, or `None` if there is none."""
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def sync(files, existing=(), check=False):
    stale = []
    for path, text in sorted(files.items()):
        if read(path) == text:
            continue
        stale.append(path)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as fh:
                fh.write(text)
    gone = sorted(set(existing) - set(files))
    stale += gone
    if not check:
        for path in gone:
            os.remove(path)
        for d in sorted({os.path.dirname(p) for p in gone}, key=len, reverse=True):
            while d and os.path.isdir(d) and not os.listdir(d):
                os.rmdir(d)
                d = os.path.dirname(d)
    return stale


def fail_if_stale(stale, check, root=None, limit=None):
    if not (check and stale):
        return
    for p in stale[:limit]:
        print('stale:', os.path.relpath(p, root) if root else p, file=sys.stderr)
    sys.exit(1)
