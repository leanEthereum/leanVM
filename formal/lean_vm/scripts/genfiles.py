"""Writing a generator's files, or checking them: shared by the generators of `scripts/core-mode/` and
`scripts/bridge-cert/`.

`sync(files, existing, check)`: `files` maps each path to its text; `existing` lists the paths the generator owns
that are on disk (a glob of what it writes). Writes each file whose text differs and removes each of `existing` not
among `files`, then any directory those removals left empty; under `check`, touches nothing. Returns the stale paths:
those written or removed, or, under `check`, that would be. `fail_if_stale(stale, check, root)` prints them, relative
to `root`, and exits 1 under `check` when there is one. `header(script)` gives the head of the Lean modules
`scripts/<script>` writes, `header(script)(mod, what)`. `merge(files, groups, head)` makes several of `files`' modules
one, each module's own import and fixed cost paid once.
"""
import os
import re
import sys

IMPORT = re.compile(r'^(?:public )?(?:meta )?import (?:all )?(\S+)$')


def header(script):
    return lambda mod, what: (f'/-\n  {mod}\n\n  Generated by `scripts/{script}`; do not edit.\n  {what}\n-/\n\n'
                              'module\n\n')


def split(text):
    """A module `header` wrote: its name, its head (up to `module`), its import lines and the rest."""
    head, rest = text.split('\nmodule\n\n', 1)
    lines = rest.split('\n')
    n = 0
    while n < len(lines) and IMPORT.match(lines[n]):
        n += 1
    return head.split('\n')[1].strip(), head + '\nmodule\n\n', lines[:n], '\n'.join(lines[n:])


def merge(files, groups, head):
    """`files` with the modules of each group made one: `groups` maps a path to `(mod, what, paths)`, the modules at
    `paths` (in `files`) merged into module `mod` at that path, headed `head(mod, what)` (with `what` `None`, as the
    member `mod` is), with their imports but each other, then their bodies in order. A module importing a merged one
    imports its group's module instead."""
    to = {split(files[p])[0]: mod for mod, _, ps in groups.values() for p in ps}
    gone = {p for _, _, ps in groups.values() for p in ps}

    def imports(lines, own=None):
        out = []
        for line in lines:
            m = IMPORT.match(line).group(1)
            if m in to:
                if to[m] == own:
                    continue
                line = line[:-len(m)] + to[m]
            if line not in out:
                out.append(line)
        return out

    out = {}
    for p, text in files.items():
        if p in gone:
            continue
        _, h, imps, body = split(text)
        new = imports(imps)
        out[p] = text if new == imps else h + '\n'.join(new) + '\n' + body
    for p, (mod, what, ps) in groups.items():
        parts = [split(files[q]) for q in ps]
        imps = imports([line for _, _, ii, _ in parts for line in ii], mod)
        h = head(mod, what) if what is not None else next(h for m, h, _, _ in parts if m == mod)
        out[p] = h + '\n'.join(sorted(imps)) + '\n' + '\n'.join(b for _, _, _, b in parts)
    return out


def read(path):
    """The file's text, or `None` if there is none."""
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def sync(files, existing=(), check=False):
    stale = []
    for path, text in sorted(files.items()):
        if read(path) == text:
            continue
        stale.append(path)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as fh:
                fh.write(text)
    gone = sorted(set(existing) - set(files))
    stale += gone
    if not check:
        for path in gone:
            os.remove(path)
        for d in sorted({os.path.dirname(p) for p in gone}, key=len, reverse=True):
            while d and os.path.isdir(d) and not os.listdir(d):
                os.rmdir(d)
                d = os.path.dirname(d)
    return stale


def fail_if_stale(stale, check, root=None, limit=None):
    if not (check and stale):
        return
    for p in stale[:limit]:
        print('stale:', os.path.relpath(p, root) if root else p, file=sys.stderr)
    sys.exit(1)
