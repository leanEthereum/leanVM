"""The core route's checks of each function on it (`route.py`): `Gen/<pack>/Core.lean`, its core data
(`CoreMode.CFun`: its frame walk, alignment context, heap certificate, core function, advice entry, powers and
promised cells) and the kernel's checks tying them to its mode certificate (`CoreMode.CoreOk`), hence its frame
interface (`Mode.FnSpecC`); `Gen/<pack>/Route.lean`, its core data the deployed guest's (`CoreMode.CfOk`).
Usage: python3 -I scripts/core-mode/core.py [--check]  (with `CORE_MODE_CACHE` as for `heap.py`)"""
import os, re, sys, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import route, heap  # noqa: E402

GUEST = route.GUEST
GEN = os.path.join(GUEST, 'CoreMode', 'Gen')
CHECK = '--check' in sys.argv
HEADER = """/-
  {mod}

  Generated by `scripts/core-mode/core.py`; do not edit.
  {what}
-/

module

"""


def index(pattern, files):
    """Each match's first group to the module (path under `LeanVM/`) whose text has it."""
    out = {}
    for f in files:
        mod = 'LeanVM.' + os.path.relpath(f, os.path.dirname(GUEST))[:-5].replace(os.sep, '.')
        for m in re.finditer(pattern, open(f, encoding='utf-8').read(), re.M):
            out[m.group(1)] = mod
    return out


def quote(mod):
    """A module name with `«»` around a pack or function component that needs it."""
    return '.'.join(('«%s»' % p) if (p[0].isdigit() or not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', p) or
                                     re.fullmatch(r'P\d+', p)) else p for p in mod.split('.'))


def frame_term(mod):
    """The frame walk's acceptance from its module: one check, or a long function's windows chained."""
    if '.FrameL' in mod:
        return '⟨by decide +kernel, by decide +kernel, frameAcc⟩'
    return 'CoreMode.frameAcc_of (by decide +kernel) frameOk'


def pair_mod(g, n):
    """The module of function `n`'s pairing in pack `g`: the pack's, or a long function's own (windows)."""
    if os.path.exists(os.path.join(GEN, g, n, 'Ok.lean')):
        return 'LeanVM.Guest.CoreMode.Gen.%s.%s.Ok' % (g, n)
    return 'LeanVM.Guest.CoreMode.Gen.%s.Pair' % g


def main():
    R = route.route_sub()
    packs = collections.defaultdict(list)
    po = heap.pack_of()
    for k in sorted(R):
        packs[po[k][0]].append(k)
    # in the order of the pack's `coreFns` (`scripts/mode-cert/gen.py`, the pack's functions in order)
    for p, ks in packs.items():
        mc = open(os.path.join(GUEST, 'Pack', p, 'ModeCert.lean'), encoding='utf-8').read()
        m = re.search(r'def coreFns : List CoreMode.CFun :=\s*\[(.*?)\]\n', mc, re.S)
        order = re.findall(r'Fn\.«([^»]+)»\.cfun', m.group(1)) if m else []
        assert sorted(order) == sorted(ks), (p, order, ks)
        packs[p] = order
    frames = index(r'^namespace LeanVM\.Guest\.Fn\.«([^»]+)»$', glob.glob(os.path.join(GUEST, 'CoreMode', 'Pack', '*', 'Frame*.lean')))
    codes = index(r'^kernel_rfl code(\d+) :', glob.glob(os.path.join(GUEST, 'Checked', 'Link*.lean')))
    tabs = index(r'^kernel_rfl tab(\d+) :', glob.glob(os.path.join(GUEST, 'Bridge', 'ProgAl', 'Link*.lean')))
    files = {}
    for p, ks in sorted(packs.items()):
        imps = {'LeanVM.Guest.Mode.InvCert', 'LeanVM.Guest.CoreMode.Gen.«%s».Ok' % p, 'LeanVM.Guest.CoreMode.Small',
                'LeanVM.Guest.Pack.«%s».ModeC' % p, 'LeanVM.Guest.SoundFacts', 'LeanVM.Guest.Exec'}
        body = []
        for k in ks:
            j = R[k]['j']
            imps.add(quote(frames[k])); imps.add(quote(codes[str(j)]))
            imps.add(quote(pair_mod(p, k)))
            K = '⟨modeEnv, modeFun, code.chunks.flatten⟩'
            body.append(
                f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\nopen LeanVM.Guest\n\n@[expose] public section\n\n'
                f'/-- `{k}`: what the core route knows of it. -/\n'
                f'noncomputable def cfun : CoreMode.CFun :=\n'
                f'  ⟨frameFun, alignCtx, hcert, core, Data.adviceFn{j}, Data.powTree, hpost⟩\n\nend\n\npublic section\n\nattribute [local irreducible] pairO pairS\n\n'
                f'/-- `{k}`: its promised cells witnessed. -/\n'
                f'theorem core_post : CoreMode.postOk cfun.pows cfun.H cfun.post cfun.fn.body = true := by\n  decide +kernel\n\n'
                f'/-- `{k}`: its signature translated. -/\n'
                f'theorem core_sig : CoreMode.sigOk modeFun.sig cfun.H cfun.post cfun.fn.params.length = true := by\n'
                f'  decide +kernel\n\n'
                f'/-- `{k}`: its returned products. -/\n'
                f'theorem core_retv : CoreMode.retVOk cfun modeFun.sig = true := by\n  decide +kernel\n\n'
                f'/-- `{k}`: its shape. -/\n'
                f'theorem core_shape : CoreMode.shapeOk cfun code.chunks.flatten = true := by\n  decide +kernel\n\n'
                f'/-- `{k}`: its reads of the jump table. -/\n'
                f'theorem core_jtd : CoreMode.jtdOk cfun modeEnv code.chunks.flatten = true := by\n  decide +kernel\n\n'
                f'/-- `{k}`: the kernel\'s checks of the core route, tied to its mode certificate. -/\n'
                f'theorem core_ok : CoreMode.CoreOk {K} cfun where\n'
                f'  heap := heap_ok\n'
                f'  post := core_post\n'
                f'  pair := pair_ok\n'
                f'  frame := {frame_term(frames[k])}\n'
                f'  sig := core_sig\n'
                f'  retv := core_retv\n'
                f'  shape := core_shape\n'
                f'  jtd := core_jtd\n'
                f'  fsig := rfl\n'
                f'  fentry := rfl\n'
                f'  xentry := by decide +kernel\n'
                f'  dhints := rfl\n'
                f'  hints := Mode.hintsEq_of_fn (j := {j}) (by decide +kernel) (by decide +kernel) (by decide +kernel) rfl\n'
                f'  fetch := Exec.guest_fetches (Checked.code{j} ▸ End.fnOf_mem (by decide))\n'
                f'  small := Mode.smallOps_of (CoreMode.offSmall_of_mem (f := code) (Checked.code{j} ▸ End.fnOf_mem (by decide)))\n'
                f'  pows := Exec.PowTree.ok_of_okW Checked.powTree_ok\n'
                f'  fpows := Exec.PowTree.ok_of_okW Checked.powTree_ok\n\n'
                f'/-- `{k}`: its frame interface, by the core route. -/\n'
                f'theorem fnSpecC : Mode.FnSpecC {K} cfun := Mode.fnSpecC_of core_ok\n\n'
                f'end\n\nend LeanVM.Guest.Fn.«{k}»\n')
        mod = 'LeanVM.Guest.CoreMode.Gen.«%s».Core' % p
        files[os.path.join(GEN, p, 'Core.lean')] = (
            HEADER.format(mod=mod, what='The core route\'s checks of `%s` and %d more.' % (ks[0], len(ks) - 1)) +
            ''.join('public import %s\n' % m for m in sorted(imps)) + '\nset_option Elab.async false\n' + ''.join(body))
        rimps = {'LeanVM.Guest.CoreMode.Route', 'LeanVM.Guest.Pack.«%s».ModeCert' % p}
        oks = []
        for k in ks:
            j = R[k]['j']
            rimps.add(quote(codes[str(j)])); rimps.add(quote(tabs[str(j)]))
            oks.append(f'CoreMode.cfOk_of (by decide) Checked.code{j} Checked.core{j} Checked.cert{j} Checked.plumbEq{j}\n'
                       f'      Bridge.ProgAl.tab{j} rfl rfl rfl (by decide +kernel)')
        chain = 'Mode.fa_nil'
        for q in reversed(oks):
            chain = 'Mode.fa_cons (%s)\n    (%s)' % (q, chain)
        rmod = 'LeanVM.Guest.CoreMode.Gen.«%s».Route' % p
        files[os.path.join(GEN, p, 'Route.lean')] = (
            HEADER.format(mod=rmod, what='The core route\'s data of `%s` and %d more, the deployed guest\'s.' % (ks[0], len(ks) - 1)) +
            ''.join('public import %s\n' % m for m in sorted(rimps)) + '\nset_option Elab.async false\n\n'
            f'namespace LeanVM.Guest.ModePack.«{p}»\n\nopen LeanVM.Guest\n\npublic section\n\n'
            f'/-- The pack\'s core data, each the deployed guest\'s. -/\n'
            f'theorem coreFns_ok : ∀ Cf ∈ coreFns, CoreMode.CfOk Cf :=\n  {chain}\n\nend\n\nend LeanVM.Guest.ModePack.«{p}»\n')
    stale = []
    have = set(glob.glob(os.path.join(GEN, '*', 'Core.lean')) + glob.glob(os.path.join(GEN, '*', 'Route.lean')))
    for path in sorted(have - set(files)):
        if CHECK: stale.append(path)
        else: os.remove(path)
    lines = 0
    for path, text in sorted(files.items()):
        lines += text.count('\n')
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old == text: continue
        if CHECK: stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w', encoding='utf-8').write(text)
    print('core route: %d functions, %d packs, %d files, %d lines' % (len(R), len(packs), len(files), lines) +
          ((', stale: %d %s' % (len(stale), stale[:3])) if CHECK else ''))
    if CHECK and stale: sys.exit(1)


if __name__ == '__main__':
    main()
