"""The core route's checks of each function on it (`route.py`): `Gen/<pack>/Core.lean`, its core data
(`CoreMode.CFun`: its frame walk, alignment context, heap certificate, core function, advice entry, powers and
promised cells) and the kernel's checks tying them to its mode certificate (`CoreMode.CoreOk`), hence its frame
interface (`Mode.FnSpecC`); `Gen/<pack>/Route.lean`, its core data the deployed guest's (`CoreMode.CfOk`). A heap
check `callc.py` windowed (`GenW/<fn>/`) is taken from its windows; a body longer than `SPLIT` statements has its
longest passes checked as declarations of their own (the kernel's memory goes by declaration).
Usage: python3 -I scripts/core-mode/core.py [--check]  (with `CORE_MODE_CACHE` as for `heap.py`)"""
import os, re, sys, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import route, heap  # noqa: E402
import callc  # noqa: E402

GUEST = route.GUEST
GEN = os.path.join(GUEST, 'CoreMode', 'Gen')
CHECK = '--check' in sys.argv
HEADER = """/-
  {mod}

  Generated by `scripts/core-mode/core.py`; do not edit.
  {what}
-/

module

"""


def index(pattern, files):
    """Each match's first group to the module (path under `LeanVM/`) whose text has it."""
    out = {}
    for f in files:
        mod = 'LeanVM.' + os.path.relpath(f, os.path.dirname(GUEST))[:-5].replace(os.sep, '.')
        for m in re.finditer(pattern, open(f, encoding='utf-8').read(), re.M):
            out[m.group(1)] = mod
    return out


def quote(mod):
    """A module name with `«»` around a pack or function component that needs it."""
    return '.'.join(('«%s»' % p) if (p[0].isdigit() or not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', p) or
                                     re.fullmatch(r'P\d+', p)) else p for p in mod.split('.'))


def frame_term(mod):
    """The frame walk's acceptance from its module: one check, or a long function's windows chained."""
    if '.FrameL' in mod:
        return '⟨by decide +kernel, by decide +kernel, frameAcc⟩'
    return 'CoreMode.frameAcc_of (by decide +kernel) frameOk'


def pair_mod(g, n):
    """The module of function `n`'s pairing in pack `g`: the pack's, or a long function's own (windows)."""
    if os.path.exists(os.path.join(GEN, g, n, 'Ok.lean')):
        return 'LeanVM.Guest.CoreMode.Gen.%s.%s.Ok' % (g, n)
    return 'LeanVM.Guest.CoreMode.Gen.%s.Pair' % g


# a body of more statements (nested ones included) than `SPLIT` has its longest passes over the body checked apart
# (`shapeOk_of`, `honB_of`): the kernel's memory goes by declaration, not by module
SPLIT = 10000


def nstmts(body):
    """The statements of a core body, nested ones included."""
    t = 0
    for s in body:
        t += 1
        if s[0] == 'ite':
            t += nstmts(s[2]) + nstmts(s[3])
        elif s[0] == 'match':
            t += sum(nstmts(a) for a in s[2])
    return t


def long_body(k):
    return nstmts(heap.CORE[k][1]) > SPLIT


def shape(k):
    """`core_shape`: one kernel evaluation, or a long body's passes apart (`shapeOk_of`)."""
    if not long_body(k):
        return (f'/-- `{k}`: its shape. -/\n'
                f'theorem core_shape : CoreMode.shapeOk cfun code.chunks.flatten = true := by\n  decide +kernel\n\n')
    return (f'/-- `{k}`: its body\'s statements. -/\n'
            f'theorem core_body : CoreMode.bodyCore cfun.fn.body = true := by\n  decide +kernel\n\n'
            f'/-- `{k}`: its tables\' jumps. -/\n'
            f'theorem core_tgt : CoreMode.tgtOk cfun code.chunks.flatten = true := by\n  decide +kernel\n\n'
            f'/-- `{k}`: the rest of its shape. -/\n'
            f'theorem core_rest : CoreMode.shapeRest cfun = true := by\n  decide +kernel\n\n'
            f'/-- `{k}`: its shape. -/\n'
            f'theorem core_shape : CoreMode.shapeOk cfun code.chunks.flatten = true :=\n'
            f'  CoreMode.shapeOk_of core_body core_tgt core_rest\n\n')


def checks(k, j, K, frame, heap):
    """The kernel's checks of function `k` on the core route, each heavy one its own declaration, and its
    frame interface."""
    return (f'/-- `{k}`: its signature translated. -/\n'
            f'theorem core_sig : CoreMode.ownOk modeFun.sig cfun cfun.fn.params.length (CoreMode.retN cfun.fn.body) = true := by\n'
            f'  decide +kernel\n\n'
            f'/-- `{k}`: its returned products. -/\n'
            f'theorem core_retv : (cfun.hc || CoreMode.retVOk cfun modeFun.sig) = true := by\n  decide +kernel\n\n'
            + shape(k) +
            f'/-- `{k}`: its calls\' jumps. -/\n'
            f'theorem core_calls : code.chunks.flatten.all (CoreMode.jumpCallOk cfun) = true := by\n  decide +kernel\n\n'
            f'/-- `{k}`: its reads of the jump table. -/\n'
            f'theorem core_jtd : CoreMode.jtdOk cfun modeEnv code.chunks.flatten = true := by\n  decide +kernel\n\n'
            f'/-- `{k}`: the kernel\'s checks of the core route, tied to its mode certificate. -/\n'
            f'theorem core_ok : CoreMode.CoreOk {K} cfun where\n'
            f'  heap := {heap}\n'
            f'  pair := pair_ok\n'
            f'  frame := {frame}\n'
            f'  sig := core_sig\n'
            f'  retv := core_retv\n'
            f'  shape := core_shape\n'
            f'  calls := core_calls\n'
            f'  jtd := core_jtd\n'
            f'  fsig := rfl\n'
            f'  fsigs := rfl\n'
            f'  fentry := rfl\n'
            f'  flen := by decide +kernel\n'
            f'  xentry := by decide +kernel\n'
            f'  dhints := rfl\n'
            f'  hints := Mode.hintsEq_of_fn (j := {j}) (by decide +kernel) (by decide +kernel) (by decide +kernel) rfl\n'
            f'  fetch := Exec.guest_fetches (Checked.code{j} ▸ End.fnOf_mem (by decide))\n'
            f'  small := Mode.smallOps_of (CoreMode.offSmall_of_mem (f := code) (Checked.code{j} ▸ End.fnOf_mem (by decide)))\n'
            f'  pows := Exec.PowTree.ok_of_okW Checked.powTree_ok\n'
            f'  fpows := Exec.PowTree.ok_of_okW Checked.powTree_ok\n\n'
            f'/-- `{k}`: its frame interface, by the core route. -/\n'
            f'theorem fnSpecC : Mode.FnSpecC {K} cfun := Mode.fnSpecC_of core_ok\n\n'
            f'end\n\nend LeanVM.Guest.Fn.«{k}»\n')


def dsp_arg(k):
    """`CFun.dsp`: callc's `dsp` for a body with a dispatch, else none."""
    return 'dsp' if any(s[0] == 'dispatch' for s in heap.CORE[k][1]) else '[]'


def cfun_c(k, j, K, frame):
    """A body with calls: its heap check (`heapOkC` at its callees' heap signatures `csigs`, in windows past
    `heapwin.BUDGET`, `heap_proof`), the kernel's checks."""
    return (f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\nopen LeanVM.Guest\n\n@[expose] public section\n\n'
            f'/-- `{k}`: what the core route knows of it. -/\n'
            f'noncomputable def cfun : CoreMode.CFun :=\n'
            f'  ⟨frameFun, alignCtx, hcert, core, Data.adviceFn{j}, Data.powTree, [], csigs, {dsp_arg(k)}, hcFlag, hcCallees, {callc.gl_lean(k)}⟩\n\nend\n\npublic section\n\n'
            f'attribute [local irreducible] pairO pairS\n\n'
            f'/-- `{k}`: the heap check, at its callees\' heap signatures. -/\n'
            f'theorem heap_okC : CoreMode.heapOkC Data.powTree cfun.sigOf core hcert = true := {heap_proof(k)}\n\n'
            + checks(k, j, K, frame, '.c heap_okC rfl (by decide +kernel) rfl rfl (by decide +kernel) rfl'))


def heap_win(k):
    """The module of `k`'s heap check in windows (`callc.windows`), if it has one."""
    if os.path.exists(os.path.join(GUEST, 'CoreMode', 'GenW', k, 'Ok.lean')):
        return 'LeanVM.Guest.CoreMode.GenW.%s.Ok' % quote(k)
    return None


def heap_proof(k):
    """`heapOkC`'s proof: one kernel evaluation, or its windows' (`GenW/<fn>/Ok.lean`)."""
    return 'heap_okW' if heap_win(k) else 'by\n  decide +kernel'


