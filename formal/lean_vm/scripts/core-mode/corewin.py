"""The core route's heap check of a long function in windows (`CoreMode/HeapCWinF.lean`), as `heapwin.py` does for
the inference's certificates: `GenW/<fn>/` holds `St` (`sigW`, the function's `CFun.sigOf`), the states `S<i>` at the
cuts, the windows `W<i>` and `Ok` (`heap_okW : heapOkC Data.powTree sigW core hcert = true`, by
`heapOkC_of_winsF`), the certificate `callc.py`'s (`Gen/<pack>/DataC.lean`). `core.py` writes them and proves
`heap_okC` (at `cfun.sigOf`, which unfolds to `sigW`) from `heap_okW`."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import infer as I  # noqa: E402
import heapc as C  # noqa: E402

# functions whose core-route heap check one `decide` cannot take within the default heartbeats
WIN = {'check_opening_terminal'}

HEADER = '''/-
  LeanVM.Guest.CoreMode.GenW.«{fn}».{mod}

  Generated by `scripts/core-mode/core.py` (`corewin.py`); do not edit.
  {what}
-/

module

'''


def cert_of(k, S):
    """`k`'s certificate as `callc.results()` finds it (`callcres.extend`'s path): `infer_one`'s result."""
    import callc, callcres as CR
    saved = set(I.F)
    EM = callc._em()
    b1, EM.Solver.pt = CR.cs_reads(EM)
    b2, EM.Solver.fact = CR.sel_facts(EM)
    _, EM.Solver.fact = CR.expq_facts(EM)
    try:
        for feats in (CR.FEATURES, {'ptr', 'pfr'}):
            I.F.clear()
            I.F.update(feats)
            try:
                return callc.infer_one(k, S, allow=lambda k, res: CR.res_ok(k, res, S))
            except callc.No:
                continue
        raise SystemExit(f'{k}: no certificate')
    finally:
        I.F.clear()
        I.F.update(saved)
        EM.Solver.pt = b1
        EM.Solver.fact = b2


def modules(k, S, pack, core_mod):
    """`[(name, text)]`: the windows of `k`'s heap check."""
    import heapwin as HW
    import emitc as E
    r = cert_of(k, S)
    H = r['cert']
    sigs = {I.callee(f): h for f, h in r['cs'].items()}
    sigs[k] = H.sig
    sigOf = lambda g: sigs.get(I.callee(g), C.EMPTY)
    assert not HW.is_loop(H)
    sts, costs, P = HW.states(k, H, sigOf)
    pre = HW.region(k, H)
    na = [HW.atoms(s) for s in pre]
    ents = [HW.entries(x) for x in sts]
    tot = sum(costs)
    bud = min(HW.WIN, 1.15 * tot / max(2, -(-tot // HW.WIN)))
    cs = HW.cuts(costs, na, ents, bud - HW.W_CERT * HW.cert_size(H))
    nw = len(cs) - 2
    ns = f'LeanVM.Guest.Fn.«{k}»'
    base = f'LeanVM.Guest.CoreMode.GenW.«{k}»'
    mods = []
    st = HEADER.format(fn=k, mod='St', what=f'The heap signatures `{k}`\'s windowed heap check reads.')
    st += ('public import LeanVM.Guest.CoreMode.HeapCWinF\n'
           f'public import LeanVM.Guest.CoreMode.Gen.«{pack}».DataC\npublic import LeanVM.Guest.Pack.«{pack}».{core_mod}\n')
    st += f'\nset_option linter.all false\n\nnamespace {ns}.HeapW\n\nopen LeanVM.Guest.CoreMode\n\n@[expose] public section\n\n'
    st += ('/-- Its own and its callees\' heap signatures (`CFun.sigOf`). -/\nnoncomputable def sigW : String → '
           'CoreMode.HSig :=\n  fun f ↦ bif f == core.name then hcert.sig else (csigs.lookup f).getD {}\n')
    st += f'\nend\nend {ns}.HeapW\n'
    mods.append(('St', st))
    lits = HW.Lits()
    for i, a in enumerate(cs[:nw + 1]):
        aux, text = lits.lstate(sts[a], f'st{i}')
        si = HEADER.format(fn=k, mod=f'S{i}', what=f'The state before statement {a} of `{k}`\'s windowed heap check.')
        si += f'public import {base}.{"S" + str(i - 1) if i else "St"}\n\nset_option maxRecDepth 100000\n'
        si += 'set_option linter.all false\n\n'
        si += (f'namespace {ns}.HeapW\n\nopen LeanVM.Guest.CoreMode\nopen LeanVM.Guest.Exec (Trie)\n\n'
               f'@[expose] public section\n')
        si += ''.join(f'\n{d}' for d in aux)
        si += f'\n/-- The state before statement {a}. -/\nnoncomputable def st{i} : CSt := {text}\n'
        si += f'\nend\nend {ns}.HeapW\n'
        mods.append((f'S{i}', HW.repack(si)))
    imps = 'public import LeanVM.Guest.Data.Pows\n'
    for i in range(nw):
        a, b = cs[i], cs[i + 1]
        w = HEADER.format(fn=k, mod=f'W{i}', what=f'Window {i} of `{k}`\'s heap check: statements {a} to {b - 1}.')
        w += f'public import {base}.S{i}\npublic import {base}.S{i + 1}\n'
        w += imps + f'\nset_option Elab.async false\n\nnamespace {ns}.HeapW\n\nopen LeanVM.Guest.CoreMode\n\n'
        w += f'@[expose] public section\n\n'
        w += (f'/-- Statements {a} to {b - 1}. -/\ntheorem win{i} : winOkF Data.powTree sigW '
              f'core hcert ((core.body.drop {a}).take ({b} - {a})) st{i} st{i + 1} = true := by\n'
              f'  decide +kernel\n\nend\nend {ns}.HeapW\n')
        mods.append((f'W{i}', w))
    n = nw
    ok = HEADER.format(fn=k, mod='Ok', what=f'`{k}`\'s heap check on the core route, from its {n} windows.')
    ok += ''.join(f'public import {base}.W{i}\n' for i in range(n))
    ok += 'public import LeanVM.Guest.CoreMode.HeapCWinF\n' + ('' if n else f'public import {base}.S0\n' + imps)
    ok += f'\nset_option Elab.async false\n\nnamespace {ns}.HeapW\n\nopen LeanVM.Guest.CoreMode\n\n@[expose] public section\n\n'
    ok += (f'/-- The parameters, the entry state. -/\ntheorem head_ok : headOkF Data.powTree sigW core hcert st0 = '
           f'true := by\n  decide +kernel\n\n')
    ok += (f'/-- Statements {cs[-2]} to the end. -/\ntheorem last_ok : lastOkF Data.powTree sigW core hcert {cs[-2]} '
           f'st{n} = true := by\n  decide +kernel\n\n')
    lst = ', '.join(f'({cs[i]}, st{i})' for i in range(1, n + 1))
    wins = ''.join(f'win{i}, by omega,\n    ' for i in range(n))
    ok += (f'/-- `{k}`: the heap check, in {n} windows. -/\ntheorem heap_okW : CoreMode.heapOkC Data.powTree sigW core '
           f'hcert = true :=\n  CoreMode.heapOkC_of_winsF (l := [{lst}]) head_ok\n    '
           f'{f"⟨{wins}trivial⟩" if n else "trivial"} rfl last_ok\n')
    ok += f'\nend\nend {ns}.HeapW\n'
    mods.append(('Ok', ok))
    print(f'{k}: {len(pre)} statements, {sum(na)} atoms, estimated {tot:.0f}k heartbeats; {nw} windows')
    return mods
