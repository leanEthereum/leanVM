"""The core route's ties to the global function index `j`, by pack: everything else of the core route
names a function by its stable key (`Fn.«k»`).

* `CoreMode/GlueA/<pack>.lean`: for each function whose core the pack holds, `Fn.«k».advice`, its entry, length and
  hints by pc (`Data.adviceFn{j}`, the statement's advice), and `idx`, its index `j`.
* `CoreMode/GlueC/<pack>.lean`: for each function of the pack with a link (`Checked.code{j}`),
  `Fn.«k».code_mem`, that its code is the program's.

An added or removed function renumbers `j` here only.

usage (from formal/lean_vm): python3 -I scripts/core-mode/glue.py [--check]
"""
import sys, os, re, glob

LV = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
GUEST = os.path.join(LV, 'LeanVM', 'Guest')
STMT = os.path.join(LV, '..', 'Statement', 'Data')
CHECK = '--check' in sys.argv
NSRE = re.compile(r'^namespace LeanVM\.Guest\.Fn\.«([^»]+)»$', re.M)


def header(mod, what):
    return f'/-\n  {mod}\n\n  Generated by `scripts/core-mode/glue.py`; do not edit.\n  {what}\n-/\n\nmodule\n\n'


def main():
    t = open(os.path.join(GUEST, 'Data', 'NameStrings.lean'), encoding='utf-8').read()
    name = dict(re.findall(r'abbrev «([^»]+)» : String := "([^"]+)"', t))
    t = ''.join(open(f, encoding='utf-8').read() for f in sorted(glob.glob(os.path.join(STMT, 'AdviceHints*.lean'))))
    adv = {m.group(1): int(m.group(2)) for m in
           re.finditer(r'/-- `([^`]*)`: its entry, length and hints by pc\. -/\ndef adviceFn(\d+)', t)}
    link = {}
    for f in glob.glob(os.path.join(GUEST, 'Checked', 'Link*.lean')):
        mod = 'LeanVM.Guest.Checked.' + os.path.basename(f)[:-5]
        for j in re.findall(r'^kernel_rfl code(\d+) :', open(f, encoding='utf-8').read(), re.M):
            link[int(j)] = mod
    # each function in the pack holding its core (as `heap.pack_of`), its code in its bundle's pack
    home, bpack = {}, {}
    for f in sorted(glob.glob(os.path.join(GUEST, 'Pack', '*', 'Core*.lean'))):
        for k in NSRE.findall(open(f, encoding='utf-8').read()):
            home.setdefault(k, os.path.basename(os.path.dirname(f)))
    for f in sorted(glob.glob(os.path.join(GUEST, 'Pack', '*', 'Bundle*.lean'))):
        for k in NSRE.findall(open(f, encoding='utf-8').read()):
            bpack[k] = os.path.basename(os.path.dirname(f))
    packs = {}
    for k, pack in home.items():
        if name.get(k) in adv and k in bpack:
            packs.setdefault(pack, []).append(k)
    want = {}
    for pack, ks in sorted(packs.items()):
        ks = sorted(ks)
        a = [header(f'LeanVM.Guest.CoreMode.GlueA.«{pack}»', 'The advice of the pack\'s functions, by stable key.'),
             'public import Statement.Data.AdviceHints\n\nset_option linter.all false\n']
        c = [header(f'LeanVM.Guest.CoreMode.GlueC.«{pack}»', 'The code of the pack\'s functions, the program\'s.'),
             'public import LeanVM.Guest.SoundFacts\n',
             ''.join(f'public import {m}\n' for m in sorted({link[adv[name[k]]] for k in ks if adv[name[k]] in link})),
             ''.join(f'public import LeanVM.Guest.Pack.«{q}».Bundle\n' for q in sorted({bpack[k] for k in ks})),
             '\nset_option linter.all false\n']
        for k in ks:
            j = adv[name[k]]
            a.append(f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\n@[expose] public section\n\n'
                     f'/-- `{k}`: its entry, length and hints by pc. -/\nabbrev advice := Data.adviceFn{j}\n\n'
                     f'/-- `{k}`: its index in the program. -/\nabbrev idx : ℕ := {j}\n\n'
                     f'end\nend LeanVM.Guest.Fn.«{k}»\n')
            if j in link:
                c.append(f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\npublic section\n\n'
                         f'/-- `{k}`: its code is the program\'s. -/\n'
                         f'theorem code_mem : code ∈ Data.functions := Checked.code{j} ▸ End.fnOf_mem (by decide)\n\n'
                         f'end\nend LeanVM.Guest.Fn.«{k}»\n')
        want[os.path.join(GUEST, 'CoreMode', 'GlueA', pack + '.lean')] = ''.join(a)
        want[os.path.join(GUEST, 'CoreMode', 'GlueC', pack + '.lean')] = ''.join(c)
    stale = []
    have = set(glob.glob(os.path.join(GUEST, 'CoreMode', 'GlueA', '*.lean'))) | \
        set(glob.glob(os.path.join(GUEST, 'CoreMode', 'GlueC', '*.lean')))
    for path, text in sorted(want.items()):
        if os.path.exists(path) and open(path, encoding='utf-8').read() == text:
            continue
        if CHECK:
            stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as fh:
                fh.write(text)
    for path in sorted(have - set(want)):
        if CHECK:
            stale.append(path)
        else:
            os.remove(path)
    if stale:
        print('stale:', *stale, sep='\n  ')
        sys.exit(1)
    print('glue: %d packs' % (len(want) // 2))


if __name__ == '__main__':
    main()
