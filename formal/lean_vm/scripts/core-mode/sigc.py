"""Writes `LeanVM/Guest/CoreMode/Sig/<pack>.lean`: each function's signature (`Fn.«k».csig : Mode.Sig`), what its
callers on either route are told of it: its entry, the frame cells and heap facts it needs at entry and
guarantees at return. The signatures are the mode walk's inference's (`scripts/mode-cert/infer.py`, read from
`MODE_CERT_CACHE`), which the core route's checks hold to its heap signatures (`CoreMode.ownOk`, `fitB`) and the
mode walk's to its walks.

`--dump FILE` writes them as JSON instead (`{key: the literal's fields}`), for `route.sigs()`.
usage (from formal/lean_vm, `MODE_CERT_CACHE` set): python3 -I scripts/core-mode/sigc.py [--check] [--dump FILE]"""
import os, sys, glob, json, pickle
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..', 'mode-cert')))
sys.setrecursionlimit(100000)
import gen as MG  # noqa: E402

OUT = os.path.join(MG.I.data.ROOT, 'CoreMode', 'Sig')


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/core-mode/sigc.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def files(sigs):
    out = {}
    for p, names in sorted(MG.packs().items()):
        body = [header('LeanVM.Guest.CoreMode.Sig.«%s»' % p, 'What a caller knows of compiled functions.'),
                'public import LeanVM.Guest.Mode.Abs\n']
        for n in sorted(names, key=lambda n: MG.I.fns[n]['ns']):
            G = sigs[n]
            assert MG.termFr(G), n
            k = MG.I.fns[n]['ns']
            body.append('\nnamespace LeanVM.Guest.Fn.«%s»\n\n@[expose] public section\n\n'
                        '/-- `%s`: its entry, the cells and heap facts it needs at entry and guarantees at return. -/\n'
                        'noncomputable def csig : Mode.Sig :=\n  %s\n\nend\n\nend LeanVM.Guest.Fn.«%s»\n' % (
                            k, n, MG.sig(G), k))
        out[os.path.join(OUT, '%s.lean' % p)] = MG.wrap(''.join(body))
    return out


def glue_g():
    """`CoreMode/GlueG.lean`: the program's constants the core route's certificates name."""
    return {os.path.join(MG.I.data.ROOT, 'CoreMode', 'GlueG.lean'): (
        header('LeanVM.Guest.CoreMode.GlueG', 'The program\'s constants the core route\'s certificates name.') +
        'namespace LeanVM.Guest.CoreMode\n\n@[expose] public section\n\n'
        '/-- The jump table\'s end (its cells `430` to `jtHi`). -/\nabbrev jtHi : Nat := %d\n\n'
        'end\n\nend LeanVM.Guest.CoreMode\n' % MG.I.JT_HI)}


def main(argv):
    sigs = pickle.load(open(os.environ['MODE_CERT_CACHE'], 'rb'))[0]
    if '--dump' in argv:
        out = argv[argv.index('--dump') + 1]
        json.dump({MG.I.fns[n]['ns']: MG.sig(G)[1:-1] for n, G in sigs.items()}, open(out + '.tmp', 'w'))
        os.replace(out + '.tmp', out)
        return
    want = files(sigs)
    want.update(glue_g())
    stale = []
    for path, text in sorted(want.items()):
        if os.path.exists(path) and open(path, encoding='utf-8').read() == text:
            continue
        if '--check' in argv:
            stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w', encoding='utf-8').write(text)
    for path in sorted(set(glob.glob(os.path.join(OUT, '*.lean'))) - set(want)):
        if '--check' in argv:
            stale.append(path)
        else:
            os.remove(path)
    if stale:
        print('stale:', *stale, sep='\n  ')
        sys.exit(1)
    print('signatures: %d functions, %d packs' % (len(sigs), len(want)))


if __name__ == '__main__':
    main(sys.argv[1:])
