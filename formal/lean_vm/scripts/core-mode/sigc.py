"""Writes `LeanVM/Guest/CoreMode/Sig/<pack>.lean`: each function's signature (`Fn.«k».csig : Mode.Sig`), what its
callers on either route are told of it: its entry, the frame cells and heap facts it needs at entry and
guarantees at return; and the glue `LeanVM/Guest/CoreMode/GlueE/<pack>.lean`: each function's entry pc
(`Fn.«k».entry`), the only place the core route's data names it.

A function on the core route keeps its signature: its contract, as written (`CoreMode/Sig/<pack>.lean`), which the
route's checks hold to its heap signature (`CoreMode.ownOk`, `fitB`), its frame cells checked against the frame layout
(`compiled.fsig`). So a routed function's signature, and its callers' certificates, change only when its contract
does, and no routed function needs the mode walk's inference. The others' signatures, a routed function's whose
frame layout changed and those named by `--fresh`, are the mode walk's inference's (`scripts/mode-cert/infer.py`,
read from `MODE_CERT_CACHE`), held to their walks.

usage (from formal/lean_vm): python3 -I scripts/core-mode/sigc.py [--check] [--fresh NAME,..]"""
import os, re, sys, glob, pickle
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.setrecursionlimit(100000)
import compiled as C  # noqa: E402

ROOT = C.ROOT
OUT = os.path.join(ROOT, 'CoreMode', 'Sig')
GLUE = os.path.join(ROOT, 'CoreMode', 'GlueE')
# `def Fn.«k».csig : Mode.Sig := ⟨Fn.«k».entry, ..⟩` up to the next declaration or the section's end
CSIG = re.compile(r'noncomputable def Fn\.«([^»]+)»\.csig\s*:\s*Mode\.Sig\s*:=\s*⟨Fn\.«[^»]+»\.entry, (.*?)⟩\n(?=noncomputable|\nend)',
                  re.S)


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/core-mode/sigc.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def routed():
    """The functions on the core route as written (`Gen/<pack>/Core.lean`'s `coreFns`), by key."""
    out = set()
    for f in glob.glob(os.path.join(ROOT, 'CoreMode', 'Gen', '*', 'Core.lean')):
        out |= set(re.findall(r'Fn\.«([^»]+)»\.cfun', open(f, encoding='utf-8').read()))
    return out


def written():
    """Each function's signature as written, the literal's fields past its entry, by key."""
    out = {}
    for f in glob.glob(os.path.join(OUT, '*.lean')):
        for m in CSIG.finditer(open(f, encoding='utf-8').read()):
            out[m.group(1)] = ' '.join(m.group(2).split())
    return out


def layout_ok(fields, fsig):
    """The written signature's entry cells, self cell and return cells are the frame layout's."""
    parts = C.split_top(fields)
    ent, slf, ret = C.parse(parts[0]), C.parse(parts[1]), C.parse(parts[5])
    return ent == fsig[0] and ret == fsig[2] and slf == (('id', 'none') if fsig[1] is None else ('some', fsig[1]))


def mode_lit(G):
    """A signature of the mode walk's inference (`walk.Sig`) as the literal's fields past its entry."""
    nat, mono, rng, lst = C.nat, C.mono, C.rng, C.lst
    ptr = lambda q: '(%s, %s)' % (rng(q[0]), lst(q[1], nat))
    ltp = lambda p: '(%s, %s)' % (C.idx(p[0]), C.idx(p[1]))
    return '%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s' % (
        lst(G.entry, nat), 'none' if G.self_ is None else '(some %d)' % G.self_, lst(G.pre, mono),
        lst(G.preR, rng), lst(G.term, ltp), lst(G.ret, nat),
        lst(G.post, mono), lst(G.postR, rng), lst(G.postL, rng), lst(G.preP, ptr), lst(G.postP, ptr),
        lst(G.postLP, ptr), lst(G.retV, lambda p: '(%d, %s)' % (p[0], mono(p[1]))), lst(G.postT, ltp),
        lst(G.postC, lambda q: '(%s, %d, %s)' % (C.base(q[0]), q[1], lst(q[2], ltp))))


def term_fr(G):
    """Each termination fact reads entry cells or constants (`Mode.termFr`)."""
    ok = lambda i: i[0] == 'num' or (i[1][0] == 'fr' and i[1][1] in G.entry)
    return all(ok(p) and ok(q) for p, q in G.term)


def inferred():
    """The mode walk's inferred signatures (`MODE_CERT_CACHE`), by compiled name."""
    cache = os.environ.get('MODE_CERT_CACHE')
    if not cache:
        raise SystemExit('sigc: functions off the core route need the mode walk\'s inference (MODE_CERT_CACHE)')
    # the pickled signatures are the mode walk's (`walk.Sig`)
    sys.path.append(os.path.normpath(os.path.join(HERE, '..', 'mode-cert')))
    import walk  # noqa: F401
    return pickle.load(open(cache, 'rb'))[0]


def signatures(fresh=()):
    """Each function's signature's fields past its entry, by compiled name, and how many were kept."""
    D = C.code()
    on, old = routed(), written()
    out, kept, sigs = {}, 0, None
    for n, f in D['fns'].items():
        k = f['ns']
        if k in on and k in old and k not in fresh and layout_ok(old[k], D['fsig'][f['entry']]):
            out[n] = old[k]
            kept += 1
            continue
        if sigs is None:
            sigs = inferred()
        G = sigs[n]
        assert term_fr(G) and G.pc == f['entry'], n
        out[n] = mode_lit(G)
    return out, kept


def files(lits):
    out = {}
    D = C.code()
    for p, names in sorted(C.packs().items()):
        sec = '\nset_option linter.style.nameCheck false\n\nnamespace LeanVM.Guest\n\n@[expose] public section\n\n'
        body = [header('LeanVM.Guest.CoreMode.Sig.«%s»' % p, 'What a caller knows of compiled functions.'),
                'public import LeanVM.Guest.Mode.Abs\npublic import LeanVM.Guest.CoreMode.GlueE.«%s»\n' % p, sec]
        glue = [header('LeanVM.Guest.CoreMode.GlueE.«%s»' % p, 'The entry pc of each compiled function of the pack.'),
                'namespace LeanVM.Guest\n\n@[expose] public section\n\n']
        for n in sorted(names, key=lambda n: D['fns'][n]['ns']):
            k = D['fns'][n]['ns']
            body.append('noncomputable def Fn.«%s».csig : Mode.Sig :=\n  ⟨Fn.«%s».entry, %s⟩\n' % (k, k, lits[n]))
            glue.append('abbrev Fn.«%s».entry : Nat := %d\n' % (k, D['fns'][n]['entry']))
        body.append('\nend\n\nend LeanVM.Guest\n'); glue.append('\nend\n\nend LeanVM.Guest\n')
        out[os.path.join(OUT, '%s.lean' % p)] = C.wrap(''.join(body))
        out[os.path.join(GLUE, '%s.lean' % p)] = ''.join(glue)
    return out


def glue_g():
    """`CoreMode/GlueG.lean`: the program's constants the core route's certificates name."""
    return {os.path.join(ROOT, 'CoreMode', 'GlueG.lean'): (
        header('LeanVM.Guest.CoreMode.GlueG', 'The program\'s constants the core route\'s certificates name.') +
        'namespace LeanVM.Guest.CoreMode\n\n@[expose] public section\n\n'
        '/-- The jump table\'s end (its cells `430` to `jtHi`). -/\nabbrev jtHi : Nat := %d\n\n'
        'end\n\nend LeanVM.Guest.CoreMode\n' % C.code()['jt_hi'])}


def main(argv):
    fresh = set(argv[argv.index('--fresh') + 1].split(',')) if '--fresh' in argv else set()
    lits, kept = signatures(fresh)
    want = files(lits)
    want.update(glue_g())
    stale = []
    for path, text in sorted(want.items()):
        if os.path.exists(path) and open(path, encoding='utf-8').read() == text:
            continue
        if '--check' in argv:
            stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w', encoding='utf-8').write(text)
    for path in sorted(set(glob.glob(os.path.join(OUT, '*.lean')) + glob.glob(os.path.join(GLUE, '*.lean'))) - set(want)):
        if '--check' in argv:
            stale.append(path)
        else:
            os.remove(path)
    if stale:
        print('stale:', *stale, sep='\n  ')
        sys.exit(1)
    print('signatures: %d functions (%d on the core route kept), %d packs' % (len(lits), kept, len(want) // 2))


if __name__ == '__main__':
    main(sys.argv[1:])
