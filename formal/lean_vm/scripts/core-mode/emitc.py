"""The heap certificates of `infer.py` in `heapOkC`'s input format (`m2-format.md`, `CoreMode/Defs.lean`'s `HCert` with
`calls` and `rets`), and their checks.

Inferred with the features `heapOkC` has (`infer.py --lean`, plus `--with` for the ones the Lean side adds). Per pack:
`LeanVM/Guest/CoreMode/GenC/<pack>/Data.lean`, every function's `hcert` whose signature is in the format (cells over
slots, run bounds `.num`/`.val` of a slot); `Ok.lean`, `heap_okC : heapOkC Data.powTree sigOf core hcert = true` for each
function whose certificate is in the format and whose pass witnessed everything, `sigOf` its callees' signatures by their
`Fn.name`.

usage (from formal/lean_vm): python3 -I scripts/core-mode/emitc.py [--with FEATURES] [--out DIR] [--check] [--mods FILE]
  [--json FILE] (every function's certificate as JSON, the full inference's when no `--lean`-style flag restricts it)
"""
import sys, os, collections, glob, re, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
argv = list(sys.argv)
sys.argv = sys.argv[:1]
import infer as I

GUEST = os.path.normpath(os.path.join(HERE, '..', '..', 'LeanVM', 'Guest'))
NAME = {k: nm for nm, k in I.STABLE.items()}


class Unsupported(Exception):
    pass


def lcell(c):
    if any(e < 0 for _, e in c[0]):
        raise Unsupported(('cell', c))
    return '⟨[' + ', '.join(f'({b}, {e})' for b, e in c[0]) + f'], {c[1]}⟩'


def lidx(i):
    """A signature run's bound: `.num n` or `.val slot`."""
    if not i[0]:
        if i[1] >= 2 ** 62:
            raise Unsupported(('idx', i))
        return f'(.num {i[1]})'
    if len(i[0]) == 1 and i[0][0][1] == 1 and i[1] == 0:
        return f'(.val {i[0][0][0]})'
    raise Unsupported(('idx', i))


def lrun(r):
    Q, S, lo, hi = r
    return f'⟨{lcell(Q)}, {S}, {lidx(lo)}, {lidx(hi)}⟩'


def lres(r):
    """A residual: `.lt a b` over value numbers."""
    if r[0] != 'lt' or len(r) < 5 or r[4] is None:
        raise Unsupported(('res', r[:4]))
    (ka, a), (kb, b) = r[4]
    return f'.lt (.{ka} {a}) (.{kb} {b})'


def lwit(P, w):
    k = w[0]
    if k == 'ev':
        return f'.ev {w[1]}'
    if k == 'pre':
        return f'.pre {w[1]}'
    if k == 'run':
        rw = w[1]
        r = rw[1] if isinstance(rw, tuple) and rw[0] == 'preR' else (len(P.sig.preR) + rw if isinstance(rw, int) else None)
        if r is None:
            raise Unsupported(('wit', w))
        return f'.run {r} [{", ".join(map(str, w[2]))}]'
    raise Unsupported(('wit', w[0]))


def wrap(items, ind='    ', width=110):
    lines, cur = [], ''
    for it in items:
        if cur and len(ind) + len(cur) + len(it) + 2 > width:
            lines.append(cur + ',')
            cur = ''
        cur = f'{cur}, {it}' if cur else it
    if cur:
        lines.append(cur)
    return ('\n' + ind).join(lines)


def lsig(G):
    return (f'⟨[{wrap(map(lcell, G.pre))}],\n    [{wrap(map(lcell, G.post))}],\n    [{wrap(map(lrun, G.preR))}],\n'
            f'    [{wrap(map(lrun, G.postR))}],\n    [{wrap(f"({lidx(a)}, {lidx(b)})" for a, b in G.term)}]⟩')


def lcert(P):
    """The certificate's fields, or `Unsupported`."""
    G = P.sig
    by_d = collections.defaultdict(list)
    for (d, p, off), w in sorted(P.reads.items()):
        by_d[d].append(f'({p}, {off}, {lwit(P, w)})')
    reads = wrap(f'({d}, [{", ".join(rs)}])' for d, rs in sorted(by_d.items()))
    calls = wrap('[' + ', '.join(lwit(P, w) for _, w in ws) + ']' for f, ws in P.calls)
    rets = wrap('[' + ', '.join(lwit(P, w) for _, w in ws) + ']' for ws in P.ret_wits)
    res = wrap(map(lres, P.res))
    return (f'  sig := {lsig(G)}\n  reads := [{reads}]\n  res := [{res}]\n  calls := [{calls}]\n'
            f'  rets := [{rets}]\n')


def pack_of():
    out = {}
    for p in glob.glob(os.path.join(GUEST, 'Pack', '*', 'Core*.lean')):
        pack = os.path.basename(os.path.dirname(p))
        for m in re.finditer(r'^namespace LeanVM\.Guest\.Fn\.«([^»]+)»$', open(p, encoding='utf-8').read(), re.M):
            out.setdefault(m.group(1), (pack, os.path.basename(p)[:-5]))
    return out


HEADER = '''/-
  LeanVM.Guest.CoreMode.GenC.«{pack}».{mod}

  Generated by `scripts/core-mode/emitc.py`; do not edit.
  {what}
-/

module

'''


def build(res):
    """Each function's certificate text, or why it is not in the format; which pass."""
    cert, why = {}, {}
    for k, P in res.items():
        try:
            if not I.ok(P):
                raise Unsupported(('uncovered', len(P.unc), I.misses(P)))
            cert[k] = lcert(P)
        except Unsupported as e:
            why[k] = e.args[0]
            try:
                lsig(P.sig)
            except Unsupported as e2:
                why[k] = ('sig',) + e2.args
    passing = set()
    for k in I.ORDER:
        if k in cert and all(c in passing for c in I.CALLS[k] if c != k and c in I.CORE):
            passing.add(k)
    return cert, why, passing


def emit(out, res, check):
    cert, why, passing = build(res)
    po = pack_of()
    packs = collections.defaultdict(list)
    sigok = {}
    for k in sorted(res):
        try:
            lsig(res[k].sig)
            sigok[k] = True
        except Unsupported:
            sigok[k] = False
        if k in cert or sigok[k]:
            packs[po[k][0]].append(k)
    stale, mods, lines = [], [], 0
    for pack, ks in sorted(packs.items()):
        d = os.path.join(out, pack)
        data = HEADER.format(pack=pack, mod='Data', what=f'The heap certificates of `{ks[0]}` and {len(ks) - 1} more.')
        data += 'public import LeanVM.Guest.CoreMode.Defs\n\nset_option maxRecDepth 100000\nset_option linter.all false\n'
        oks = [k for k in ks if k in passing]
        imps = sorted({f'LeanVM.Guest.Pack.«{pack}».{po[k][1]}' for k in oks} |
                      {f'LeanVM.Guest.CoreMode.GenC.«{po[c][0]}».Data' for k in oks for c in I.CALLS[k] if c in I.CORE})
        ok = HEADER.format(pack=pack, mod='Ok', what=f'The kernel\'s heap checks of {len(oks)} functions.')
        ok += 'public import LeanVM.Guest.CoreMode.HeapC\npublic import LeanVM.Guest.Data.Pows\n'
        ok += ''.join(f'public import {m}\n' for m in imps)
        ok += f'public import LeanVM.Guest.CoreMode.GenC.«{pack}».Data\n\nset_option Elab.async false\n'
        for k in ks:
            body = cert.get(k)
            if body is None:
                # the signature alone, for callers' `sigOf`
                G = res[k].sig
                body = f'  sig := {lsig(G)}\n  reads := []\n  res := []\n'
            data += (f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\n@[expose] public section\n\n'
                     f'/-- `{k}`: its heap certificate{"" if k in cert else " (its signature only: not checked)"}. -/\n'
                     f'def hcert : CoreMode.HCert where\n{body}\nend\nend LeanVM.Guest.Fn.«{k}»\n')
        for k in oks:
            cs = sorted({c for c in I.CALLS[k] if c in I.CORE})
            arms = ''.join(f'\n    | "{NAME.get(c, c)}" => Fn.«{c}».hcert.sig' for c in cs)
            sig = f'(fun g ↦ match g with{arms}\n    | _ => .empty)' if cs else '(fun _ ↦ .empty)'
            ok += (f'\nnamespace LeanVM.Guest.Fn.«{k}»\n\n@[expose] public section\n\n/-- `{k}`: the heap check. -/\n'
                   f'theorem heap_okC : CoreMode.heapOkC Data.powTree\n    {sig}\n    core hcert = true := by\n'
                   f'  decide +kernel\n\nend\nend LeanVM.Guest.Fn.«{k}»\n')
        files = [('Data', data)] + ([('Ok', ok)] if oks else [])
        for name, text in files:
            path = os.path.join(d, name + '.lean')
            lines += text.count('\n')
            mods.append(f'LeanVM.Guest.CoreMode.GenC.«{pack}».{name}')
            if check:
                if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
                    stale.append(path)
            else:
                os.makedirs(d, exist_ok=True)
                with open(path, 'w', encoding='utf-8') as fh:
                    fh.write(text)
    if check:
        have = set(glob.glob(os.path.join(out, '*', '*.lean')))
        want = {os.path.join(out, m.split('«')[1].split('»')[0], m.rsplit('.', 1)[1] + '.lean') for m in mods}
        stale += sorted(have - want)
    cw = collections.Counter(w[0] if isinstance(w, tuple) else str(w) for w in why.values())
    print(f'certificates in the format: {len(cert)}; checked (callees too): {len(passing)}; data for {sum(len(v) for v in packs.values())}'
          f' functions in {len(packs)} packs, {lines} lines')
    print('  not in the format, by first reason:', dict(cw.most_common()))
    if check:
        print(f'checked: ' + (f'{len(stale)} stale: {stale[:5]}' if stale else 'up to date'))
        if stale:
            sys.exit(1)
    return mods


def as_json(res):
    def j(x):
        if isinstance(x, (tuple, list)):
            return [j(y) for y in x]
        if isinstance(x, (set, frozenset)):
            return sorted(j(y) for y in x)
        if isinstance(x, dict):
            return {str(k): j(v) for k, v in x.items()}
        return x
    out = {}
    for k, P in res.items():
        G = P.sig
        out[k] = dict(shape=I.shape(k), ok=I.ok(P), sig={f: j(getattr(G, f)) for f in I.Sig.FIELDS},
                      retM=j(G.retM), reads=[[j(a), j(w)] for a, w in sorted(P.reads.items())],
                      calls=[[j(f), j(ws)] for f, ws in P.calls], rets=j(P.ret_wits), res=j(P.res),
                      unc=j(P.unc))
    return out


def main():
    I.set_features(argv)
    res, dt = I.run_all()
    print(f'inferred {len(res)} functions in {dt:.1f} s, features: {",".join(sorted(I.F)) or "(heapOkC)"}')
    if '--json' in argv:
        with open(argv[argv.index('--json') + 1], 'w') as fh:
            json.dump(as_json(res), fh)
    out = argv[argv.index('--out') + 1] if '--out' in argv else os.path.join(GUEST, 'CoreMode', 'GenC')
    if '--json' not in argv or '--out' in argv or '--check' in argv:
        mods = emit(out, res, '--check' in argv)
        if '--mods' in argv:
            with open(argv[argv.index('--mods') + 1], 'w') as fh:
                fh.write('\n'.join(mods) + '\n')


if __name__ == '__main__':
    main()
