"""Writes `Guest/Res/AnyOk.lean`: `ResTop guestCerts` with the `sub` residuals open less the reads of
`child_claim_list_any`'s entries table by its callees (`Res.anyLink`, `anyLink_ok`: the core route's
`scripts/core-mode/anylink.py` writes them, read off the core IR). That every `sub` residual is in a family,
these reads among them, is `sub.py`'s check. Also the helpers `coreBody`, `coreCount` and `RANGES` the other
res-cert scripts read. `--check` writes nothing and fails when the file differs.
Usage: python3 -I scripts/res-cert/link.py [--check]"""
import sys, os, re, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import term

OUT = term.OUT
ROOT = term.ROOT
# the callers' check by ranges of functions, each a kernel check
RANGES = [(0, 100), (100, 300), (400, 400), (800, 400), (1200, None)]


def coreBody(ns):
    """The core IR body of the function of stable name `ns`, as text."""
    for path in glob.glob(os.path.join(ROOT, 'Pack', '*', 'Core.lean')):
        t = open(path).read()
        key = '\nnamespace LeanVM.Guest.Fn.«%s»\n' % ns
        if key in t:
            blk = t[t.index(key):]
            return blk[:blk.index('\nend LeanVM.Guest.Fn.«%s»' % ns)]
    raise KeyError(ns)


def coreCount():
    t = open(os.path.join(ROOT, 'Data', 'NameStrings.lean')).read()
    return int(re.search(r'abbrev coreCount : Nat := (\d+)', t).group(1))


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/link.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def render():
    files = {}
    mod = 'LeanVM.Guest.Res.AnyOk'
    t = [header(mod, '`ResTop guestCerts` less `anyLink`\'s reads.')]
    t.append('public import LeanVM.Guest.CoreMode.Gen.AnyLinkOk\npublic import LeanVM.Guest.Res.ResCerts\n\n'
             'namespace LeanVM.Guest.EndExec\n\nopen LeanVM.Guest LeanVM.Guest.Mode LeanVM.Guest.Res LeanVM.Guest.Memory\n\n'
             'public section\n\n')
    t.append('/-- **The residuals at the honest frames**, for the mode walk\'s certificates: from the listed\n'
             'certificates\', the `sub` residuals\' but the splits\' and `anyLink`\'s reads, and the listed\n'
             'parameters\' nonzero values. -/\n'
             'theorem resTop_guestA {A : String → Bridge.FnAl} (hexc : ∀ K ∈ resExc, ResCert A K)\n'
             '    (hsub : ResOpen guestCerts A fun j x ↦ ((∃ a bs, x = .sub a bs) ∧ splitB j x = false) ∧\n'
             '      anyResB anyLink j x = false)\n'
             '    (hexp : ResOpen guestCerts A fun j x ↦ ltExpB j x = true)\n'
             '    (hnz : ∀ p ∈ nzVals, NzVal p.1 p.2) : ResTop guestCerts A :=\n'
             '  resTop_guest hexc (resOpen_any anyLink_ok hsub) hexp hnz\n\nend\n\nend LeanVM.Guest.EndExec\n')
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'AnyCallers*.lean')) + [os.path.join(OUT, 'AnyData.lean')]:
        if os.path.exists(p):
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('AnyOk: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
