"""Writes `Guest/Res/AnyData.lean`, `AnyCallers{k}.lean` and `AnyOk.lean`: the callees of
`child_claim_list_any` whose `sub` residuals read its entries table (`Res.anyLink`: each callee with
the positions of the caller's entries parameter and bound quotient among its call's arguments), the
callers' check over the whole program by ranges, the link's other checks (`EndExec.LinkOk`), that
every `sub` residual of each callee is such a read (`Res.subDone`), and `ResTop guestCerts` with the
`sub` residuals open less these. The callees are those of the caller's call sites with `sub`
residuals (`sel.residuals`), the call sites read off its core IR (`Pack/*/Core.lean`).
`--check` writes nothing and fails when a file differs.
Usage: python3 -I scripts/res-cert/link.py [--check]"""
import sys, os, re, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import term
import sel
sys.path.insert(0, os.path.join(HERE, '..', 'mode-cert'))
import data

OUT = term.OUT
ROOT = term.ROOT
# the caller: its stable name, its entries and bound parameters
ORIGIN = 'child_claim_list_any'
UE, UL = 0, 3
# the callers' check by ranges of functions, each a kernel check
RANGES = [(0, 100), (100, 300), (400, 400), (800, 400), (1200, None)]


def coreBody(ns):
    """The core IR body of the function of stable name `ns`, as text."""
    for path in glob.glob(os.path.join(ROOT, 'Pack', '*', 'Core.lean')):
        t = open(path).read()
        key = '\nnamespace LeanVM.Guest.Fn.«%s»\n' % ns
        if key in t:
            blk = t[t.index(key):]
            return blk[:blk.index('\nend LeanVM.Guest.Fn.«%s»' % ns)]
    raise KeyError(ns)


def coreCount():
    t = open(os.path.join(ROOT, 'Data', 'NameStrings.lean')).read()
    return int(re.search(r'abbrev coreCount : Nat := (\d+)', t).group(1))


def link():
    """The callees `(stable name, kE, kL)`, the bound quotient `w` and the constant `c`."""
    D = data.load()
    stable = {f['name']: f['ns'] for f in D['fns'].values()}
    body = coreBody(ORIGIN)
    w, c = re.search(r'\.mul \(\.n %d\) \(\.n (\d+)\) \(\.n (\d+)\)' % UL, body).groups()
    sites = {}
    for m in re.finditer(r'\.dispatch \(\.n \d+\) \[([^\]]*)\] \[([^\]]*)\]', body):
        for f in re.findall(r'"([^"]+)"', m.group(1)): sites.setdefault(f, []).append(m.group(2))
    for m in re.finditer(r'\.callIf \(\.n \d+\) "([^"]+)" \[([^\]]*)\]', body):
        sites.setdefault(m.group(1), []).append(m.group(2))
    for m in re.finditer(r'\.call "([^"]+)" \[([^\]]*)\]', body):
        sites.setdefault(m.group(1), []).append(m.group(2))
    F = sel.residuals(); fams = []
    for f in sorted(sites, key=lambda f: stable[f]):
        ns = stable[f]
        if not any(r[0] == 'sub' for rs in F.get(ns, {}).values() for r in rs): continue
        ks = set()
        for a in sites[f]:
            args = [x.strip() for x in a.split(',')]
            ks.add((args.index('.n %d' % UE), args.index('.n %s' % w)))
        assert len(ks) == 1, (f, ks)
        fams.append((ns,) + ks.pop())
    return fams, int(w), int(c)


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/link.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def render():
    fams, w, c = link(); files = {}
    n = coreCount()
    ranges = [(a, (n - a) if m is None else m) for a, m in RANGES]
    assert sum(m for _, m in ranges) == n
    mod = 'LeanVM.Guest.Res.AnyData'
    t = [header(mod, 'The callees reading `child_claim_list_any`\'s entries table.')]
    t.append('public import LeanVM.Guest.Res.LinkDefs\n\nnamespace LeanVM.Guest.Res\n\nopen LeanVM.Guest LeanVM.Guest.Core\n\n'
             '@[expose] public section\n\n/-- **The callees reading `child_claim_list_any`\'s entries table.** -/\n'
             'noncomputable def anyLink : Link := ⟨[\n  %s],\n  fn_idx%% «%s», name%% «%s», .n %d, .n %d, .n %d, .n %d⟩\n\n'
             'end\n\nend LeanVM.Guest.Res\n' % (',\n  '.join('(name%% «%s», %d, %d)' % F for F in fams),
                                                ORIGIN, ORIGIN, UE, UL, w, c))
    files[mod] = ''.join(t)
    mods = []
    for k, (a, m) in enumerate(ranges):
        mod = 'LeanVM.Guest.Res.AnyCallers%d' % k
        t = [header(mod, 'The callers\' check of `anyLink`, functions %d to %d.' % (a, a + m - 1))]
        t.append('public import LeanVM.Guest.Res.AnyData\n\nnamespace LeanVM.Guest.Res\n\nopen LeanVM.Guest.Memory\n\n'
                 'public section\n\ntheorem anyCallers_%d : RangeOk (fun _ fn => callersB anyLink fn) %d %d := by\n'
                 '  unfold RangeOk; decide +kernel\n\nend\n\nend LeanVM.Guest.Res\n' % (a, a, m))
        files[mod] = ''.join(t); mods.append(mod)
    G = term.groups(); pack = {}
    for g in G:
        for p in g:
            for nm in term.packCerts(p): pack[nm] = p
    mod = 'LeanVM.Guest.Res.AnyOk'
    t = [header(mod, '`anyLink`\'s checks, its callees\' `sub` residuals all reads, and `ResTop guestCerts`.')]
    t.append(''.join('public import %s\n' % m for m in mods))
    t.append('public import LeanVM.Guest.EndExecRA\npublic import LeanVM.Guest.Res.ResCerts\n\n'
             'namespace LeanVM.Guest.EndExec\n\nopen LeanVM.Guest LeanVM.Guest.Mode LeanVM.Guest.Res LeanVM.Guest.Memory\n\n'
             'public section\n\n')
    app = 'anyCallers_0'
    for a, m in ranges[1:]: app = '(%s.append anyCallers_%d)' % (app, a)
    t.append('/-- **The callers\' check of `anyLink`, every function.** -/\n'
             'theorem anyCallers_all : RangeOk (fun _ fn => callersB anyLink fn) 0 coreProgram.length := by\n'
             '  have h := %s\n  rw [coreProgram_length]\n  exact h\n\n' % app)
    t.append('/-- **`anyLink`\'s checks.** -/\ntheorem anyLink_ok : LinkOk anyLink where\n'
             '  idx := by decide +kernel\n  origin := by decide +kernel\n'
             '  fams := List.all_eq_true.mp (show anyLink.fams.all calleeB = true by decide +kernel)\n'
             '  callers := rangeOk_all anyCallers_all\n'
             '  main := fun F hF ↦ of_decide_eq_true (List.all_eq_true.mp\n'
             '    (show anyLink.fams.all (fun F ↦ decide (F.1 ≠ "main")) = true by decide +kernel) F hF)\n\n')
    t.append('/-- **The residuals at the honest frames**, for the mode walk\'s certificates: from the listed\n'
             'certificates\', the `sub` residuals\' but the splits\' and `anyLink`\'s reads, and the listed\n'
             'parameters\' nonzero values. -/\n'
             'theorem resTop_guestA {A : String → Bridge.FnAl} (hexc : ∀ K ∈ resExc, ResCert A K)\n'
             '    (hsub : ResOpen guestCerts A fun j x ↦ ((∃ a bs, x = .sub a bs) ∧ splitB j x = false) ∧\n'
             '      anyResB anyLink j x = false)\n'
             '    (hnz : ∀ p ∈ nzVals, NzVal p.1 p.2) : ResTop guestCerts A :=\n'
             '  resTop_guest hexc (resOpen_any anyLink_ok hsub) hnz\n\nend\n\nend LeanVM.Guest.EndExec\n')
    files[mod] = ''.join(t)
    mod = 'LeanVM.Guest.Res.AnyDone'
    t = [header(mod, 'Every `sub` residual of `anyLink`\'s callees is a read inside the caller\'s table.')]
    t.append(''.join('public import LeanVM.Guest.Pack.«%s».ModeCert\n' % p for p in sorted({pack[F[0]] for F in fams})))
    t.append('public import LeanVM.Guest.Res.AnyData\n\nnamespace LeanVM.Guest.EndExec\n\n'
             'open LeanVM.Guest LeanVM.Guest.Mode LeanVM.Guest.Res\n\npublic section\n\n')
    t.append('/-- **Each callee\'s `sub` residuals are reads inside the caller\'s table.** -/\n'
             'theorem anyLink_done : ∀ K ∈ [%s],\n    ∃ j, (fnOf j).entryPc = K.F.entry ∧ allV (fun l ↦ l.all (subDone anyLink j)) K.F.res = true :=\n  %s\n\n' % (
                 ', '.join('Fn.«%s».modeCert' % F[0] for F in fams),
                 term.chain(['⟨fn_idx%% «%s», by decide +kernel⟩' % F[0] for F in fams])))
    t.append('end\n\nend LeanVM.Guest.EndExec\n')
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'AnyCallers*.lean')):
        if p not in files:
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('AnyLink: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
