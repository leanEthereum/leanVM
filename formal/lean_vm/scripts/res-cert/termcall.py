"""Writes `Guest/Res/TermCallers{k}.lean` and `TermCallers.lean`: the callers' check of
`check_opening_terminal` and the `column_selector` specializations over the whole program by ranges
(`Res.termCallers`, `Res.callersG`), the ranges `link.py`'s.
`--check` writes nothing and fails when a file differs.
Usage: python3 -I scripts/res-cert/termcall.py [--check]"""
import sys, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import term
import link

OUT = term.OUT


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/termcall.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def render():
    files = {}
    n = link.coreCount()
    ranges = [(a, (n - a) if m is None else m) for a, m in link.RANGES]
    mods = []
    for k, (a, m) in enumerate(ranges):
        mod = 'LeanVM.Guest.Res.TermCallers%d' % k
        t = [header(mod, 'The callers\' check of `termCallers`, functions %d to %d.' % (a, a + m - 1))]
        t.append('public import LeanVM.Guest.Res.MonoDefs\npublic import LeanVM.Guest.Res.TermDefs\n\n'
                 'namespace LeanVM.Guest.Res\n\nopen LeanVM.Guest.Memory\n\n'
                 'public section\n\ntheorem termCallers_%d : RangeOk (fun _ fn => callersG termCallers fn) %d %d := by\n'
                 '  unfold RangeOk; decide +kernel\n\nend\n\nend LeanVM.Guest.Res\n' % (a, a, m))
        files[mod] = ''.join(t); mods.append(mod)
    mod = 'LeanVM.Guest.Res.TermCallers'
    t = [header(mod, 'The callers\' check of `termCallers`, every function.')]
    t.append(''.join('public import %s\n' % m for m in mods))
    t.append('public import LeanVM.Guest.Res.LinkDefs\n\nnamespace LeanVM.Guest.Res\n\n'
             'open LeanVM.Guest LeanVM.Guest.Core LeanVM.Guest.Memory\n\npublic section\n\n')
    app = 'termCallers_0'
    for a, m in ranges[1:]: app = '(%s.append termCallers_%d)' % (app, a)
    t.append('/-- **The callers\' check of `termCallers`, every function.** -/\n'
             'theorem termCallers_all : ∀ fn ∈ coreProgram, callersG termCallers fn = true := by\n'
             '  have h := %s\n  exact rangeOk_all (by rw [coreProgram_length]; exact h)\n\nend\n\n'
             'end LeanVM.Guest.Res\n' % app)
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'TermCallers*.lean')):
        if p not in files:
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('TermCallers: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
