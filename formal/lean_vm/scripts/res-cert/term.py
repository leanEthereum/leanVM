"""Writes `Guest/Res/TermCerts*.lean`: every mode walk certificate's termination facts are its
function's loop shape's (`EndExec.TermOk`, decided at the function's index by `termOkB`), and
`TermNode guestCerts`. The certificates, their packs and groups are `Mode/Certs/List.lean`'s, each
pack's in `Pack/*/ModeCert.lean`'s order, each one's function index its `FnLink`'s in `Mode/Certs/Sig*.lean`.
`--check` writes nothing and fails when a file differs.
Usage: python3 -I scripts/res-cert/term.py [--check]"""
import sys, os, re, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', 'LeanVM', 'Guest'))
OUT = os.path.join(ROOT, 'Res')


def groups():
    t = open(os.path.join(ROOT, 'Mode', 'Certs', 'List.lean')).read()
    blk = t[t.index('def guestGroups'):t.index('def guestPacks')]
    return [re.findall(r'ModePack\.«([^»]+)»\.certs', g) for g in blk.split('[')[2:]]


def packCerts(p):
    t = open(os.path.join(ROOT, 'Pack', p, 'ModeCert.lean')).read()
    blk = t[t.index('noncomputable def certs : List Mode.Cert :='):]
    blk = blk[:blk.index('\n\n')]
    return re.findall(r'Fn\.«([^»]+)»\.modeCert', blk)


def packIdx():
    out = {}
    for f in glob.glob(os.path.join(ROOT, 'Mode', 'Certs', 'Sig*.lean')):
        t = open(f).read()
        for m in re.finditer(r'namespace LeanVM\.Guest\.ModePack\.«([^»]+)»\n(.*?)\nend LeanVM', t, re.S):
            c = m.group(2)[m.group(2).index('theorem certs_fn'):]
            out[m.group(1)] = [int(x) for x in re.findall(r'Checked\.code(\d+)', c[:c.index('\n\n')])]
    return out


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/term.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def chain(ps, ind='    '):
    out = 'Mode.fa_nil'
    for q in reversed(ps): out = 'Mode.fa_cons (%s)\n%s(%s)' % (q, ind, out)
    return out


def render():
    G = groups(); idx = packIdx(); files = {}; mods = []
    for k, g in enumerate(G):
        mod = 'LeanVM.Guest.Res.TermCerts%d' % k
        t = [header(mod, 'Each certificate\'s termination facts are its loop shape\'s (`EndExec.TermOk`), pack by pack.')]
        t.append('public import LeanVM.Guest.EndExecRT\npublic import LeanVM.Guest.Mode.Certs.List\n\n'
                 'set_option Elab.async false\n')
        for p in g:
            ns = packCerts(p); js = idx[p]
            assert len(ns) == len(js), p
            t.append('\nnamespace LeanVM.Guest.ModePack.«%s»\n\nopen LeanVM.Guest LeanVM.Guest.EndExec\n\n'
                     'public section\n\ntheorem certs_term : ∀ K ∈ certs, TermOk K :=\n  %s\n\nend\n\n'
                     'end LeanVM.Guest.ModePack.«%s»\n' % (
                         p, chain(['termOk_of (j := %d) (by decide +kernel)' % j for j in js]), p))
        files[mod] = ''.join(t); mods.append(mod)
    mod = 'LeanVM.Guest.Res.TermCerts'
    t = [header(mod, '`TermNode guestCerts`: the termination facts of the entered instances.')]
    t.append(''.join('public import %s\n' % m for m in mods))
    t.append('\nset_option Elab.async false\n\nnamespace LeanVM.Guest.EndExec\n\nopen LeanVM.Guest LeanVM.Guest.Mode\n\n'
             'public section\n\n/-- **Every certificate\'s termination facts are its loop shape\'s.** -/\n'
             'theorem guestCerts_term : ∀ K ∈ guestCerts, TermOk K :=\n  fa_flatten (fa_flatten (%s))\n\n' % chain(
                 ['(%s)' % chain(['ModePack.«%s».certs_term' % p for p in g]) for g in G]))
    t.append('/-- **The termination facts of the entered honest instances**, for the mode walk\'s certificates. -/\n'
             'theorem termNode_guest : TermNode guestCerts := termNode_of guestCerts_term\n\nend\n\nend LeanVM.Guest.EndExec\n')
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'TermCerts*.lean')):
        if p not in files:
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('TermCerts: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
