"""Writes `Guest/Res/CarryCallers{k}.lean` and `CarryOk.lean`: the carried facts' check (`Res.carryG`:
every call site passes the listed callees' carried facts, every heap witness pointer its spine does not
pin is in `K` by the carried values) over the whole program by ranges, and its conjunction. The listed
parameters are `Res.carried` (`Res/CarryDefs.lean`). `--check` writes nothing and fails when a file
differs.
Usage: python3 -I scripts/res-cert/carry.py [--check]"""
import sys, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import term
import link

OUT = term.OUT
# by ranges of functions, each a kernel check; `main` (function 0) alone
RANGES = [(0, 1), (1, 19), (20, 10), (30, 10), (40, 60), (100, 300), (400, 400), (800, 400), (1200, 200), (1400, None)]


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/carry.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def render():
    files = {}
    n = link.coreCount()
    ranges = [(a, (n - a) if m is None else m) for a, m in RANGES]
    assert sum(m for _, m in ranges) == n
    mods = []
    for k, (a, m) in enumerate(ranges):
        mod = 'LeanVM.Guest.Res.CarryCallers%d' % k
        t = [header(mod, 'The carried facts\' check, functions %d to %d.' % (a, a + m - 1))]
        t.append('public import LeanVM.Guest.Res.CarryDefs\n\nnamespace LeanVM.Guest.Res\n\nopen LeanVM.Guest.Memory\n\n'
                 'public section\n\ntheorem carry_%d : RangeOk (fun _ fn => carryG fn) %d %d := by\n'
                 '  unfold RangeOk; decide +kernel\n\nend\n\nend LeanVM.Guest.Res\n' % (a, a, m))
        files[mod] = ''.join(t); mods.append(mod)
    mod = 'LeanVM.Guest.Res.CarryOk'
    t = [header(mod, 'The carried facts\' check, every function.')]
    t.append(''.join('public import %s\n' % m for m in mods))
    t.append('public import LeanVM.Guest.Res.LinkDefs\n')
    t.append('\nnamespace LeanVM.Guest.Res\n\nopen LeanVM.Guest LeanVM.Guest.Memory\n\npublic section\n\n')
    app = 'carry_0'
    for a, m in ranges[1:]: app = '(%s.append carry_%d)' % (app, a)
    t.append('/-- **The carried facts\' check, every function.** -/\n'
             'theorem carry_all : ∀ fn ∈ coreProgram, carryG fn = true := by\n'
             '  have h := %s\n'
             '  have h\' : RangeOk (fun _ fn => carryG fn) 0 coreProgram.length := by\n'
             '    rw [coreProgram_length]; exact h\n  exact rangeOk_all h\'\n\nend\n\nend LeanVM.Guest.Res\n' % app)
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'CarryCallers*.lean')):
        if p not in files:
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('Carry: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
