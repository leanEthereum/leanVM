"""Writes `Guest/Res/ResCerts*.lean`: every mode walk certificate's residuals are in the families
(`Res.ResOk`, decided at the function's index by `Res.resOk_of`), but the certificates of `EXC`;
and `ResTop guestCerts` from them (`EndExec.resTop_of_ok`). `Guest/Res/ResGiven.lean` lists `EXC`'s
certificates (`resExc`) and the parameters whose nonzero values the divisor residuals need
(`nzVals`: each `nz o` residual's parameter `o - 2`, but a loop helper's counter). The
certificates, their packs, groups and function indices are those `term.py` reads, the residuals
the walks' checks `mode-cert/gen.py` wrote (`Pack/*/Mode{k}.lean`, `ModeD{k}.lean`, `ModeX.lean`).
`--check` writes nothing and fails when a file differs.
Usage: python3 -I scripts/res-cert/sel.py [--check]"""
import sys, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import term
sys.path.insert(0, os.path.join(HERE, '..', 'mode-cert'))
import res as R
import data

OUT = term.OUT
# the certificates whose residuals the families leave: `claim_list_digest`'s dispatch sits in a branch,
# `certify_placement`'s divisor is no parameter
EXC = ['claim_list_digest', 'certify_placement']


def residuals():
    """Each walk's residuals {offset: [res]}, by its function's stable name."""
    import re
    fns = {}
    for path in sorted(glob.glob(os.path.join(R.PACKS, '*', 'Mode*.lean'))):
        b = os.path.basename(path)[:-5]
        if not re.fullmatch(r'Mode\d+|ModeD\d+|ModeX', b): continue
        t = open(path).read()
        for blk in t.split('\nnamespace LeanVM.Guest.Fn.«')[1:]:
            n = blk.split('»', 1)[0]
            if 'def modeFun' not in blk: continue
            defs = R.defsOf(blk)
            fns[n] = {i: [R.res(r, defs) for r in R.flat(l, defs)]
                      for i, l in R.trie(defs['modeFun'][1][4], defs).items()}
    return fns


def nzVals():
    """The parameters `(function, k)` whose nonzero values the divisor residuals need."""
    F = residuals(); D = data.load()
    core = {f['ns']: f['name'] for f in D['fns'].values()}
    out = []
    for n in sorted(F):
        if n in EXC: continue
        for o in sorted({r[1] for rs in F[n].values() for r in rs if r[0] == 'nz'}):
            if core[n].startswith('__loop') and o == 2: continue
            out.append((core[n], o - 2))
    return out


def header(mod, what):
    return '/-\n  %s\n\n  Generated by `scripts/res-cert/sel.py`; do not edit.\n  %s\n-/\n\nmodule\n\n' % (mod, what)


def render():
    G = term.groups(); idx = term.packIdx(); files = {}; mods = []
    pack = {}
    for g in G:
        for p in g:
            for n in term.packCerts(p): pack[n] = p
    mod = 'LeanVM.Guest.Res.ResGiven'
    t = [header(mod, 'The certificates whose residuals are given whole, and the parameters given nonzero.')]
    t.append(''.join('public import LeanVM.Guest.Pack.«%s».ModeCert\n' % p for p in sorted({pack[n] for n in EXC})))
    t.append('public import LeanVM.Guest.Res.SelDefs\n\nnamespace LeanVM.Guest.Res\n\nopen LeanVM.Guest LeanVM.Guest.Core\n\n'
             '@[expose] public section\n\n/-- The certificates whose residuals are given whole. -/\n'
             'noncomputable def resExc : List Mode.Cert := [\n  %s]\n\n'
             '/-- The parameters whose nonzero values the divisor residuals need, by function. -/\n'
             'def nzVals : List (String × V) := [\n  %s]\n\nend\n\nend LeanVM.Guest.Res\n' % (',\n  '.join(
                 'Fn.«%s».modeCert' % n for n in EXC), ',\n  '.join('("%s", .n %d)' % p for p in nzVals())))
    files[mod] = ''.join(t)
    for k, g in enumerate(G):
        mod = 'LeanVM.Guest.Res.ResCerts%d' % k
        t = [header(mod, 'Each certificate\'s residuals are in the families (`Res.ResOk`), pack by pack.')]
        t.append('public import LeanVM.Guest.Res.ResGiven\npublic import LeanVM.Guest.Mode.Certs.List\n\n'
                 'set_option Elab.async false\n')
        for p in g:
            ns = term.packCerts(p); js = idx[p]
            assert len(ns) == len(js), p
            t.append('\nnamespace LeanVM.Guest.ModePack.«%s»\n\nopen LeanVM.Guest LeanVM.Guest.Res\n\n'
                     'public section\n\ntheorem certs_res : ∀ K ∈ certs, ResOk resExc nzVals K :=\n  %s\n\nend\n\n'
                     'end LeanVM.Guest.ModePack.«%s»\n' % (p, term.chain([
                         ('resOk_exc (by simp [resExc])' if n in EXC else
                          'resOk_of (j := %d) (by decide +kernel)' % j) for n, j in zip(ns, js)]), p))
        files[mod] = ''.join(t); mods.append(mod)
    mod = 'LeanVM.Guest.Res.ResCerts'
    t = [header(mod, '`ResTop guestCerts alignA` from the families\' and the listed certificates\' residuals.')]
    t.append(''.join('public import %s\n' % m for m in mods))
    t.append('public import LeanVM.Guest.EndExecRSplit\n')
    t.append('\nset_option Elab.async false\n\nnamespace LeanVM.Guest.EndExec\n\nopen LeanVM.Guest LeanVM.Guest.Mode '
             'LeanVM.Guest.Res\n\npublic section\n\n/-- **Every certificate\'s residuals are in the families.** -/\n'
             'theorem guestCerts_res : ∀ K ∈ guestCerts, ResOk resExc nzVals K :=\n  fa_flatten (fa_flatten (%s))\n\n' % term.chain(
                 ['(%s)' % term.chain(['ModePack.«%s».certs_res' % p for p in g]) for g in G]))
    t.append('/-- **The residuals at the honest frames**, for the mode walk\'s certificates: from the listed\n'
             'certificates\', the `sub` residuals\' but the splits\', the exponent facts\' order residuals and the listed\n'
             'parameters\' nonzero values. -/\n'
             'theorem resTop_guest {A : String → Bridge.FnAl} (hexc : ∀ K ∈ resExc, ResCert A K)\n'
             '    (hsub : ResOpen guestCerts A fun j x ↦ (∃ a bs, x = .sub a bs) ∧ splitB j x = false)\n'
             '    (hexp : ResOpen guestCerts A fun j x ↦ ltExpB j x = true)\n'
             '    (hnz : ∀ p ∈ nzVals, NzVal p.1 p.2) : ResTop guestCerts A :=\n'
             '  resTop_of_ok guestCerts_res hexc splits_ok hsub hexp hnz\n\nend\n\nend LeanVM.Guest.EndExec\n')
    files[mod] = ''.join(t)
    return {os.path.join(OUT, m.split('.')[-1] + '.lean'): v for m, v in files.items()}


def main(argv):
    files = render(); bad = []
    for p in glob.glob(os.path.join(OUT, 'ResCerts*.lean')) + glob.glob(os.path.join(OUT, 'ResExc.lean')) + glob.glob(os.path.join(OUT, 'ResGiven.lean')):
        if p not in files:
            bad.append(p)
            if '--check' not in argv: os.remove(p)
    for p, text in sorted(files.items()):
        old = open(p).read() if os.path.exists(p) else None
        if old == text: continue
        bad.append(p)
        if '--check' not in argv: open(p, 'w').write(text)
    if '--check' in argv and bad: print('stale:', *bad, sep='\n  '); sys.exit(1)
    print('ResCerts: %d files, %s' % (len(files), 'unchanged' if not bad else ('stale' if '--check' in argv else 'written')))


if __name__ == '__main__':
    main(sys.argv[1:])
