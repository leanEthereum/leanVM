def write_fast(g):
    D = os.path.join(g.lv, 'LeanVM', 'Guest', 'Count')
    for f in os.listdir(D):
        if re.fullmatch(r'FastChk\d+\.lean|FastData\.lean', f): os.remove(os.path.join(D, f))
    path = os.path.join(D, 'Fast.lean')
