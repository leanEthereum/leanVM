GENBY = 'Generated by `scripts/count/hand.py`; do not edit.'
family.GENBY = GENBY

LRS = 'level_residual_sum'
# Counting words (`α`); `cycles.py` sets it false, its frame weights an opcode's.
ALPHA = True


def defmap(ss, out):
    for s in ss:
        if s[0] == 'atom' and s[1] in ('const', 'add', 'mul', 'copy'): out.setdefault(s[2][0], s)
        elif s[0] == 'ite': defmap(s[2], out); defmap(s[3], out)
        elif s[0] == 'match':
            for a in s[2]: defmap(a, out)
        elif s[0] == 'call':
            for r in s[3]: out.setdefault(r, ('ret', s[1]))
        elif s[0] == 'dispatch':
            for r in s[4]: out.setdefault(r, ('dret', s[2][0]))
    return out


def show(fn, dm, v, d=0):
    if d > 6: return '..'
    if v in fn['params']: return 'P%d' % fn['params'].index(v)
    x = dm.get(v)
    if x is None: return 'v%d' % v
    if x[0] in ('ret', 'dret'): return 'v%d<-%s' % (v, x[1])
    if x[1] == 'const':
        e = checker.word_exp(x[2][1])
        return 'g^%s' % e if e is not None else 'k%s' % (x[2][1][0],)
    if x[1] == 'copy': return show(fn, dm, x[2][1], d + 1)
    op = '*' if x[1] == 'mul' else '+'
    return '(%s%s%s)' % (show(fn, dm, x[2][1], d + 1), op, show(fn, dm, x[2][2], d + 1))


class AnyRun:
    """Every loop may run no iteration: each `callIf` guard whose end is a parameter is kept (`guardAtom`), so a
    loop's run asks only `start <= end` (`siteBL`)."""
    def __contains__(self, q): return True


checker.const_args = lambda fns: AnyRun()


class Hands:
    def __init__(self, g, zero, om=None):
        self.g = g
        self.fns = g.fns
        self.om = g.om if om is None else om
        self.by = {f['name']: i for i, f in self.fns.items()}
        self.absent = {f['name'] for f in self.fns.values() if f['name'].startswith(LRS)} if zero else set()
        ab = {n: ('stat', [], (0, []), []) for n in self.absent}
        _, self.cert = checker.gen(self.fns, self.om, alpha=ALPHA, hand=ab)
        self.hand = [self.fns[i]['name'] for i in range(g.N) if self.fns[i]['name'] not in self.cert]

    def fn(self, name): return self.fns[self.by[name]]

    # --- virtual parameters: the values a failing size, loop end or callee argument comes from ---
    def chase(self, fn, dm, v, vps):
        """Append to `vps` what bounds `v`: itself, or the values a product `x·x`, `x·g^c` or `x·y` of it reads."""
        if v in fn['params'] or v in vps: return
        d = dm.get(v)
        if d is not None and d[0] == 'atom' and d[1] == 'const': return
        if d is not None and d[0] == 'atom' and d[1] == 'copy': return self.chase(fn, dm, d[2][1], vps)
        if d is not None and d[0] == 'atom' and d[1] == 'mul':
            _, x, y = d[2]
            dy = dm.get(y); dx = dm.get(x)
            if x == y: return self.chase(fn, dm, x, vps)
            isc = lambda dz: dz is not None and dz[0] == 'atom' and dz[1] == 'const' and \
                checker.word_exp(dz[2][1]) is not None
            if isc(dy): return self.chase(fn, dm, x, vps)
            if isc(dx): return self.chase(fn, dm, y, vps)
            if (dy is not None and dy[0] == 'atom' and dy[1] == 'const') or \
                    (dx is not None and dx[0] == 'atom' and dx[1] == 'const'):
                vps.append(v); return
            ok = lambda z: z in fn['params'] or z in vps or \
                (dm.get(z) is not None and dm[z][0] == 'atom' and dm[z][1] in ('mul', 'const', 'copy'))
            if ok(x) and ok(y):
                self.chase(fn, dm, x, vps); self.chase(fn, dm, y, vps); return
        vps.append(v)

    def fails(self, cx, rho, ss, out):
        """The statements of a block the checker fails on, each branch walked."""
        for s in ss:
            t = s[0]
            if t == 'atom':
                r = checker.atomB(cx, rho, s)
                if r is None: out.append(('atom', s)); return out
                rho = r[1]
            elif t == 'ite': self.fails(cx, rho, s[2], out); self.fails(cx, rho, s[3], out)
            elif t == 'match':
                for a in s[2]: self.fails(cx, rho, a, out)
            elif t == 'call':
                if checker.siteB(cx, rho, s[1], s[2]) is None: out.append(('call', s))
            elif t == 'callIf':
                if checker.siteBC(cx, rho, s[1], s[2], s[3]) is None: out.append(('callIf', s))
            elif t == 'dispatch':
                if checker.maxB(lambda h: checker.siteB(cx, rho, h, s[3]), s[2]) is None: out.append(('dispatch', s))
            elif t == 'ret': return out
        return out

    def ctx(self, fn, ps, certs):
        """The checker's context for `fn` over parameters `ps`, its constants as `gen` picks them."""
        fn2 = dict(fn); fn2['params'] = ps
        fns2 = dict(self.fns); fns2[self.by[fn['name']]] = fn2
        seen = {}
        init = checker.Ctx.__init__
        def spy(c, *a, **k):
            init(c, *a, **k)
            if c.self == fn['name']: seen['cx'] = c
        checker.Ctx.__init__ = spy
        try:
            hand = {k: v for k, v in certs.items() if k != fn['name']}
            _, c2 = checker.gen(fns2, self.om, alpha=ALPHA, hand=hand, only={fn['name']})
        finally:
            checker.Ctx.__init__ = init
        return c2.get(fn['name']), seen.get('cx')

    def body(self, fn):
        """The statements a hand check walks: a loop helper's iteration (`loopShape`), else the body."""
        if fn['name'].startswith('__loop'):
            for endc in (None, checker.const_end(fn)):
                pre = checker.loop_shape(fn, endc)
                if pre is not None: return pre, endc
            raise ValueError('%s: no loop shape' % fn['name'])
        return fn['body'], None

    def inner(self, name, certs):
        """`name`'s virtual parameters and inner certificate, its callees' certificates `certs`."""
        fn = self.fn(name); dm = defmap(fn['body'], {})
        ss, endc = self.body(fn)
        vps = []
        for _ in range(8):
            ps = fn['params'] + vps
            if endc is not None or name.startswith('__loop'):
                _, cx = self.ctx(dict(fn, body=ss + [('ret', [])]), ps, certs)
                cx = checker.Ctx(certs, cx.ks, ps, name, ALPHA, self.om)
                r = checker.blockB(cx, ([], []), ss)
                if r is not None:
                    return vps, ('stat', checker.dedup(r[2]), (self.om[name] + r[0], r[1]), cx.ks), ss, endc
            else:
                c, cx = self.ctx(fn, ps, certs)
                if c is not None: return vps, c, ss, endc
            out = self.fails(cx, ([], []), ss, [])
            new = False
            for kind, s in out:
                if kind == 'atom' and s[1] == 'allocDyn':
                    n0 = len(vps); self.chase(fn, dm, s[2], vps); new |= len(vps) > n0
                elif kind == 'callIf':
                    for a in s[3][:2]:
                        n0 = len(vps); self.chase(fn, dm, a, vps); new |= len(vps) > n0
                elif kind in ('call', 'dispatch'):
                    gs = [s[1]] if kind == 'call' else s[2]
                    args = s[2] if kind == 'call' else s[3]
                    for h in gs:
                        c = certs.get(h)
                        if c is None: raise ValueError('%s: callee %s has no certificate' % (name, h))
                        b, pre = (c[2], c[1]) if c[0] == 'stat' else (c[3], c[2])
                        idx = [k for k, _ in b[1]] + [k for k, _ in pre] + ([0, 1] if c[0] == 'loop' else [])
                        for k in idx:
                            if k < len(args) and args[k] not in ps and args[k] not in vps:
                                dd = dm.get(args[k])
                                if dd is not None and dd[0] == 'atom' and dd[1] == 'const' and \
                                        checker.word_exp(dd[2][1]) is not None: continue
                                vps.append(args[k]); new = True
                else: raise ValueError('%s: stuck at %s %s' % (name, kind, str(s)[:150]))
            if not new: raise ValueError('%s: no virtual parameter found: %s' % (name, [(k, str(s)[:100]) for k, s in out]))
        raise ValueError('%s: too many rounds' % name)

    def order(self):
        """The hand functions, callees first."""
        hs = set(self.hand); out = []; seen = set()

        def topo(n):
            if n in seen: return
            seen.add(n)
            for h in sorted(checker.callees(self.fn(n)['body'], set())):
                if h in hs and h != n: topo(h)
            out.append(n)
        for n in self.hand: topo(n)
        return out


def ceil_div(a, b): return -(-a // b)


def terms_of(c):
    t = {}
    for k, x in c[2][1]: t[k] = t.get(k, 0) + x
    return t


def pos_totals(fn):
    """`open_stacked`'s positions totals by rate: the constants stored to `pos_totals` after its `alloc`."""
    body = fn['body']
    i = next(i for i, s in enumerate(body) if s == ('atom', 'alloc', 4))
    out = []
    for s in body[i + 1:]:
        if s[0] == 'atom' and s[1] == 'const': out.append(checker.word_exp(s[2][1]))
        elif s[0] == 'atom' and s[1] == 'load': continue
        else: break
    assert len(out) == 4 and all(e is not None for e in out), (fn['name'], out)
    return out


# A count's quotient `q = count / d` by its count: the virtual parameter, the count's parameter and `d`.
SPLIT_OF = {'squeeze_packed': {7: (6, 4)}, 'rs_eq_run': {4: (2, 8)}, 'ring_rows': {5: (4, 8)}}


# A child's shape at its largest (`verify_sub`'s range checks): stream chunks, link permutations,
# pointer width, tallest table, Keccak table log; `q_keccak`'s slot log.
VS_MAX = {'c': 32, 'p': 19, 'w': 24, 'n': 24, 'tau': 24}
TAU_MAX = 24
QKECCAK_SLOT_LOG = 6
# `verify_sub`'s virtual parameters, by the callee they are passed to.
VS_USE = {'hint_stream': 'c', 'squeeze_packed': 'p', 'link_rounds__L1_L0': 'w', 'link_row_side__L6': 'n',
          'link_row_side__L7': 'n', 'link_row_side__L8': 'n', 'link_row_side__L9': 'n',
          'check_stack_terminal': 'n', 'verify_keccak': 'tau'}
# The functions whose outer bound is the node's (`main` their only caller): a symbolic constant, zero here.
SYMBOLIC = ('da_verify', '__loop4_main')


def vs_use(fn, k):
    """What `verify_sub`'s virtual parameter `k` is: the first callee it is passed to."""
    v = VPS[fn['name']][k - len(fn['params'])]
    for s in checker.stmts_all(fn['body']):
        if s[0] == 'call' and v in s[2] and s[1] in VS_USE: return VS_USE[s[1]]
        if s[0] == 'dispatch' and v in s[3] and s[2][0] in VS_USE: return VS_USE[s[2][0]]
    raise ValueError('verify_sub: virtual parameter v%d passed to no known callee' % v)


VPS = {}


def outer_of(name, fn, c, shape):
    """The outer certificate a hand function's callers see: its inner bound with each virtual parameter
    bounded by its parameters or a constant; `None` where the outer bound is not by parameters."""
    np_ = len(fn['params'])
    if name in SYMBOLIC or name == 'main': return ('stat', [], (0, []), [])
    t = terms_of(c)
    const = c[2][0]
    out = {}
    def add(k, x): out[k] = out.get(k, 0) + x
    for k, x in t.items():
        if k < np_: add(k, x); continue
        if name.startswith('link_rounds__'): add(8, ceil_div(x, 4)); continue
        if name in SPLIT_OF: p, d = SPLIT_OF[name][k]; add(p, ceil_div(x, d)); continue
        if name == 'child_claim_list_digest':
            if k == 5: add(4, ceil_div(x, 136))
            else: const += 7 * x
            continue
        if name == 'claim_list_digest':
            if k == 2: add(1, ceil_div(x, 136))
            else: const += 7 * x
            continue
        if name == 'verify_keccak': add(6, x); continue
        if name.startswith('open_stacked__'): const += x * max(pos_totals(fn)); continue
        if name == 'check_stack_terminal': const += x * (TAU_MAX + QKECCAK_SLOT_LOG); continue
        if name == 'verify_sub': const += x * VS_MAX[vs_use(fn, k)]; continue
        return None
    return ('stat', [], (const, sorted(out.items())), [])


def lean_hand(h):
    """A hand (`Hand`): its virtual parameters and inner certificate's preconditions, bound and constants."""
    vps, c = h
    return '⟨[%s], %s, %s, %s⟩' % (', '.join('.n %d' % v for v in vps), writelean.lean_pairs(c[1]),
                                     writelean.lean_aff(c[2]), writelean.lean_ks(c[3]))


def solve(H, report=False):
    """Every function's certificate, the hand functions' inner checks (virtual parameters, inner certificate) and
    the loop hands' (and their ends), callees first."""
    certs = dict(H.cert)
    for n in H.absent: certs[n] = ('stat', [], (0, []), [])
    hands, loops = {}, {}
    for name in H.order():
        vps, c, ss, endc = H.inner(name, certs)
        VPS[name] = vps
        fn = H.fn(name)
        loop = name.startswith('__loop')
        if report:
            dm = defmap(fn['body'], {})
            print('== %s params %d frame %d%s' % (name, len(fn['params']), H.om[name], ' loop' if loop else ''))
            for j, v in enumerate(vps): print('   vp %d (v%d) = %s' % (len(fn['params']) + j, v, show(fn, dm, v)))
            print('   inner %d + %s   pre %s' % (c[2][0], terms_of(c), c[1]))
        if loop: loops[name] = (vps, c, endc)
        elif vps or name in SYMBOLIC or name == 'main': hands[name] = (vps, c)
        if not vps and not loop and name not in SYMBOLIC and name != 'main':
            certs[name] = c
        else:
            o = outer_of(name, fn, c, None)
            if o is None: raise ValueError('%s: no outer bound' % name)
            certs[name] = o
        if report: print('   outer %s' % (certs[name][1:3],))
    return certs, hands, loops


def walk_cost(H, name, body):
    sp = checker.SPLIT.get(name)
    return 0.1 + family.walk_cost(body) + (
        sum(family.walk_cost(checker.sel_body(body, sp[0], r)) for r in range(sp[1])) if sp else 0)


def write(H, fam, pre, certs, hands, loops):
    """`Memory/<fam>/`: the family's data, its checks by ranges (`<pre>Range_<a>`) and `<pre>_all`."""
    fns, N, om = H.fns, H.g.N, H.om
    D = os.path.join(H.g.LD, fam)
    os.makedirs(D, exist_ok=True)
    for f in glob.glob(os.path.join(D, '*.lean')): os.remove(f)
    mod = 'LeanVM.Guest.Memory.%s' % fam
    idx = {fns[i]['name']: i for i in range(N)}
    assert len(loops) <= 1, loops
    data = family.header('%s.Data' % mod, 'The certificates counting the guest\'s words with its hand functions, by core '
                         'index: the certificates, the hands\' inner checks, the loop hand\'s, the absent functions.',
                         'public import LeanVM.Guest.Memory.FamilyHand\npublic import LeanVM.Guest.Memory.GuestWordsA.Data\n')
    data += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\n@[expose] public section\n\n'
    data += family.tree_defs('%scertT' % pre, 'Cert', [(i, certs[fns[i]['name']]) for i in range(N)],
                             writelean.lean_cert, 'The certificates, by index.') + '\n'
    data += family.tree_defs('%shandT' % pre, 'Hand', sorted((idx[n], h) for n, h in hands.items()), lean_hand,
                             'The hand functions\' inner checks, by index.') + '\n'
    if loops:
        (ln, (lvps, lc, lend)), = loops.items()
        data += ('/-- The loop hand, `%s`: its iteration\'s inner check. -/\ndef %sloopHand : Hand := %s\n\n'
                 '/-- The loop hand by index, and its end. -/\n'
                 'def %sloopJ (j : ℕ) : Option (Hand × Option ℕ) :=\n  if j = %d then some (%sloopHand, %s) else none\n\n'
                 % (ln, pre, lean_hand((lvps, lc)), pre, idx[ln], pre, 'none' if lend is None else '(some %d)' % lend))
    else:
        data += 'def %sloopJ (_ : ℕ) : Option (Hand × Option ℕ) := none\n\n' % pre
    data += ('/-- `main`, `da_verify` and the children\'s loop, by index. -/\n'
             'def %sidxMain : ℕ := %d\ndef %sidxDa : ℕ := %d\ndef %sidxLoop : ℕ := %d\n\n'
             % (pre, idx['main'], pre, idx['da_verify'], pre, idx['__loop4_main']))
    data += '/-- `main`\'s inner check. -/\ndef %smainHand : Hand := %s\n\n' % (pre, lean_hand(hands['main']))
    data += ('/-- The absent functions, by index. -/\ndef %sabsL : List Bool := [%s]\n\n'
             % (pre, ', '.join('true' if fns[i]['name'] in H.absent else 'false' for i in range(N))))
    data += ('/-- The certificate of function `j`. -/\ndef %scertJ (j : ℕ) : Cert := (%scertT.find j).getD .none\n\n'
             '/-- Function `j`\'s inner check, if a hand function. -/\ndef %shandJ (j : ℕ) : Option Hand := %shandT.find j\n\n'
             '/-- Whether function `j` is absent. -/\ndef %sabsJ (j : ℕ) : Bool := %sabsL.getD j false\n\n'
             'end\nend LeanVM.Guest.Data\n' % ((pre,) * 6))
    family.write(os.path.join(D, 'Data.lean'), data)
    chk = 'chkHJ true Data.%scertJ Data.%shandJ Data.%sloopJ Data.%sabsJ Data.waomegaJ' % ((pre,) * 4)

    def kind(j):
        n = fns[j]['name']
        if n in H.absent: return 'abs'
        if n in loops: return 'loop'
        if n in hands: return 'hand'
        return 'stat'

    def walked(j):
        n = fns[j]['name']; k = kind(j)
        if k == 'loop': return fns[j]['body'][:-2]
        if k == 'stat' and certs[n][0] == 'loop': return fns[j]['body'][:-2]
        return fns[j]['body']

    def ctx(j):
        n = fns[j]['name']; k = kind(j); fn = fns[j]
        if k == 'hand': return checker.Ctx(certs, hands[n][1][3], fn['params'] + hands[n][0], n, True, om)
        if k == 'loop': return checker.Ctx(certs, loops[n][1][3], fn['params'] + loops[n][0], n, True, om)
        return checker.Ctx(certs, words.cert_ks(certs[n]), fn['params'], n, True, om)

    costs = [0.05 if kind(j) == 'abs' else walk_cost(H, fns[j]['name'], walked(j)) for j in range(N)]
    RB, MB = 40, 120
    big = [j for j in range(N) if costs[j] > MB]
    mods = family.pack(costs, RB, MB, set(big))
    for j in big: write_cut(H, D, mod, pre, chk, j, kind(j), walked, ctx, certs, hands, loops, RB, MB)
    for k, m in enumerate(mods):
        t = family.header('%s.Part%02d' % (mod, k), 'Ranges of the core IR passing `%s`.' % chk,
                          'public import %s.Data\npublic import LeanVM.Guest.Memory.Family\n' % mod)
        t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
        for a, n, _ in m:
            t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d %d := by\n'
                  '  unfold RangeOk; decide +kernel\n' % (pre, a, chk, a, n))
        t += '\nend\nend LeanVM.Guest.Memory\n'
        family.write(os.path.join(D, 'Part%02d.lean' % k), t)
    rs = sorted([(a, n) for m in mods for a, n, _ in m] + [(j, 1) for j in big])
    t = family.header('%s.All' % mod, 'Every function of the guest\'s core IR passes its check with the hand functions.',
                      ''.join('public import %s.Part%02d\n' % (mod, k) for k in range(len(mods))) +
                      ''.join('public import %s.Fn%d\n' % (mod, j) for j in big))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\n/-- **Every function passes.** -/\ntheorem %s_all : RangeOk (%s) 0 coreProgram.length := by\n'
          '  rw [coreProgram_length]\n  have h := %s\n  exact h\n\nend\nend LeanVM.Guest.Memory\n'
          % (pre, chk, family.chain(rs, lambda a: '%sRange_%d' % (pre, a))))
    family.write(os.path.join(D, 'All.lean'), t)
    return len(rs), len(mods), big


def write_cut(H, D, mod, pre, chk, j, k, walked, ctx, certs, hands, loops, RB, MB):
    """`Fn{j}.lean` and its `Cut{j}*` ranges: function `j`'s check by ranges of its walk."""
    fns = H.fns; n = fns[j]['name']
    if k == 'hand':
        step = 'stepHJ true Data.%scertJ Data.%shandJ Data.waomegaJ' % (pre, pre)
        of_run = 'chkHJ_of_hand_run (by decide +kernel) (by decide +kernel) (by decide +kernel)'
        of_split = 'chkHJ_of_hand_split (by decide +kernel) (by decide +kernel) (by decide +kernel)'
        walk_t = 'Data.core%d.body' % j
    elif k == 'stat':
        step = 'stepS true Data.%scertJ Data.waomegaJ' % pre
        of_run = None
        walk_t = '((Data.%scertJ %d).walk Data.core%d)' % (pre, j, j)
    else:
        raise ValueError('%s: a loop hand too large for one check' % n)
    cut = family.Cut(step, 'Acc.add', 'Acc.zero', 'Acc.add_assoc', 'Data.%scertJ' % pre, None, None,
                     lambda jj, rho, ss: checker.run_range(checker.stmt_step, checker.add, ctx(jj), rho, ss),
                     writelean.lean_acc, None, None, None)
    sp = checker.SPLIT.get(n)
    if sp is None:
        names, steps = family.cut_walk(D, mod, pre, j, cut, RB, MB, walked(j), walk_t, '')
        if k == 'hand':
            proof = '  exact RangeOk.one (fn := Data.core%d) rfl (%s h0 (by decide +kernel))' % (j, of_run)
        else:
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (chkHJ_of_chkS (by decide +kernel) (by decide +kernel)\n'
                     '    (by decide +kernel) (chkS_of_run (by decide +kernel) h0 (by decide +kernel)))' % j)
    else:
        x, na = sp
        names, steps, alts = [], [], []
        for r in range(na):
            nm, st = family.cut_walk(D, mod, pre, j, cut, RB, MB, checker.sel_body(fns[j]['body'], x, r),
                                     '(selL %d %d Data.core%d.body)' % (x, r, j), 'A%d' % r)
            names += nm; steps += st
            alts.append('    · exact ⟨_, A%dh0, by decide +kernel⟩' % r)
        if k == 'hand':
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (%s (x := %d) (n := %d) rfl (by decide +kernel)\n'
                     '    fun r hr ↦ by\n    interval_cases r\n%s)' % (j, of_split, x, na, '\n'.join(alts)))
        else:
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (chkHJ_of_chkS (by decide +kernel) (by decide +kernel)\n'
                     '    (by decide +kernel) (chkS_of_split (x := %d) (n := %d) rfl rfl (by decide +kernel)\n'
                     '    fun r hr ↦ by\n    interval_cases r\n%s))' % (j, x, na, '\n'.join(alts)))
    t = family.header('%s.Fn%d' % (mod, j), 'Function %d passes `%s`, by ranges of its walk.' % (j, chk),
                      ''.join('public import %s.%s\n' % (mod, nm) for nm in names))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d 1 := by\n%s\n%s\n'
          % (pre, j, chk, j, '\n'.join(steps), proof))
    t += '\nend\nend LeanVM.Guest.Memory\n'
    family.write(os.path.join(D, 'Fn%d.lean' % j), t)


