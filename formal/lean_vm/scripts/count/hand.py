"""The guest's words with its hand functions: the functions the static checker cannot bound from their
arguments (a size or a loop's end split from hinted bits, or loaded from memory), each checked over
virtual parameters, values of its body taken as further parameters (`Memory/StaticSound.lean`'s
`Hand`), its callers seeing an outer certificate in its arguments.

    python3 -I scripts/count/hand.py LEAN_VM [--report [--zero]] [--cache DIR]

Writes `LeanVM/Guest/Memory/GuestWordsH/` (the zero-challenge sum counted) and `GuestWordsZ/` (its
functions `level_residual_sum__*` absent, certified at zero), gitignored, before a build that imports
`Memory/GuestWordsH.lean`: `Data.lean` (every function's certificate, the hands' inner checks, the
loop hand's, the absent functions), `PartNN.lean`, `Cut*`, `Fn*`, the kernel checks of
`Memory/FamilyHand.lean`'s `chkHJ` by ranges, and `All.lean`. Every loop may run no iteration: each
`callIf` guard is kept (`guardAtom`), so a loop's run asks only `start <= end`.

A hand's virtual parameters are found by the checker's failures (`Hands.inner`); its outer bound
(`outer_of`) bounds each by its arguments or a constant: a count's quotient by the count, `list_split`'s
blocks by the list's length, a table's size at its largest entry, `verify_sub`'s shape at its largest
(`VS_MAX`). `da_verify`'s and the children's loop's outer bounds are the node's (`SYMBOLIC`), zero here.
`--report` prints each hand function's virtual parameters, inner and outer bounds.
"""
