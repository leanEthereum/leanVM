REN = re.compile(r'\b(certTree|omegaTree|lnkTree|certJ|omegaJ|lnkJ|lookJ|omLookJ|handJ|chkIdx\w*|StaticRange|staticRange_\d+|split_\d+_\d+|certT[lr]*|omegaT[lr]*|lnkT[lr]*)\b')

def write_lean(LD, fns, cert, omega, B=2500, M=6000, FMAX=30, alpha=False, fam='GuestStatic', pre='', hand=(),
               mem=None):
    """Writes the family `fam` into the directory `LD` (`lean_vm/LeanVM/Guest/Memory`).

    A body costs `0.05` per statement and `8` per call site, a certified function `40` more; a
    range of functions or a chunk of a large body (split when its function costs more) at most `B`,
    a module at most `M`. With `mem = (RB, MB)` ranges and modules are packed by an estimate of the
    kernel's memory instead, in megabytes over the imports' (`memcost`): a range at most `RB`, a
    module at most `MB`."""
    byn = {fns[i]['name']: i for i in range(len(fns))}
    handlist = '[' + ', '.join('(%d, "%s")' % (byn[h], h) for h in hand) + ']'
    def ren(t):
        t = re.sub(r'\(lookJ (\w+)\) ALPHA', r'(lookJ \1) (omLookJ \1) ALPHA', t)
        t = t.replace('HANDLIST', handlist)
        t = t.replace('ALPHA', 'true' if alpha else 'false').replace('GuestStatic', fam)
        if pre: t = REN.sub(lambda m: pre + m.group(1), t)
        return t
    class W:
        def __init__(self, path): self.path = path
        def write(self, t): open(self.path, 'w').write(ren(t))
    def wopen(path, mode='w'): return W(path)
    os.makedirs(LD + '/' + fam, exist_ok=True)
    for f in glob.glob(LD + '/' + fam + '/*.lean'): os.remove(f)
    N = len(fns)
    byname = {fns[i]['name']: i for i in range(N)}
    def lnk(i):
        return [(g, byname[g]) for g in sorted(callees(fns[i]['body'], set()), key=lambda g: byname[g])]
    def nkey(n):
        k = 0
        for c in reversed(n): k = ord(c) + 1 + 2 ** 21 * k
        return k
    def lean_lnk(l):
        items = sorted((nkey(g), (g, i)) for (g, i) in l)
        def t(it):
            if not it: return '.leaf'
            m = len(it) // 2
            k, (g, i) = it[m]
            return '(.node %d ("%s", %d) %s %s)' % (k, g, i, t(it[:m]), t(it[m + 1:]))
        return t(items)
    def ntree(items, val, name, defs, depth=0):
        if not items: return '.leaf'
        m = len(items) // 2
        k, v = items[m]
        l = ntree(items[:m], val, name + 'l', defs, depth + 1)
        r = ntree(items[m + 1:], val, name + 'r', defs, depth + 1)
        t = '(.node %d (%s) %s %s)' % (k, val(v), l, r)
        if depth == 3:
            defs.append((name, t)); return name
        return t
    body = ('/-\n  LeanVM.Guest.Memory.GuestStatic.Data\n\n  ' + GENBY + '\n'
            '  The static weight certificates of the guest\'s core IR by function index: the certificate, the\n'
            '  weight of a frame (the compiled function\'s length) and the indices of the callees.\n-/\n\n' + HEAD)
    for (nm, items, val, ty) in [
            ('cert', [(i, cert[fns[i]['name']]) for i in range(N) if fns[i]['name'] in cert], lean_cert, 'Cert'),
            ('omega', [(i, omega[fns[i]['name']]) for i in range(N)], str, 'ℕ'),
            ('lnk', [(i, lnk(i)) for i in range(N)], lean_lnk, 'NTree (String × ℕ)')]:
        defs = []; t = ntree(items, val, nm + 'T', defs)
        for n, tt in defs: body += '\n/-- A subtree. -/\ndef %s : NTree (%s) := %s\n' % (n, ty, tt)
        body += '\n/-- By function index. -/\ndef %sTree : NTree (%s) := %s\n' % (nm, ty, t)
    body += DATA_TAIL
    wopen(LD + '/' + fam + '/Data.lean', 'w').write(body)
    def size(ss):
        n = 0
        for s in ss:
            n += 1
            if s[0] == 'ite': n += size(s[2]) + size(s[3])
            elif s[0] == 'match': n += sum(size(a) for a in s[2])
        return n
    def sites(ss):
        n = 0
        for s in ss:
            if s[0] in ('call', 'callIf'): n += 1
            elif s[0] == 'dispatch': n += len(s[2])
            elif s[0] == 'ite': n += sites(s[2]) + sites(s[3])
            elif s[0] == 'match': n += sum(sites(a) for a in s[2])
        return n
    def scost(ss): return 0.05 * size(ss) + 8 * sites(ss)
    cost = [(40 + scost(fns[i]['body'])) if fns[i]['name'] in cert else 4 for i in range(N)]
    def memcost(i):
        """Measured: about 2.5 MB per function, 3 per callee but itself (the check of its name),
        0.02 per statement, 0.11 in a loop helper (its shape's lookups), 0.005 per statement and
        constant of the certificate."""
        cs = callees(fns[i]['body'], set())
        base = 2.5 + 3 * len(cs - {fns[i]['name']})
        c = cert.get(fns[i]['name'])
        if c is None: return base
        n = size(fns[i]['body'])
        return base + n * (0.11 if c[0] == "loop" else 0.02) + 0.005 * n * len(c[-1])
    mc = [memcost(i) for i in range(N)]
    def kslen(i):
        c = cert.get(fns[i]['name'])
        return len(c[-1]) if c is not None else 0
    def chunkw(i, ss):
        """A chunk's weight: by `scost`, or with `mem` its memory estimate."""
        return scost(ss) if mem is None else size(ss) * (0.015 + 0.01 * kslen(i))
    split = {}
    for i in range(N):
        c = cert.get(fns[i]['name'])
        body = fns[i]['body']
        big = cost[i] > B if mem is None else (cost[i] > B or chunkw(i, body) > mem[0])
        lim = B if mem is None else mem[0] / 2
        if big and c is not None and c[0] == 'stat' and all(s[0] != 'ret' for s in body[:-1]):
            rs = []; a = 0
            while a < len(body):
                n, w = 1, chunkw(i, [body[a]])
                while a + n < len(body) and w + chunkw(i, [body[a + n]]) <= lim:
                    w += chunkw(i, [body[a + n]]); n += 1
                rs.append((a, n, w)); a += n
            split[i] = rs
    g = []; a = 0
    while a < N:
        if a in split: a += 1; continue
        n, w, wm = 1, cost[a], mc[a]
        while a + n < N and n < FMAX and (a + n) not in split and w + cost[a + n] <= B and \
                (mem is None or wm + mc[a + n] <= mem[0]):
            w += cost[a + n]; wm += mc[a + n]; n += 1
        g.append((a, n, w if mem is None else wm)); a += n
    # decls: ('range', a, n, w) and ('split', j, a, n, w, acc, env before, env after)
    decls = [('range', a, n, w) for (a, n, w) in g]
    for j, rs in split.items():
        fn = fns[j]
        cx = Ctx(cert, cert[fn['name']][3], fn['params'], fn['name'], alpha, omega)
        rho = ([], [])
        for (a, n, w) in rs:
            chunk = fn['body'][a:a + n]
            r = pyB(cx, rho, chunk)
            rho2 = pyenv(cx, rho, chunk)
            decls.append(('split', j, a, n, w, r, rho, rho2))
            rho = rho2
    decls.sort(key=lambda d: (d[1], d[2] if d[0] == 'split' else -1))
    mods = []; cur = []; cw = 0
    for d in decls:
        w = d[3] if d[0] == 'range' else d[4]
        if cur and cw + w > (M if mem is None else mem[1]): mods.append(cur); cur = []; cw = 0
        cur.append(d); cw += w
    if cur: mods.append(cur)
    wopen(LD + '/' + fam + '/Range.lean', 'w').write(RANGE)
    def lit(r): return 'some (⟨%d, %s⟩, %s)' % (r[0], '[' + ', '.join('(%d, %d)' % q for q in r[1]) + ']', '[' + ', '.join('(%d, %d)' % q for q in r[2]) + ']')
    def litenv(rho):
        return '(%s, %s)' % ('[' + ', '.join('(.n %d, %d)' % q for q in rho[0]) + ']',
                             '[' + ', '.join('(.n %d, %s)' % (v, lean_aff(b)) for v, b in rho[1]) + ']')
    def kslit(j): return lean_ks(cert[fns[j]['name']][3])
    def decl(d):
        if d[0] == 'range': return DECL % (d[1], d[1], d[2])
        _, j, a, n, w, r, e0, e1 = d
        if a + n == len(fns[j]['body']):
            return SPLITLAST % (j, a, j, kslit(j), j, j, j, a, litenv(e0), lit(r))
        return SPLIT % (j, a, j, a, n, j, kslit(j), j, j, j, a, n, litenv(e0), lit(r),
                        kslit(j), j, litenv(e0), j, a, n, litenv(e1))
    for k, mod in enumerate(mods):
        wopen(LD + '/' + fam + '/Part%02d.lean' % k, 'w').write(PART % ''.join(decl(d) for d in mod))
    imports = ''.join('public import LeanVM.Guest.Memory.GuestStatic.Part%02d\n' % k for k in range(len(mods)))
    # whole-function theorems for split functions
    sp = ''
    for j, rs in split.items():
        fn = fns[j]
        cx = Ctx(cert, cert[fn['name']][3], fn['params'], fn['name'], alpha, omega)
        assert pyB(cx, ([], []), fn['body']) is not None
        acc = pyB(cx, ([], []), fn['body'])
        steps = []
        for (a, n, w) in rs[:-1]:
            steps.append('    rw [blockB_dropE _ _ _ %d %d %d split_%d_%d.1 rfl split_%d_%d.2.2,\n'
                         '      ← blockR_eq ((Data.core%d.body.drop %d).take %d), split_%d_%d.2.1]'
                         % (a, n, a + n, j, a, j, a, j, a, n, j, a))
        la = rs[-1][0]
        steps.append('    rw [← blockR_eq (Data.core%d.body.drop %d), split_%d_%d]' % (j, la, j, la))
        sp += SPLITALL % (j, j, j, kslit(j), j, j, j, lit(acc), j, '\n'.join(steps), j)
    wopen(LD + '/' + fam + '/All.lean', 'w').write(ALL % (imports, sp, N, '\n'.join(
        ['  by_cases h%d : j = %d\n  · subst h%d; exact chkIdx_%d' % (i + 1000, j, i + 1000, j) for i, j in enumerate(split)] +
        ['  by_cases h%d : j < %d\n  · exact staticRange_%d.get (by omega) (by omega)' % (i, a + n, a) for i, (a, n, w) in enumerate(g[:-1])]), g[-1][0]))
    return g, mods

