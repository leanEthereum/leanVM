"""Writes a family of static certificates as Lean modules `Memory/<fam>/{Data,Range,PartNN,All}.lean`:
the certificates, frame weights and callee links by core index (`Data`), the check of a function
(`Range`), the kernel's checks of ranges of functions and of chunks of the large bodies
(`PartNN`, each about `M` cost units), and `chkIdx_all` (`All`). Names are prefixed `pre`."""
import os, glob, re
from checker import callees, blockB as pyB, block_env as pyenv, Ctx


def lean_pairs(l): return '[' + ', '.join('(%d, %d)' % q for q in l) + ']'
def lean_ks(l): return '[' + ', '.join('(.n %d, %d)' % q for q in l) + ']'
def lean_aff(b): return '⟨%d, %s⟩' % (b[0], lean_pairs(b[1]))


def lean_cert(c):
    if c[0] == 'stat':
        return '.stat %s %s %s' % (lean_pairs(c[1]), lean_aff(c[2]), lean_ks(c[3]))
    endc = 'none' if c[1] is None else '(some %d)' % c[1]
    return '.loop %s %s %s %s' % (endc, lean_pairs(c[2]), lean_aff(c[3]), lean_ks(c[4]))


