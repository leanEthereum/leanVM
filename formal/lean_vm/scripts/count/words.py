"""The guest's static certificates counting words on the aligned allocator, generated from the guest data.

    python3 -I scripts/count/words.py LEAN_VM [--report] [--cache DIR]

Writes `LeanVM/Guest/Memory/GuestWordsA/` (gitignored, before a build that imports
`Memory/GuestWordsA.lean`): `Data.lean`, the certificates by core index (`wacertJ`), the frame sizes
(`wfsJ`: `main`'s with the jump table's slots, the others at least `2`) and the aligned flags (`walJ`);
`PartNN.lean`, `Cut*`, `Fn*`, the kernel checks of `chkS true Data.wacertJ Data.waomegaJ` by ranges;
`All.lean`, every function passing. The checker is `checker.py`, `Memory/Static.lean`'s mirror,
run at the padded frame weights `wfsJ j + 15·walJ j` (`Memory/WordsA.lean`'s `fsPad`).

A function is allocated aligned (`walJ`) when its body holds a `KECCAK`, or it is an arm of a
`dispatch` one of whose arms is: a superset of the compiler's aligned frames (`aligned` in
`crates/zkdsl_compiler/src/lib.rs`), which `Memory/GuestWordsA.lean` takes as a hypothesis on the
allocator's `al`. A function the checker cannot certify (a size or a loop's end read from memory)
gets `.none`, and so does every caller of one: `--report` lists them, the hand bounds left.
"""
import sys, os, re, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import core, checker, writelean, family

GENBY = 'Generated by `scripts/count/words.py`; do not edit.'
family.GENBY = GENBY


def has_keccak(ss):
    for s in ss:
        if s[0] == 'atom' and s[1] == 'keccak': return True
        if s[0] == 'ite' and (has_keccak(s[2]) or has_keccak(s[3])): return True
        if s[0] == 'match' and any(has_keccak(a) for a in s[2]): return True
    return False


def dispatches(ss, out):
    for s in ss:
        if s[0] == 'dispatch': out.append(s[2])
        elif s[0] == 'ite': dispatches(s[2], out); dispatches(s[3], out)
        elif s[0] == 'match':
            for a in s[2]: dispatches(a, out)
    return out


class G:
    def __init__(self, lv, cache):
        self.lv = lv
        self.D = os.path.join(lv, 'LeanVM', 'Guest', 'Data')
        self.LD = os.path.join(lv, 'LeanVM', 'Guest', 'Memory')
        self.fns = core.load(self.D, cache)
        checker.set_pows(core.load_pows(self.D))
        self.fsz = core.load_frame_sizes(self.D)
        self.N = len(self.fns)
        assert len(self.fsz) == self.N + 1, 'data out of step'
        frames = open(os.path.join(self.D, 'FrameSizes.lean'), encoding='utf-8').read()
        cells = int(re.search(r'abbrev mainCells : ℕ := (\d+)\n', frames).group(1))
        slots = int(re.search(r'abbrev jtSlots : ℕ := (\d+)\n', frames).group(1))
        self.fs = [cells + slots] + [max(2, self.fsz[i + 1]) for i in range(1, self.N)]
        al = {f['name'] for f in self.fns.values() if has_keccak(f['body'])}
        groups = [g for f in self.fns.values() for g in dispatches(f['body'], [])]
        changed = True
        while changed:
            changed = False
            for g in groups:
                if any(x in al for x in g) and not all(x in al for x in g):
                    al |= set(g); changed = True
        self.al = [self.fns[i]['name'] in al for i in range(self.N)]
        self.om = {self.fns[i]['name']: self.fs[i] + (15 if self.al[i] else 0) for i in range(self.N)}

    def certs(self):
        return checker.gen(self.fns, self.om, alpha=True)[1]


def cert_ks(c): return c[3] if c[0] == 'stat' else c[4]


def walked(fn, c):
    return fn['body'][:-2] if c[0] == 'loop' else fn['body']


def fam_cost(fns, cert, i):
    if fns[i]['name'] not in cert: return 0.05
    sp = checker.SPLIT.get(fns[i]['name'])
    return 0.1 + family.walk_cost(fns[i]['body']) + (
        sum(family.walk_cost(checker.sel_body(fns[i]['body'], sp[0], r)) for r in range(sp[1])) if sp else 0)


def write(g):
    cert = g.certs()
    N = g.N
    data = family.header('LeanVM.Guest.Memory.GuestWordsA.Data',
                         'The certificates counting the guest\'s words on the aligned allocator, by core index, '
                         'the frame sizes and the aligned flags.',
                         'public import LeanVM.Guest.Memory.Static\npublic import LeanVM.Guest.Renumber\n')
    data += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\n@[expose] public section\n\n'
    data += family.tree_defs('wacertT', 'Cert', [(i, cert[g.fns[i]['name']]) for i in range(N)
                                                 if g.fns[i]['name'] in cert], writelean.lean_cert,
                             'The certificates, by index.') + '\n'
    data += family.tree_defs('wfsT', 'ℕ', [(i, g.fs[i]) for i in range(N)], str, 'The frame sizes, by index.') + '\n'
    data += ('/-- The functions allocated aligned, by index. -/\ndef walL : List Bool := [%s]\n\n'
             % ', '.join('true' if a else 'false' for a in g.al))
    data += ('/-- The certificate of function `j`. -/\ndef wacertJ (j : ℕ) : Cert := (wacertT.find j).getD .none\n\n'
             '/-- The frame size of function `j`. -/\ndef wfsJ (j : ℕ) : ℕ := (wfsT.find j).getD 0\n\n'
             '/-- Whether function `j` is allocated aligned. -/\ndef walJ (j : ℕ) : Bool := walL.getD j false\n\n'
             '/-- The padded frame weight of function `j`. -/\n'
             'def waomegaJ (j : ℕ) : ℕ := wfsJ j + padOf (walJ j)\n\n'
             'end\nend LeanVM.Guest.Data\n')
    om = g.om

    def ctx(j):
        fn = g.fns[j]; c = cert[fn['name']]
        return checker.Ctx(cert, cert_ks(c), fn['params'], fn['name'], True, om)
    cut = family.Cut('stepS true Data.wacertJ Data.waomegaJ', 'Acc.add', 'Acc.zero', 'Acc.add_assoc', 'Data.wacertJ',
                     'chkS_of_run', lambda j: walked(g.fns[j], cert[g.fns[j]['name']]),
                     lambda j, rho, ss: checker.run_range(checker.stmt_step, checker.add, ctx(j), rho, ss),
                     writelean.lean_acc, 'chkS_of_split', lambda j: checker.SPLIT.get(g.fns[j]['name']),
                     lambda j, r: checker.sel_body(g.fns[j]['body'], checker.SPLIT[g.fns[j]['name']][0], r))
    data_imp = data.replace('public import LeanVM.Guest.Memory.Static\n',
                            'public import LeanVM.Guest.Memory.Static\npublic import LeanVM.Guest.Memory.WordsA\n')
    rs, mods = family.write_family(g.LD, g.fns, 'GuestWordsA', 'wa', data_imp, 'chkS true Data.wacertJ Data.waomegaJ',
                                   lambda i: fam_cost(g.fns, cert, i), RB=40, MB=120,
                                   doc='Every function of the guest\'s core IR passes its check counting aligned words.',
                                   cut=cut)
    return cert, rs, mods


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('lean_vm')
    ap.add_argument('--report', action='store_true')
    ap.add_argument('--cache')
    ap.add_argument('show', nargs='*')
    a = ap.parse_args()
    g = G(a.lean_vm, a.cache)
    if a.report:
        cert = g.certs()
        miss = [g.fns[i]['name'] for i in range(g.N) if g.fns[i]['name'] not in cert]
        print('aligned: %d functions; certified %d of %d' % (sum(g.al), len(cert), g.N))
        for n in miss: print('  hand:', n)
        for n in a.show:
            if n in cert: print(n, cert[n])
        return
    cert, rs, mods = write(g)
    print('words (aligned): certified %d of %d; %d ranges, %d parts' % (len(cert), g.N, len(rs), len(mods)))


if __name__ == '__main__':
    main()
