"""Writes the guest's certificate families for `Memory/Family.lean`: the callees' indices and names
(`Memory/GuestCallees.lean`, checked by `Memory/GuestCalleesOk.lean`), and a family's data and
kernel checks (`Memory/<fam>/{Data,PartNN,All}.lean`): ranges of functions, each one `decide
+kernel` of `RangeOk`, packed into modules by an estimate of their kernel cost, and `All` joining
them over the core IR."""
import os, glob
import writelean
from checker import callees

GENBY = 'Generated by `scripts/count/gen.py`; do not edit.'


def ntree(items, val, name, defs, depth=0, split=3):
    """A balanced `NTree` of the sorted `(key, value)` items, a node per line; the subtrees at depth
    `split` become the definitions `defs`."""
    if not items: return '.leaf'
    m = len(items) // 2
    k, v = items[m]
    l = ntree(items[:m], val, name + 'l', defs, depth + 1, split)
    r = ntree(items[m + 1:], val, name + 'r', defs, depth + 1, split)
    t = '(.node %d (%s)\n    %s\n    %s)' % (k, val(v), l, r)
    if depth == split:
        defs.append((name, t)); return name
    return t


def tree_defs(nm, ty, items, val, doc):
    """`nm : NTree ty` and its subtrees, as Lean definitions."""
    defs = []
    t = ntree(items, val, nm + 'T', defs)
    out = ''.join('/-- A subtree. -/\ndef %s : NTree (%s) :=\n  %s\n\n' % (n, ty, s) for n, s in defs)
    return out + '/-- %s -/\ndef %s : NTree (%s) :=\n  %s\n' % (doc, nm, ty, t)


def header(mod, doc, imports):
    return '/-\n  %s\n\n  %s\n  %s\n-/\n\nmodule\n\n%s' % (mod, GENBY, doc, imports)


def size(ss):
    n = 0
    for s in ss:
        n += 1
        if s[0] == 'ite': n += size(s[2]) + size(s[3])
        elif s[0] == 'match': n += sum(size(a) for a in s[2])
    return n


def sites(ss):
    n = 0
    for s in ss:
        if s[0] in ('call', 'callIf'): n += 1
        elif s[0] == 'dispatch': n += len(s[2])
        elif s[0] == 'ite': n += sites(s[2]) + sites(s[3])
        elif s[0] == 'match': n += sum(sites(a) for a in s[2])
    return n


def walk_cost(ss):
    """The kernel cost of a check's walk of statements, in the units of the budgets `RB`, `MB`: its
    statements, and its call sites, a callee's certificate translated at each."""
    return size(ss) / 250 + sites(ss) / 3


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write(text)


def chain(ranges, name):
    """`RangeOk.append` of the ranges' theorems, in order."""
    t = name(ranges[0][0])
    for a, _ in ranges[1:]:
        t = '(%s.append %s)' % (t, name(a))
    return t


def pack(costs, RB, MB, skip=()):
    """Ranges of consecutive functions of cost at most `RB` (a costlier function alone), those of
    `skip` left out, and modules of consecutive ranges of cost at most `MB`."""
    rs = []; a = 0; N = len(costs)
    while a < N:
        if a in skip: a += 1; continue
        n, w = 1, costs[a]
        while a + n < N and a + n not in skip and w + costs[a + n] <= RB:
            w += costs[a + n]; n += 1
        rs.append((a, n, w)); a += n
    mods = []; cur = []; cw = 0
    for r in rs:
        if cur and cw + r[2] > MB: mods.append(cur); cur = []; cw = 0
        cur.append(r); cw += r[2]
    if cur: mods.append(cur)
    return mods


def write_callees(LD, fns):
    """`Memory/GuestCallees.lean`, each function's name and callees' indices, and
    `Memory/GuestCalleesOk.lean`, their checks."""
    N = len(fns)
    by = {fns[i]['name']: i for i in range(N)}
    names = [(i, fns[i]['name']) for i in range(N)]
    cl = [(i, sorted(by[g] for g in callees(fns[i]['body'], set()))) for i in range(N)]
    cl = [(i, l) for i, l in cl if l]
    body = header('LeanVM.Guest.Memory.GuestCallees',
                  'The functions of the guest\'s core IR by index: their names (`nameT`) and their\n'
                  '  callees\' indices (`calleeT`), for the certificate families (`Memory/Family`).',
                  'public import LeanVM.Guest.Memory.Static\n')
    body += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\n@[expose] public section\n\n'
    body += tree_defs('nameT', 'String', names, lambda s: '"%s"' % s, 'The functions\' names, by index.') + '\n'
    body += tree_defs('calleeT', 'List ℕ', cl, lambda l: '[' + ', '.join(map(str, l)) + ']',
                      'The functions\' callees\' indices, by index.') + '\n'
    body += ('/-- The indices of function `j`\'s callees. -/\n'
             'def calleesJ (j : ℕ) : List ℕ := (calleeT.find j).getD []\n\nend\nend LeanVM.Guest.Data\n')
    write(os.path.join(LD, 'GuestCallees.lean'), body)
    R = 400
    rs = [(a, min(R, N - a)) for a in range(0, N, R)]
    chk = '(fun j fn => decide (Data.nameT.find j = some fn.name))'
    ok = header('LeanVM.Guest.Memory.GuestCalleesOk',
                'The names of `Memory/GuestCallees` are the functions\', and its callees\' indices in range.',
                'public import LeanVM.Guest.Memory.Family\n')
    ok += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\npublic section\n'
    for a, n in rs:
        ok += '\ntheorem nameT_ok_%d : RangeOk %s %d %d := by\n  unfold RangeOk; decide +kernel\n' % (a, chk, a, n)
    ok += ('\n/-- **The names are the functions\'.** -/\ntheorem nameT_ok : RangeOk %s 0 coreProgram.length := by\n'
           '  rw [coreProgram_length]\n  have h := %s\n  exact h\n' % (chk, chain(rs, lambda a: 'nameT_ok_%d' % a)))
    ok += ('\n/-- **The callees\' indices are in range.** -/\n'
           'theorem calleeT_lt : calleeT.all (fun l => l.all fun k => Nat.blt k %d) = true := by\n'
           '  decide +kernel\n' % N)
    ok += ('\n/-- **`nameT` names the functions.** -/\n'
           'theorem nameT_spec {k : ℕ} {g : String} (hk : k < coreProgram.length) (h : nameT.find k = some g) :\n'
           '    (coreProgram[k]?).map Core.Fn.name = some g := by\n'
           '  have hname := RangeOk.all nameT_ok hk\n'
           '  simp only [decide_eq_true_eq] at hname\n'
           '  rw [hname, Option.some.injEq] at h\n'
           '  rw [List.getElem?_eq_getElem hk, Option.map_some, h]\n\nend\nend LeanVM.Guest.Data\n')
    write(os.path.join(LD, 'GuestCalleesOk.lean'), ok)


def lean_env(rho):
    """The constants and bounds `rho` (`Env × BEnv`)."""
    return '(%s, [%s])' % (writelean.lean_ks(rho[0]),
                           ', '.join('(.n %d, %s)' % (v, writelean.lean_aff(b)) for v, b in rho[1]))


class Cut:
    """A family's checks of a function too large for one, by ranges of its walk (`StaticCut`): the
    Lean names of its step (applied to the function's index and data), addition, zero and
    associativity, its certificates and its `*_of_run` lemma; `walk(j)` the statements function
    `j`'s check walks, `run(j, rho, ss)` the mirror's walk of the range `ss` from `rho`
    (`checker.run_range`) and `acc` a result's literal."""
    def __init__(self, step, add, zero, assoc, cert, of_run, walk, run, acc):
        self.step = step; self.add = add; self.zero = zero; self.assoc = assoc; self.cert = cert
        self.of_run = of_run; self.walk = walk; self.run = run; self.acc = acc


def write_cuts(D, mod, pre, chk, j, cut, RB, MB):
    """`<fam>/Cut{j}_*.lean`, the ranges of function `j`'s walk, each its result and the constants
    after it, and `<fam>/Fn{j}.lean`, the walk they make and the function's check."""
    ss = cut.walk(j)
    mods = pack([walk_cost([s]) for s in ss], RB, MB)
    step = '(%s %d Data.core%d)' % (cut.step, j, j)
    walk = '((%s %d).walk Data.core%d)' % (cut.cert, j, j)
    rho = ([], [])
    rs = []
    for m in mods:
        for a, n, _ in m:
            assert not rs or rs[-1][4] is not None, 'function %d: its walk stops before its end' % j
            q = cut.run(j, rho, ss[a:a + n])
            assert q is not None, 'function %d: the range from %d fails' % (j, a)
            rs.append((a, n, rho, q[0], q[1]))
            if q[1] is not None: rho = q[1]
    names = []
    for k, m in enumerate(mods):
        nm = 'Cut%d_%d' % (j, k)
        names.append(nm)
        t = header('%s.%s' % (mod, nm), 'Ranges of the walk of function %d\'s check (`StaticCut`).' % j,
                   'public import %s.Data\npublic import LeanVM.Guest.Memory.StaticCut\n' % mod)
        t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
        for a, n, _ in m:
            _, _, r0, acc, r1 = next(r for r in rs if r[0] == a)
            t += ('\nset_option maxRecDepth 100000 in\ntheorem %sCut_%d_%d :\n    runS %s %s ((%s.drop %d).take %d) %s =\n'
                  '      some (%s, %s) := by\n  decide +kernel\n'
                  % (pre, j, a, cut.add, step, walk, a, n, lean_env(r0), cut.acc(acc),
                     'none' if r1 is None else 'some %s' % lean_env(r1)))
        t += '\nend\nend LeanVM.Guest.Memory\n'
        write(os.path.join(D, nm + '.lean'), t)
    steps = []
    if rs[-1][4] is not None:
        steps.append('  have h%d : runB %s %s %s (%s.drop %d) %s = some %s :=\n    runB_end (by decide +kernel)'
                     % (len(ss), cut.add, cut.zero, step, walk, len(ss), lean_env(rs[-1][4]), cut.zero))
    nxt = len(ss)
    for a, n, _, _, r1 in reversed(rs):
        steps.append('  have h%d := runB_dropStop (zero := %s) %sCut_%d_%d' % (a, cut.zero, pre, j, a) if r1 is None else
                     '  have h%d := runB_drop %s %sCut_%d_%d h%d' % (a, cut.assoc, pre, j, a, nxt))
        nxt = a
    t = header('%s.Fn%d' % (mod, j), 'Function %d passes `%s`, by ranges of its walk.' % (j, chk),
               ''.join('public import %s.%s\n' % (mod, nm) for nm in names))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d 1 := by\n%s\n'
          '  exact RangeOk.one (fn := Data.core%d) rfl (%s (by decide +kernel) h0 (by decide +kernel))\n'
          % (pre, j, chk, j, '\n'.join(steps), j, cut.of_run))
    t += '\nend\nend LeanVM.Guest.Memory\n'
    write(os.path.join(D, 'Fn%d.lean' % j), t)


def write_family(LD, fns, fam, pre, data, chk, cost, RB, MB, doc, cut=None):
    """`Memory/<fam>/`: `Data.lean` (the text `data`), the checks `<pre>Range_<a> : RangeOk chk a n`
    in `PartNN.lean`, ranges packed by `cost` (per function), and `<pre>_all` in `All.lean`; with
    `cut`, a function costlier than a module by ranges of its walk (`write_cuts`)."""
    D = os.path.join(LD, fam)
    os.makedirs(D, exist_ok=True)
    for f in glob.glob(os.path.join(D, '*.lean')): os.remove(f)
    write(os.path.join(D, 'Data.lean'), data)
    N = len(fns)
    costs = [cost(i) for i in range(N)]
    big = [i for i in range(N) if cut is not None and costs[i] > MB]
    mods = pack(costs, RB, MB, set(big))
    mod = 'LeanVM.Guest.Memory.%s' % fam
    for j in big: write_cuts(D, mod, pre, chk, j, cut, RB, MB)
    for k, m in enumerate(mods):
        t = header('%s.Part%02d' % (mod, k), 'Ranges of the core IR passing `%s`.' % chk,
                   'public import %s.Data\npublic import LeanVM.Guest.Memory.Family\n' % mod)
        t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
        for a, n, _ in m:
            t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d %d := by\n'
                  '  unfold RangeOk; decide +kernel\n' % (pre, a, chk, a, n))
        t += '\nend\nend LeanVM.Guest.Memory\n'
        write(os.path.join(D, 'Part%02d.lean' % k), t)
    rs = sorted([(a, n) for m in mods for a, n, _ in m] + [(j, 1) for j in big])
    t = header('%s.All' % mod, doc, ''.join('public import %s.Part%02d\n' % (mod, k) for k in range(len(mods))) +
               ''.join('public import %s.Fn%d\n' % (mod, j) for j in big))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\n/-- **Every function passes.** -/\ntheorem %s_all : RangeOk (%s) 0 coreProgram.length := by\n'
          '  rw [coreProgram_length]\n  have h := %s\n  exact h\n\nend\nend LeanVM.Guest.Memory\n'
          % (pre, chk, chain(rs, lambda a: '%sRange_%d' % (pre, a))))
    write(os.path.join(D, 'All.lean'), t)
    return rs, mods
