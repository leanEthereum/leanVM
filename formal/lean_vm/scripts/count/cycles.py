"""The guest's instruction counts by opcode with its hand functions: `hand.py`'s method, not counting
words, at the frame weights `B2C.ωArm B2C.xmssArmC op` (each function's `pmax`, `main_loop2`'s
separately counted arms at their largest), one run per opcode joined into a vector family
(`Memory/StaticVec.lean`'s `CertV`, `Memory/FamilyHandV.lean`'s `HandV`).

    python3 -I scripts/count/cycles.py LEAN_VM [--report [--zero]] [--cache DIR]

Writes `LeanVM/Guest/Memory/GuestCntH/` (the zero-challenge sum counted) and `GuestCntZ/` (its
functions `level_residual_sum__*` absent), gitignored, before a build that imports
`Memory/GuestCnt.lean`: `Data.lean` (every function's vector certificate, the hands' inner checks, the
loop hand's, the absent functions, the frame weights), `PartNN.lean`, `Cut*`, `Fn*`, the kernel checks
of `chkHJV` by ranges, and `All.lean`. Each opcode's run finds the same hand functions, virtual
parameters, preconditions and terms (the checker's walk does not read the weights), so the six join.
`--report` prints each hand function's inner and outer bounds by opcode.
"""
import sys, os, re, glob, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import core, checker, words, family, writelean, hand

GENBY = 'Generated by `scripts/count/cycles.py`; do not edit.'
OPS = ['xor', 'mulNative', 'setConstant', 'deref', 'jump', 'keccak']


class Weights:
    """`B2C.ωArm B2C.xmssArmC op` by name, `op` the `k`-th opcode: `pmax` and `main_loop2`'s arms."""
    def __init__(self, g):
        self.pm = core.load_pmax(g.D)
        assert sorted(self.pm) == list(range(1, g.N + 1)), 'pmax missing: run guest-cert --c'
        s = open(os.path.join(g.D, 'CplArms.lean'), encoding='utf-8').read()
        self.arm_fn = int(re.search(r'def armFn : ℕ := (\d+)', s).group(1))
        self.arm_max = [int(x) for x in re.search(r'def armMax : List ℕ := \[([\d, ]*)\]', s).group(1).split(',')]
        self.xj = self.arm_fn - 1
        self.xn = g.fns[self.xj]['name']
        self.N = g.N
        self.fns = g.fns

    def vec(self, i):
        """Function `i`'s weights, a coordinate per opcode."""
        p = self.pm.get(i + 1, [])
        p = p + [0] * (6 - len(p))
        return [p[k] + (self.arm_max[k] if i == self.xj else 0) for k in range(6)]

    def om(self, k):
        return {self.fns[i]['name']: self.vec(i)[k] for i in range(self.N)}


def join_cert(cs):
    """The vector certificate of six certificates of one shape."""
    c0 = cs[0]
    if c0[0] == 'stat':
        assert all(c[0] == 'stat' and c[1] == c0[1] and c[3] == c0[3] and [k for k, _ in c[2][1]] == [k for k, _ in c0[2][1]]
                   for c in cs), cs
    else:
        assert all(c[0] == 'loop' and c[1] == c0[1] and c[2] == c0[2] and c[4] == c0[4] and
                   [k for k, _ in c[3][1]] == [k for k, _ in c0[3][1]] for c in cs), cs
    return checker.certv(cs)


def solve_all(g, W, zero):
    """`hand.solve` at each opcode's weights, joined: the vector certificates, hands and loop hands."""
    hand.ALPHA = False
    runs = []
    for k in range(6):
        H = hand.Hands(g, zero, W.om(k))
        hand.VPS.clear()
        runs.append((H,) + hand.solve(H))
    H0 = runs[0][0]
    names = set(runs[0][1])
    for r in runs[1:]:
        assert set(r[1]) == names and set(r[2]) == set(runs[0][2]) and set(r[3]) == set(runs[0][3])
    certs = {n: join_cert([r[1][n] for r in runs]) for n in names}
    hands = {}
    for n in runs[0][2]:
        vps = runs[0][2][n][0]
        assert all(r[2][n][0] == vps for r in runs), n
        hands[n] = (vps, join_cert([r[2][n][1] for r in runs]))
    loops = {}
    for n in runs[0][3]:
        vps, _, endc = runs[0][3][n]
        assert all(r[3][n][0] == vps and r[3][n][2] == endc for r in runs), n
        loops[n] = (vps, join_cert([r[3][n][1] for r in runs]), endc)
    return H0, certs, hands, loops


def report(g, W, zero):
    H, certs, hands, loops = solve_all(g, W, zero)
    print('%s: %d hands, loop hands %s, absent %d' % ('zero' if zero else 'sum', len(hands), list(loops), len(H.absent)))
    for n in sorted(hands):
        vps, c = hands[n]
        print('== %s vps %d inner %s + %s pre %s' % (n, len(vps), c[2][0], c[2][1], c[1]))
        o = certs[n]
        print('   outer %s' % (o[1:3],))
    for n, (vps, c, endc) in loops.items():
        print('== loop %s vps %d endc %s inner %s + %s pre %s' % (n, len(vps), endc, c[2][0], c[2][1], c[1]))
    for n in ('main', 'da_verify', 'verify_sub', 'exponent_tables', 'statement_digest', 'aggregate_claims'):
        if n in certs: print('cert', n, certs[n][:3])


def vle(a, b):
    """`Vec.le`."""
    return all(x <= (b[i] if i < len(b) else 0) for i, x in enumerate(a))


def final_ok(pre, b, w, r, loop=False):
    """`CertV.final`: the walk's result `r` at the frame weights `w` within the bound `b`."""
    ok = r is not None and vle(checker.vadd(w, r[0]), b[0]) and r[1] == b[1] and all(p in pre for p in r[2])
    if ok and loop: ok = all(k != 0 for k, _ in b[1]) and all(k != 0 for k, _ in pre)
    return ok


class Fam:
    """A vector family with hand functions: its certificates, hands, loop hands, absent functions."""
    def __init__(self, g, W, zero):
        self.g, self.W = g, W
        self.H, self.certs, self.hands, self.loops = solve_all(g, W, zero)
        self.fns = g.fns
        self.idx = {self.fns[i]['name']: i for i in range(g.N)}

    def kind(self, j):
        n = self.fns[j]['name']
        if n in self.H.absent: return 'abs'
        if n in self.loops: return 'loop'
        if n in self.hands: return 'hand'
        return 'stat'

    def ctx(self, j):
        n = self.fns[j]['name']; k = self.kind(j); fn = self.fns[j]
        if k == 'hand': return checker.Ctx(self.certs, self.hands[n][1][3], fn['params'] + self.hands[n][0], n)
        if k == 'loop': return checker.Ctx(self.certs, self.loops[n][1][3], fn['params'] + self.loops[n][0], n)
        return checker.Ctx(self.certs, words.cert_ks(self.certs[n]), fn['params'], n)

    def walked(self, j):
        n = self.fns[j]['name']; k = self.kind(j)
        if k == 'loop' or (k == 'stat' and self.certs[n][0] == 'loop'): return self.fns[j]['body'][:-2]
        return self.fns[j]['body']

    def check(self, j):
        """`chkHJV`, mirrored: function `j` passes."""
        n = self.fns[j]['name']; k = self.kind(j); w = self.W.vec(j); cx = self.ctx(j)
        if k == 'abs': return True
        if k == 'loop':
            vps, c, endc = self.loops[n]
            pre = checker.loop_shape(self.fns[j], endc)
            return pre is not None and final_ok(c[1], c[2], w, checker.blockBV(cx, ([], []), pre))
        c = self.hands[n][1] if k == 'hand' else self.certs[n]
        if c[0] == 'loop':
            pre = checker.loop_shape(self.fns[j], c[1])
            return pre is not None and final_ok(c[2], c[3], w, checker.blockBV(cx, ([], []), pre), loop=True)
        body = self.fns[j]['body']
        if final_ok(c[1], c[2], w, checker.blockBV(cx, ([], []), body)): return True
        sel = checker.top_sel(body)
        if sel is None or not 0 < sel[1] < 2 ** 62 or not checker.arm_le(body, *sel): return False
        return all(final_ok(c[1], c[2], w, checker.blockBV(cx, ([], []), checker.sel_body(body, sel[0], r)))
                   for r in range(sel[1]))


def lean_handv(h):
    """A hand by coordinate (`HandV`)."""
    vps, c = h
    return '⟨[%s], %s, %s, %s⟩' % (', '.join('.n %d' % v for v in vps), writelean.lean_pairs(c[1]),
                                     writelean.lean_affv(c[2]), writelean.lean_ks(c[3]))


def lean_certv(c):
    if c[0] == 'stat':
        return '.stat %s %s %s' % (writelean.lean_pairs(c[1]), writelean.lean_affv(c[2]), writelean.lean_ks(c[3]))
    endc = 'none' if c[1] is None else '(some %d)' % c[1]
    return '.loop %s %s %s %s' % (endc, writelean.lean_pairs(c[2]), writelean.lean_affv(c[3]), writelean.lean_ks(c[4]))


def write_weights(g, W):
    """`Memory/GuestCntW/Data.lean`: the frame weights by index, a coordinate per opcode."""
    D = os.path.join(g.LD, 'GuestCntW')
    os.makedirs(D, exist_ok=True)
    t = family.header('LeanVM.Guest.Memory.GuestCntW.Data', 'The frames\' weights counting each opcode\'s instructions, '
                      'by core index: `B2C.ωArm B2C.xmssArmC op`.', 'public import LeanVM.Guest.Memory.FamilyHandV\n')
    t += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\n@[expose] public section\n\n'
    t += family.tree_defs('cntOmT', 'Vec', [(i, W.vec(i)) for i in range(g.N)], writelean.lean_vec,
                          'The frame weights, by index.') + '\n'
    t += ('/-- The frame weights of function `j`. -/\ndef cntOmJ (j : ℕ) : Vec := (cntOmT.find j).getD []\n\n'
          '/-- `main_loop2`\'s core index and its arms\' counts. -/\ndef cntArmJ : ℕ := %d\n\ndef cntArms : Vec := %s\n\n'
          'end\nend LeanVM.Guest.Data\n' % (W.xj, writelean.lean_vec(W.arm_max)))
    family.write(os.path.join(D, 'Data.lean'), t)


def write(F, fam, pre):
    """`Memory/<fam>/`: the vector family's data, its checks by ranges (`<pre>Range_<a>`) and `<pre>_all`."""
    g, fns, N = F.g, F.fns, F.g.N
    bad = [fns[j]['name'] for j in range(N) if not F.check(j)]
    assert not bad, 'the mirror rejects: %s' % bad[:10]
    D = os.path.join(g.LD, fam)
    os.makedirs(D, exist_ok=True)
    for f in glob.glob(os.path.join(D, '*.lean')): os.remove(f)
    mod = 'LeanVM.Guest.Memory.%s' % fam
    assert len(F.loops) == 1, F.loops
    data = family.header('%s.Data' % mod, 'The certificates counting each opcode\'s instructions with the hand functions, '
                         'by core index: the certificates, the hands\' inner checks, the loop hand\'s, the absent functions.',
                         'public import LeanVM.Guest.Memory.GuestCntW.Data\n')
    data += '\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest.Memory\n\n@[expose] public section\n\n'
    data += family.tree_defs('%scertT' % pre, 'CertV', [(i, F.certs[fns[i]['name']]) for i in range(N)
                                                       if fns[i]['name'] in F.certs], lean_certv,
                             'The certificates, by index.') + '\n'
    data += family.tree_defs('%shandT' % pre, 'HandV', sorted((F.idx[n], h) for n, h in F.hands.items()), lean_handv,
                             'The hand functions\' inner checks, by index.') + '\n'
    (ln, (lvps, lc, lend)), = F.loops.items()
    data += ('/-- The loop hand, `%s`: its iteration\'s inner check. -/\ndef %sloopHand : HandV := %s\n\n'
             '/-- The loop hand by index, and its end. -/\n'
             'def %sloopJ (j : ℕ) : Option (HandV × Option ℕ) :=\n  if j = %d then some (%sloopHand, %s) else none\n\n'
             % (ln, pre, lean_handv((lvps, lc)), pre, F.idx[ln], pre, 'none' if lend is None else '(some %d)' % lend))
    data += ('/-- `main`, `da_verify` and the children\'s loop, by index. -/\n'
             'def %sidxMain : ℕ := %d\ndef %sidxDa : ℕ := %d\ndef %sidxLoop : ℕ := %d\n\n'
             % (pre, F.idx['main'], pre, F.idx['da_verify'], pre, F.idx['__loop4_main']))
    data += '/-- `main`\'s inner check. -/\ndef %smainHand : HandV := %s\n\n' % (pre, lean_handv(F.hands['main']))
    data += ('/-- The absent functions, by index. -/\ndef %sabsL : List Bool := [%s]\n\n'
             % (pre, ', '.join('true' if fns[i]['name'] in F.H.absent else 'false' for i in range(N))))
    data += ('/-- The certificate of function `j`. -/\ndef %scertJ (j : ℕ) : CertV := (%scertT.find j).getD .none\n\n'
             '/-- Function `j`\'s inner check, if a hand function. -/\ndef %shandJ (j : ℕ) : Option HandV := %shandT.find j\n\n'
             '/-- Whether function `j` is absent. -/\ndef %sabsJ (j : ℕ) : Bool := %sabsL.getD j false\n\n'
             'end\nend LeanVM.Guest.Data\n' % ((pre,) * 6))
    family.write(os.path.join(D, 'Data.lean'), data)
    chk = 'chkHJV Data.%scertJ Data.%shandJ Data.%sloopJ Data.%sabsJ Data.cntOmJ' % ((pre,) * 4)
    costs = [0.05 if F.kind(j) == 'abs' else hand.walk_cost(F.H, fns[j]['name'], F.walked(j)) for j in range(N)]
    RB, MB = 40, 120
    big = [j for j in range(N) if costs[j] > MB]
    mods = family.pack(costs, RB, MB, set(big))
    for j in big: write_cut(F, D, mod, pre, chk, j, RB, MB)
    for k, m in enumerate(mods):
        t = family.header('%s.Part%02d' % (mod, k), 'Ranges of the core IR passing `%s`.' % chk,
                          'public import %s.Data\npublic import LeanVM.Guest.Memory.Family\n' % mod)
        t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
        for a, n, _ in m:
            t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d %d := by\n'
                  '  unfold RangeOk; decide +kernel\n' % (pre, a, chk, a, n))
        t += '\nend\nend LeanVM.Guest.Memory\n'
        family.write(os.path.join(D, 'Part%02d.lean' % k), t)
    rs = sorted([(a, n) for m in mods for a, n, _ in m] + [(j, 1) for j in big])
    t = family.header('%s.All' % mod, 'Every function of the guest\'s core IR passes its check counting instructions with '
                      'the hand functions.',
                      ''.join('public import %s.Part%02d\n' % (mod, k) for k in range(len(mods))) +
                      ''.join('public import %s.Fn%d\n' % (mod, j) for j in big))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\n/-- **Every function passes.** -/\ntheorem %s_all : RangeOk (%s) 0 coreProgram.length := by\n'
          '  rw [coreProgram_length]\n  have h := %s\n  exact h\n\nend\nend LeanVM.Guest.Memory\n'
          % (pre, chk, family.chain(rs, lambda a: '%sRange_%d' % (pre, a))))
    family.write(os.path.join(D, 'All.lean'), t)
    return len(rs), len(mods), big


def write_cut(F, D, mod, pre, chk, j, RB, MB):
    """`Fn{j}.lean` and its `Cut{j}*` ranges: function `j`'s vector check by ranges of its walk."""
    fns = F.fns; n = fns[j]['name']; k = F.kind(j)
    if k == 'hand':
        step = 'stepHJV Data.%scertJ Data.%shandJ' % (pre, pre)
        walk_t = 'Data.core%d.body' % j
    elif k == 'stat':
        step = 'stepV Data.%scertJ' % pre
        walk_t = '((Data.%scertJ %d).walk Data.core%d)' % (pre, j, j)
    else:
        raise ValueError('%s: a loop hand too large for one check' % n)
    cut = family.Cut(step, 'AccV.add', 'AccV.zero', 'AccV.add_assoc', 'Data.%scertJ' % pre, None, None,
                     lambda jj, rho, ss: checker.run_range(checker.stmt_stepV, checker.addv, F.ctx(jj), rho, ss),
                     writelean.lean_accv, None, None, None)
    sp = checker.SPLIT.get(n)
    hd = '(by decide +kernel) (by decide +kernel) (by decide +kernel)'
    if sp is None:
        names, steps = family.cut_walk(D, mod, pre, j, cut, RB, MB, F.walked(j), walk_t, '')
        if k == 'hand':
            proof = '  exact RangeOk.one (fn := Data.core%d) rfl (chkHJV_of_hand_run %s h0 (by decide +kernel))' % (j, hd)
        else:
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (chkHJV_of_chkV %s\n'
                     '    (chkV_of_run (by decide +kernel) h0 (by decide +kernel)))' % (j, hd))
    else:
        x, na = sp
        names, steps, alts = [], [], []
        for r in range(na):
            nm, st = family.cut_walk(D, mod, pre, j, cut, RB, MB, checker.sel_body(fns[j]['body'], x, r),
                                     '(selL %d %d Data.core%d.body)' % (x, r, j), 'A%d' % r)
            names += nm; steps += st
            alts.append('    · exact ⟨_, A%dh0, by decide +kernel⟩' % r)
        if k == 'hand':
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (chkHJV_of_hand_split %s (x := %d) (n := %d) rfl\n'
                     '    (by decide +kernel) fun r hr ↦ by\n    interval_cases r\n%s)' % (j, hd, x, na, '\n'.join(alts)))
        else:
            proof = ('  exact RangeOk.one (fn := Data.core%d) rfl (chkHJV_of_chkV %s\n'
                     '    (chkV_of_split (x := %d) (n := %d) rfl rfl (by decide +kernel)\n'
                     '    fun r hr ↦ by\n    interval_cases r\n%s))' % (j, hd, x, na, '\n'.join(alts)))
    t = family.header('%s.Fn%d' % (mod, j), 'Function %d passes `%s`, by ranges of its walk.' % (j, chk),
                      ''.join('public import %s.%s\n' % (mod, nm) for nm in names))
    t += '\nnamespace LeanVM.Guest.Memory\n\nopen LeanVM.Guest\n\npublic section\n'
    t += ('\nset_option maxRecDepth 100000 in\ntheorem %sRange_%d : RangeOk (%s) %d 1 := by\n%s\n%s\n'
          % (pre, j, chk, j, '\n'.join(steps), proof))
    t += '\nend\nend LeanVM.Guest.Memory\n'
    family.write(os.path.join(D, 'Fn%d.lean' % j), t)


COLS = [7, 9, 5, 10, 14, 68]
# The words coefficients the checker's count fits (`Budget/HandCount.lean`'s `Coefs.checker*`), but the child's.
WORDS = {'claim': 66, 'xmss': 1348, 'sphincs': 7336, 'matrix': 96774, 'row': 120875, 'fixed': 41297}
WORDS_CHILD = {False: 456272 + 993, True: 372185 + 993}


def node_vectors(F):
    """`main`'s, `da_verify`'s and the children's loop's inner bounds as the node's counts, a vector each: `main`'s
    constant (with the jump table's `SET`s and the loop's last frame), a declared claim, a duplicate slot, a raw
    leanXMSS, a raw leanSPHINCS, a child; `da_verify`'s constant, a row, a padding row; the loop's iteration and a
    claim of a child's list."""
    _, mc = F.hands['main']
    t = {}
    for k, v in mc[2][1]: t.setdefault(k, []).append(v)
    one = lambda k: (t[k][0] if len(t[k]) == 1 else None)
    assert one(0) == one(1) and one(2) == one(3), t
    child = [0] * 6
    for v in t[6]: child = checker.vadd(child, v)
    _, dc = F.hands['da_verify']
    dt = dict(dc[2][1])
    (ln, (lvps, lc, _)), = F.loops.items()
    lt = dict(lc[2][1])
    assert len(lt) == 2 and len(set(map(tuple, lt.values()))) == 1, lt
    last = F.W.vec(F.idx[ln])
    jt = [0, 0, F.g.fs[0] - int(re.search(r'abbrev mainCells : ℕ := (\d+)', open(os.path.join(F.g.D, 'FrameSizes.lean'),
                                                                                 encoding='utf-8').read()).group(1)), 0, 0, 0]
    return dict(main=mc[2][0], jt=jt, last=last, decl=one(0), dup=one(2), xmss=one(4), sphincs=one(5), child=child,
                da=dc[2][0], row=dt[1], pad=dt[2], iter=lc[2][0], claim=list(lt.values())[0])


def table(F, zero):
    """Each item's rows and weighted rows, and the smallest coefficients that bound words, rows and weighted rows."""
    v = node_vectors(F)
    for k in ('main', 'jt', 'last', 'decl', 'dup', 'xmss', 'sphincs', 'child', 'da', 'row', 'pad', 'iter', 'claim'):
        print('  %-8s %s' % (k, v[k]))
    assert all(a >= b for a, b in zip(v['row'], v['pad']))
    add = checker.vadd
    # a slot is a declared claim's or a duplicate's, at most the larger of the two by coordinate
    slot = checker.vmax(v['decl'], v['dup'])
    print('  %-8s %s' % ('slot', slot))
    items = {'claim': add(v['claim'], slot), 'child': add(v['iter'], v['child']), 'xmss': add(v['xmss'], slot),
             'sphincs': add(v['sphincs'], slot), 'matrix': add(v['da'], [32 * x for x in v['pad']]),
             'row': [a - b for a, b in zip(v['row'], v['pad'])], 'fixed': add(add(v['main'], v['jt']), v['last'])}
    words = dict(WORDS, child=WORDS_CHILD[zero])
    print('  %-8s %10s %10s %12s %10s %12s' % ('item', 'rows', 'weighted', 'words coef', 'rows+cmt', 'all three'))
    for k, x in items.items():
        r = sum(x); w = sum(a * b for a, b in zip(COLS, x))
        if k == 'fixed': c = max(r + 1, -(-(w + 2 ** 15) // 31))
        else: c = max(r, -(-w // 31))
        print('  %-8s %10d %10d %12d %10d %12d' % (k, r, w, words[k], c, max(c, words[k])))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('lean_vm')
    ap.add_argument('--report', action='store_true')
    ap.add_argument('--zero', action='store_true')
    ap.add_argument('--table', action='store_true')
    ap.add_argument('--cache')
    a = ap.parse_args()
    g = words.G(a.lean_vm, a.cache)
    W = Weights(g)
    print('arms: %s (%s), max %s' % (W.xn, W.arm_fn, W.arm_max))
    if a.report:
        report(g, W, a.zero)
        return
