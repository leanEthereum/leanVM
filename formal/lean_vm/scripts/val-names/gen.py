#!/usr/bin/env python3
"""The value and statement names the proofs cite, as data: `LeanVM/Guest/Data/ValNames/<f>.lean`.

    python3 -I scripts/val-names/gen.py [--check] [--dump FILE]

Scans the hand-written Lean files for `val% f "name"`, `pos% f "name"` and `span% f "a" "b"`
(`Guest/ValRef.lean`), and the rule files `scripts/core-mode/fn/*.py` for `val('f', 'name')`,
`valf('f', 'name')`, `pos('f', 'name')` (`fnrules`; a value's name is its source name, `acc`,
`g.acc` or `acc@2`, or its expansion path, `s3.i3:g.s8#0`), looks each name up in `guest-core
--names` (or `--dump`, its saved output) and writes, for each cited function `f`, the numerals of
the names cited: `V.«f/name»` a value's number, `S.«f/name»` the position of the top-level statement
that names it first (by that value's source name or path; `ret`, a body's final `ret`; `NAME+d` the
statement `d` past `NAME`'s, those between naming no new value). A cited name the core IR no longer
has fails, naming the proofs that cite it: the function changed, and those proofs follow it.
`--check` writes nothing and fails when a file differs. Run from `lean_vm`.
"""
import os, re, subprocess, sys

sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import genfiles  # noqa: E402

OUT = os.path.join("LeanVM", "Guest", "Data", "ValNames")
SKIP = (os.path.join("LeanVM", "Guest", "Data"), os.path.join("LeanVM", "Guest", "Pack"))
CITE = re.compile(r'\b(valf|val|pos)%((?:\s+«?[A-Za-z0-9_]+»?)+)\s+"([^"]+)"')
SPAN = re.compile(r'\bspan%\s+«?([A-Za-z0-9_]+)»?\s+"([^"]+)"\s+"([^"]+)"')
PYCITE = re.compile(r"\b(valf|val|pos)\(\s*'([A-Za-z0-9_]+)'\s*,\s*(?:'(_[A-Za-z0-9_]+)'\s*,\s*)?'([^']+)'\s*\)")


def cited():
    out = {}
    for top in ("LeanVM", "tests"):
        for d, _, fs in os.walk(top):
            if d.startswith(SKIP):
                continue
            for f in fs:
                if f.endswith(".lean"):
                    p = os.path.join(d, f)
                    text = re.sub(r'--[^\n]*', '', re.sub(r'/-.*?-/', '', open(p, encoding="utf-8").read(), flags=re.S))
                    for m in CITE.finditer(text):
                        kind = {"val": "V", "valf": "F", "pos": "S"}[m.group(1)]
                        ids = re.findall(r'«?([A-Za-z0-9_]+)»?', m.group(2))
                        # `valf% f "n"`, `valf% f «_loop0» "n"`: the family `f__L`, `f__L_loop0`
                        keys = [ids[0] + "__L" + "".join(ids[1:])] if kind == "F" else ids
                        for key in keys:
                            out.setdefault(key, {}).setdefault((kind, m.group(3)), set()).add(p)
                    for m in SPAN.finditer(text):
                        for n in m.group(2, 3):
                            out.setdefault(m.group(1), {}).setdefault(("S", n), set()).add(p)
    # the rule files cite them as `val('f', 'name')`, `valf('f', ['suffix',] 'name')`, `pos('f', 'name')` (`fnrules`)
    rules = os.path.join("scripts", "core-mode", "fn")
    for f in sorted(os.listdir(rules)) if os.path.isdir(rules) else []:
        if f.endswith(".py"):
            p = os.path.join(rules, f)
            text = re.sub(r'#[^\n]*', '', open(p, encoding="utf-8").read())
            for m in PYCITE.finditer(text):
                kind = {"val": "V", "valf": "F", "pos": "S"}[m.group(1)]
                ids = [m.group(2)] + ([m.group(3)] if m.group(3) else [])
                key = ids[0] + "__L" + "".join(ids[1:]) if kind == "F" else ids[0]
                out.setdefault(key, {}).setdefault((kind, m.group(4)), set()).add(p)
    return out


def names(dump):
    text = open(dump, encoding="utf-8").read() if dump else subprocess.run(
        [os.path.join(".lake", "build", "bin", "guest-core"), "--names"], check=True,
        capture_output=True, text=True).stdout
    t, path = {}, {}
    for line in text.splitlines():
        f, kind, i, n = line.split("\t")
        t[(f, "S" if kind == "s" else "V", n)] = int(i)
        if kind == "s": t[("#pos", f, int(i))] = True
        if kind == "v": path[(f, int(i))] = n
    # a statement by the source name of the first value it names
    for (f, k, n), i in list(t.items()):
        if k == "V" and (f, i) in path and (f, "S", path[(f, i)]) in t:
            t.setdefault((f, "S", n), t[(f, "S", path[(f, i)])])
    return t


def render(f, rows):
    body = []
    for ns in ("V", "F", "S"):
        ent = sorted((n, i) for (k, n), i in rows.items() if k == ns)
        if ent:
            g = f
            body.append(f"namespace {ns}\n" + "".join(f"abbrev «{g}/{n}» : Nat := {i}\n" for n, i in ent) + f"end {ns}\n")
    return (f"/-\n  LeanVM.Guest.Data.ValNames.{f}\n\n  Generated by `scripts/val-names/gen.py`; do not edit.\n"
            f"  The values and statements of `{f}` the proofs cite by name (`val%`, `pos%`).\n-/\n\nmodule\n\n"
            "namespace LeanVM.Guest.Data.ValNames\n\n@[expose] public section\n\n" + "\n".join(body) +
            "\nend\nend LeanVM.Guest.Data.ValNames\n")


def main():
    check = "--check" in sys.argv
    dump = sys.argv[sys.argv.index("--dump") + 1] if "--dump" in sys.argv else None
    c = cited()
    t = names(dump) if c else {}
    bad, files = [], {}
    fnames = {g for (g, _, _) in t}
    for f, cs in sorted(c.items()):
        rows = {}
        for (k, n), ps in sorted(cs.items()):
            if k == "F":
                base, suffix = f.split("__L", 1)
                members = sorted({g for g in fnames if re.fullmatch(re.escape(base) + r'__L\d+(?:_L\d+)*' + re.escape(suffix), g)})
                nums = {t.get((g, "V", n)) for g in members}
                i = nums.pop() if len(nums) == 1 and members else None
                if i is None:
                    bad.append(f"{f}: {n} is not one value of every member ({len(members)}), cited in {', '.join(sorted(ps))}")
                    continue
                rows[(k, n)] = i
                continue
            i = t.get((f, k, n))
            # `NAME+d`: the statement `d` past `NAME`'s, every one between naming no new value
            pm = re.fullmatch(r'(.+)\+(\d+)', n) if k == "S" and i is None else None
            if pm and (f, "S", pm.group(1)) in t:
                b, d = t[(f, "S", pm.group(1))], int(pm.group(2))
                if not any(t.get(("#pos", f, b + e)) for e in range(1, d + 1)):
                    i = b + d
            if i is None:
                bad.append(f"{f}: no {'value' if k == 'V' else 'statement'} {n}, cited in {', '.join(sorted(ps))}")
            else:
                rows[(k, n)] = i
        files[os.path.join(OUT, f + ".lean")] = render(f, rows)
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    existing = [os.path.join(OUT, x) for x in (os.listdir(OUT) if os.path.isdir(OUT) else [])]
    stale = genfiles.sync(files, existing, check)
    genfiles.fail_if_stale(stale, check)
    if not check:
        print(f"val-names: {sum(len(r) for r in c.values())} names of {len(files)} functions, {len(stale)} written or removed")
    return 0

if __name__ == "__main__":
    sys.exit(main())
