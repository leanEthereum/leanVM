//! The compiled aggregation guest as Lean data: `Statement/Data/Bytecode*.lean` (paths here are
//! relative to `lean_vm/`), the bytecode `LeanVM.Guest.guest` (`Statement/LeanVmGuest.lean`) is
//! assembled from. Each compiled function is a definition holding its
//! name, entry pc, length and code, in chunks of `CHUNK` instructions (`LeanVM.Guest.chunkSize`),
//! one definition per chunk; operands are frame offsets and `SET` immediates limbs, so that Lean
//! never evaluates a power of `g`. The format is the BLAKE2s-era `guest_bytecode_lean`'s, with
//! `.keccak m0 m1 m2 m3 tail b8 cap out inOdd outOdd outCells` in place of `.blake2s`.

use super::*;
use leanvm_core::cpu::{DerefMode, Op, OutCells};
use std::fmt::Write as _;

/// Where the data modules go, relative to `lean_vm/`: the statement's generated data.
pub const DATA: &str = "../Statement/Data";

/// Instructions per chunk definition: `LeanVM.Guest.chunkSize`.
pub const CHUNK: usize = 2048;

/// A chunk module closes after the chunk that takes it past this many instructions.
const MODULE: usize = 16384;

pub fn lean_op(op: &Op) -> String {
    match *op {
        Op::Xor { a, b, c } => format!(".xor {a} {b} {c}"),
        Op::Mul { a, b, c } => format!(".mul {a} {b} {c}"),
        Op::Set { o, k } => format!(".set {o} {} {}", k.c0, k.c1),
        Op::Deref { o1, o2, o3, mode } => {
            let mode = match mode {
                DerefMode::Cell => "cell",
                DerefMode::Pc => "pc",
                DerefMode::Fp => "fp",
            };
            format!(".deref {o1} {o2} {o3} .{mode}")
        }
        Op::Jump { oc, od, of } => format!(".jump {oc} {od} {of}"),
        Op::Keccak {
            m: [m0, m1, m2, m3],
            tail,
            b8,
            cap,
            out,
            in_odd,
            out_odd,
            out_cells,
        } => {
            let out_cells = match out_cells {
                OutCells::One => "one",
                OutCells::Two => "two",
                OutCells::All => "all",
            };
            format!(".keccak {m0} {m1} {m2} {m3} {tail} {b8} {cap} {out} {in_odd} {out_odd} .{out_cells}")
        }
    }
}

fn header(module: &str, about: &str, imports: &str) -> String {
    format!(
        "/-\n  Statement.Data.{module}\n\n  Generated by `guest-export` (lean_vm/scripts/guest-export) from leanVM \
         {rev}; do not edit.\n  {about}\n-/\n\nmodule\n\n\
         {imports}\n\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest\n\nset_option maxRecDepth 20000\n\n\
         @[expose] public section\n\n",
        rev = env!("LEANVM_REV")
    )
}

const FOOTER: &str = "end\nend LeanVM.Guest.Data\n";

/// The data modules.
pub fn files(guest: &Program) -> Vec<File> {
    let prog = guest.prog();
    let log_size = prog.len().trailing_zeros();
    assert_eq!(prog.len(), 1 << log_size);
    let mut pc = 0;
    for (name, entry, len) in &guest.fn_ranges {
        assert!(name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'), "{name}");
        assert_eq!(*entry as usize, pc, "{name} is not laid out after its predecessor");
        pc += *len as usize;
    }
    let code_len = pc;
    assert_eq!(code_len, guest.code_len());
    assert!(code_len < prog.len());
    for op in &prog[code_len..] {
        assert!(
            matches!(*op, Op::Set { o: 0, k } if k == F128::ZERO),
            "the padding is not `SET fp[0] = 0`"
        );
    }

    let mut files = Vec::new();
    let mut body = String::new();
    let mut size = 0;
    let close = |files: &mut Vec<File>, body: &mut String| {
        let module = format!("Bytecode{:02}", files.len());
        let text = header(
            &module,
            "Compiled functions of the aggregation guest.",
            "public import Statement.LeanIsa",
        ) + body
            + FOOTER;
        files.push(File {
            path: format!("{DATA}/{module}.lean"),
            text,
        });
        body.clear();
    };
    // Chunk modules hold only the chunks, closing at a chunk boundary once past `MODULE`
    // instructions, so that no module elaborates one huge function whole (the 100k-instruction
    // `verify_sig_lean_sphincs` spans several) and the modules elaborate in parallel. The
    // function records `f{i}` go to the table module, which imports them all.
    let mut records = String::new();
    for (index, (name, entry, len)) in guest.fn_ranges.iter().enumerate() {
        let (entry, len) = (*entry as usize, *len as usize);
        let code = &prog[entry..entry + len];
        let chunks: Vec<String> = (0..code.len().div_ceil(CHUNK)).map(|c| format!("f{index}c{c}")).collect();
        for (c, (chunk, ops)) in chunks.iter().zip(code.chunks(CHUNK)).enumerate() {
            let ops: Vec<String> = ops.iter().map(|op| format!("  {}", lean_op(op))).collect();
            writeln!(body, "/-- `{name}` from offset {}. -/", c * CHUNK).unwrap();
            writeln!(body, "def {chunk} : List OffsetInstruction := [\n{}]\n", ops.join(",\n")).unwrap();
            size += ops.len();
            if size >= MODULE {
                close(&mut files, &mut body);
                size = 0;
            }
        }
        writeln!(
            records,
            "/-- `{name}`: pc {entry} to {}. -/\ndef f{index} : CompiledFunction :=\n  ⟨\"{name}\", {entry}, {len}, [{}]⟩\n",
            entry + len,
            chunks.join(", ")
        )
        .unwrap();
    }
    if !body.is_empty() {
        close(&mut files, &mut body);
    }

    let imports: Vec<String> = files
        .iter()
        .map(|f| {
            let m = f.path.trim_start_matches(DATA).trim_start_matches('/').trim_end_matches(".lean");
            format!("public import Statement.Data.{m}")
        })
        .collect();
    let table: Vec<String> = (0..guest.fn_ranges.len()).map(|i| format!("f{i}")).collect();
    let mut body = records;
    writeln!(body, "/-- The log of the bytecode size. -/\ndef logSize : ℕ := {log_size}\n").unwrap();
    writeln!(
        body,
        "/-- The compiled functions' instructions; the padding `SET fp[0] = 0` follows. -/\ndef codeLen : ℕ := {code_len}\n"
    )
    .unwrap();
    let rows: Vec<String> = table.chunks(16).map(|row| format!("  {}", row.join(", "))).collect();
    writeln!(
        body,
        "/-- The compiled functions, in layout order. -/\ndef functions : List CompiledFunction := [\n{}]\n",
        rows.join(",\n")
    )
    .unwrap();
    let text = header("Bytecode", "The function table of the aggregation guest.", &imports.join("\n")) + &body + FOOTER;
    files.push(File {
        path: format!("{DATA}/Bytecode.lean"),
        text,
    });
    files
}
