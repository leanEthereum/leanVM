//! The guest's advice for the Lean executor: `main`'s frame size and the hints by pc
//! (`CompiledProgram::export_hints`, no witness stream), as one string literal the executor parses
//! (`LeanVM/Guest/Data/Advice.lean`).

use super::*;
use isa::{BitsDest, RHint};

/// `LeanVM/Guest/Data/Advice.lean`.
pub fn file() -> File {
    let advice = guest().export_hints(&[]);
    assert!(
        advice.chars().all(|c| c.is_ascii_alphanumeric() || " _-\n".contains(c)),
        "the advice is plain tokens"
    );
    let literal = advice.replace('\n', "\\n");
    let text = format!(
        "/-
  LeanVM.Guest.Data.Advice

  Generated by `scripts/guest-export` from leanVM's sources; do not edit.
  The guest's advice without its witness streams: `main`'s frame size and the compiler's hints
  by pc (`CompiledProgram::export_hints`), parsed by `LeanVM.Prover.parseAdvice`.
-/

module

@[expose] public section

namespace LeanVM.Guest.Data

/-- The guest's advice text. -/
def adviceText : String := \"{literal}\"

end LeanVM.Guest.Data
"
    );
    File { path: "LeanVM/Guest/Data/Advice.lean".to_string(), text }
}

/// A function's entries per definition.
const HINTS_PER_DEF: usize = 256;

/// A run's start as a Lean `BitsDest`.
fn dest(d: &BitsDest) -> String {
    match d {
        BitsDest::Stack(v) => format!("(.stack {v})"),
        BitsDest::Heap(v) => format!("(.heap {v})"),
    }
}

/// A hint as a Lean `Hint`, `None` for a `Print`, which the executor does not run.
fn hint_lean(h: &RHint) -> Option<String> {
    Some(match h {
        RHint::FrameAddress { offset } => format!("(.frameAddress {offset})"),
        RHint::AllocFrames {
            ptr,
            size,
            end,
            start_inverse,
        } => format!("(.allocFrames {ptr} {size} {end} (LeanVM.Parameters.K.ofBits 0x{:x}))", start_inverse.0),
        RHint::Alloc { ptr, size } => format!("(.alloc {ptr} {size})"),
        RHint::AllocDyn { ptr, size } => format!("(.allocDyn {ptr} {size})"),
        RHint::AllocArm { ptr, sel, sizes } => {
            let sizes: Vec<String> = sizes.iter().map(u32::to_string).collect();
            format!("(.allocArm {ptr} {sel} [{}])", sizes.join(", "))
        }
        RHint::CellAddress { ptr, cell } => format!("(.cellAddress {ptr} {cell})"),
        RHint::WitnessStack { name, base, len } => format!("(.witnessStack \"{name}\" {base} {len})"),
        RHint::WitnessHeap { name, ptr, lo, len } => format!("(.witnessHeap \"{name}\" {ptr} {lo} {len})"),
        RHint::Log2Ceil {
            bits,
            dst,
            nbits,
            floor,
        } => format!("(.log2Ceil {} {dst} {nbits} {floor})", dest(bits)),
        RHint::BitDecompose { value, bits, nbits } => format!("(.bitDecompose {value} {} {nbits})", dest(bits)),
        RHint::BitDecomposeExp { value, bits, nbits } => format!("(.bitDecomposeExp {value} {} {nbits})", dest(bits)),
        RHint::DigitDecomposeExp {
            value,
            dst,
            nbits,
            ndigits,
            digit_bits,
            start,
            start_cell,
        } => {
            let sc = start_cell.map_or("none".to_string(), |c| format!("(some {c})"));
            format!("(.digitDecomposeExp {value} {} {nbits} {ndigits} {digit_bits} {start} {sc})", dest(dst))
        }
        RHint::WindowsExp {
            value,
            dest: d,
            at,
            start,
            width,
            count,
        } => format!("(.windowsExp {value} {} {at} {start} {width} {count})", dest(d)),
        RHint::FieldLimbs { value, base, len } => format!("(.fieldLimbs {value} {base} {len})"),
        RHint::Inverse { value, dst } => format!("(.inverse {value} {dst})"),
        RHint::Print { .. } => return None,
    })
}

/// A hint module closes after the function that takes it past this many bytes of hints.
const HINT_MODULE_BYTES: usize = 700_000;

/// The header of a hint module, as `Statement/Data/Bytecode*.lean`'s.
fn hints_header(module: &str, about: &str, imports: &str) -> String {
    format!(
        "/-\n  Statement.Data.{module}\n\n  Generated by `guest-export` (lean_vm/scripts/guest-export) from leanVM; do not \
         edit.\n  {about}\n  {}\n-/\n\nmodule\n\n{imports}\n\nnamespace LeanVM.Guest.Data\n\n\
         open LeanVM.Prover.Exec\n\npublic section\n\n",
        super::bytecode::HIDDEN
    )
}

/// `Statement/Data/AdviceHints*.lean`: the advice of `file` as Lean data, each function's hints
/// with its entry and length (`adviceFn{j}`, in parts `adviceFn{j}p{k}` past `HINTS_PER_DEF`
/// entries), in modules of about `HINT_MODULE_BYTES` bytes (`AdviceHints00`, ...), and in
/// `AdviceHints`, which imports them, the records of the functions in parts, `main`'s frame size and
/// the table of the functions' hints. The guest's prover (`Statement/LeanVmGuestProver.lean`) runs on it,
/// and the core route's generated certificates (`scripts/core-mode`) read their hints from it.
pub fn data_files() -> Vec<File> {
    let g = guest();
    let main_frame = g.main_frame;
    let mut pcs: Vec<(&u32, &Vec<RHint>)> = g.hints.iter().collect();
    pcs.sort_by_key(|(pc, _)| **pc);
    let entries: Vec<(u64, String)> = (pcs.into_iter())
        .map(|(&pc, hs)| {
            let hs: Vec<String> = hs.iter().filter_map(hint_lean).collect();
            (u64::from(pc), format!("({pc}, [{}])", hs.join(", ")))
        })
        .collect();
    let mut files = Vec::new();
    let mut defs = String::new();
    let close = |files: &mut Vec<File>, defs: &mut String| {
        let module = format!("AdviceHints{:02}", files.len());
        let text = hints_header(&module, "The compiler's hints by pc of the aggregation guest's functions.",
            "public import Statement.Prover.Execute") + defs + "end\nend LeanVM.Guest.Data\n";
        files.push(File { path: format!("{}/{module}.lean", super::bytecode::DATA), text });
        defs.clear();
    };
    let mut names = Vec::new();
    let mut split_records = String::new();
    let mut rest = entries.as_slice();
    for (j, (name, entry, len)) in g.fn_ranges.iter().enumerate() {
        let (entry, len) = (*entry as u64, *len as u64);
        let k = rest.iter().take_while(|e| e.0 < entry + len).count();
        let (mine, more) = rest.split_at(k);
        assert!(mine.iter().all(|e| entry <= e.0), "a hint before `{name}`");
        rest = more;
        let body: Vec<&str> = mine.iter().map(|e| e.1.as_str()).collect();
        names.push(format!("adviceFn{j}"));
        let list = if body.len() <= HINTS_PER_DEF {
            format!("[{}]", body.join(",\n    "))
        } else {
            let mut parts = Vec::new();
            for (k, part) in body.chunks(HINTS_PER_DEF).enumerate() {
                parts.push(format!("adviceFn{j}p{k}"));
                defs.push_str(&format!(
                    "/-- `{name}`: its hints by pc, part {k}. -/\ndef adviceFn{j}p{k} : List (ℕ × List Hint) :=\n  [{}]\n\n",
                    part.join(",\n    ")
                ));
                if defs.len() >= HINT_MODULE_BYTES {
                    close(&mut files, &mut defs);
                }
            }
            format!("List.flatten [{}]", parts.join(", "))
        };
        // A function in parts has its record in `AdviceHints`, which imports every part.
        let record = format!(
            "/-- `{name}`: its entry, length and hints by pc. -/\ndef adviceFn{j} : ℕ × ℕ × List (ℕ × List Hint) :=\n  ({entry}, {len}, {list})\n\n"
        );
        if body.len() <= HINTS_PER_DEF {
            defs.push_str(&record);
        } else {
            split_records.push_str(&record);
        }
        if defs.len() >= HINT_MODULE_BYTES {
            close(&mut files, &mut defs);
        }
    }
    assert!(rest.is_empty(), "a hint past the code");
    if !defs.is_empty() {
        close(&mut files, &mut defs);
    }
    let imports: Vec<String> = (0..files.len()).map(|i| format!("public import Statement.Data.AdviceHints{i:02}\nimport all Statement.Data.AdviceHints{i:02}")).collect();
    let text = hints_header(
        "AdviceHints",
        "The guest's advice of `LeanVM/Guest/Data/Advice.lean` as data: `main`'s frame size and the\n  compiler's hints by pc, each function's with its entry and length, in layout order.",
        &imports.join("\n"),
    ) + &split_records + &format!(
        "/-- `main`'s frame size. -/\ndef adviceMainFrame : ℕ := {main_frame}\n\n\
         /-- The functions' hints, in layout order. -/\ndef adviceFns : List (ℕ × ℕ × List (ℕ × List Hint)) := [{}]\n\n\
         /-- The hints by pc. -/\ndef adviceHints : List (ℕ × List Hint) := (adviceFns.map (·.2.2)).flatten\n\n\
         end\nend LeanVM.Guest.Data\n",
        names.join(", ")
    );
    files.push(File { path: format!("{}/AdviceHints.lean", super::bytecode::DATA), text });
    files
}
