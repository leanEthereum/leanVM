//! The guest's advice for the Lean executor: `main`'s frame size and the hints by pc
//! (`Program::advice_text`, no witness stream), as one string literal the executor parses
//! (`LeanVM/Guest/Data/Advice.lean`).

use super::*;

/// `LeanVM/Guest/Data/Advice.lean`.
pub fn file() -> File {
    let advice = guest().advice_text();
    assert!(
        advice.chars().all(|c| c.is_ascii_alphanumeric() || " _-\n".contains(c)),
        "the advice is plain tokens"
    );
    let literal = advice.replace('\n', "\\n");
    let text = format!(
        "/-
  LeanVM.Guest.Data.Advice

  Generated by `scripts/guest-export` from leanVM's sources; do not edit.
  The guest's advice without its witness streams: `main`'s frame size and the compiler's hints
  by pc (`Program::advice_text`), parsed by `LeanVM.Prover.parseAdvice`.
-/

module

@[expose] public section

namespace LeanVM.Guest.Data

/-- The guest's advice text. -/
def adviceText : String := \"{literal}\"

end LeanVM.Guest.Data
"
    );
    File { path: "LeanVM/Guest/Data/Advice.lean".to_string(), text }
}
