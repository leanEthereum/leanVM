//! What the Rust reports of the deployed guest, as Lean data the Lean side checks its assembled
//! `guest` against (`tests/LeanVMTests/Guest/Manifest.lean`): the log size, the code length, the
//! function count, the instructions of each opcode, and the guest's Fiat-Shamir IV
//! (`leanvm_core::cpu::fs_seed`, the Spec's `deployedSeed guest`), which hashes the stacked
//! bytecode and so pins every instruction.

use super::*;
use leanvm_core::cpu::Op;

/// The counts of `XOR`, `MUL`, `SET`, `DEREF`, `JUMP`, `KECCAK` in the whole padded bytecode.
pub fn opcode_counts(prog: &[Op]) -> [usize; 6] {
    let mut n = [0; 6];
    for op in prog {
        n[match op {
            Op::Xor { .. } => 0,
            Op::Mul { .. } => 1,
            Op::Set { .. } => 2,
            Op::Deref { .. } => 3,
            Op::Jump { .. } => 4,
            Op::Keccak { .. } => 5,
        }] += 1;
    }
    n
}

pub fn file() -> File {
    let g = guest();
    let seed = leanvm_core::cpu::fs_seed(g);
    let counts = opcode_counts(&g.prog);
    let text = format!(
        "/-\n  LeanVMTests.Guest.Manifest\n\n  Generated by `guest-export` (lean_vm/scripts/guest-export) from leanVM {rev}; do not\n  \
         edit. What the Rust reports of the deployed aggregation guest.\n-/\n\n\
         namespace LeanVMTests.Guest.Manifest\n\n\
         /-- The leanVM commit the guest was compiled at. -/\ndef leanvmRev : String := {rev:?}\n\n\
         /-- The log of the bytecode size. -/\ndef logSize : Nat := {log}\n\n\
         /-- The compiled functions' instructions. -/\ndef codeLen : Nat := {code}\n\n\
         /-- The compiled functions. -/\ndef functionCount : Nat := {nf}\n\n\
         /-- The instructions of each opcode (`XOR`, `MUL`, `SET`, `DEREF`, `JUMP`, `KECCAK`), the padding included. -/\n\
         def opcodeCounts : List Nat := {counts:?}\n\n\
         /-- The smallest stacked witness the guest's proofs commit to, as a log (`min_log_committed`). -/\n\
         def minLogCommitted : Nat := {minlog}\n\n\
         /-- `fs_seed`: the guest's Fiat-Shamir IV, two cells as `(c0, c1, c2)` limbs. -/\n\
         def fsSeed : List (Nat × Nat × Nat) := [({}, {}, {}), ({}, {}, {})]\n\n\
         end LeanVMTests.Guest.Manifest\n",
        seed[0].c0,
        seed[0].c1,
        seed[0].c2,
        seed[1].c0,
        seed[1].c1,
        seed[1].c2,
        rev = env!("LEANVM_REV"),
        log = g.prog.len().trailing_zeros(),
        code = g.code_len(),
        nf = g.fn_ranges.len(),
        minlog = g.min_log_committed,
    );
    File {
        path: "tests/LeanVMTests/Guest/Manifest.lean".into(),
        text,
    }
}
