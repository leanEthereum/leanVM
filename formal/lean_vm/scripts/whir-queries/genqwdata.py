"""Write B1/Bits/QueryWindowsBody{0,1}.lean (the bodies, by kernel evaluation, over the core packs)
and QueryWindowsData.lean (the functions found in `coreProgram`) from the guest data."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen
B = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/B1/Bits/'
shapes = sorted((tuple(map(int, n[len('decode_query_windows__L'):].split('_L'))), n, i)
                for n, i in gen.fns.items() if n.startswith('decode_query_windows__L'))
N = len(shapes)
CHUNKS = 2
for k in range(CHUNKS):
    part = [s for s in shapes if gen.chunk_of(s[1], CHUNKS) == k]
    out = ['''/-
  LeanVM.Guest.B1.Bits.QueryWindowsBody%d

  The bodies of the `decode_query_windows` specializations in the core packs `P{j}`, `j %% %d = %d`,
  are their template, by kernel evaluation. Generated by `scripts/whir-queries/genqwdata.py`; do not
  edit.
-/

module

public import LeanVM.Guest.B1.Bits.QueryWindowsT
%s
namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Guest.Core LeanVM.Guest

@[expose] public section
''' % (k, CHUNKS, k, gen.pack_imports(n for _, n, _ in part))]
    for (d, cd), n, i in part:
        out.append('''set_option maxRecDepth 100000 in
theorem qwBody_L%d_L%d : (Fn.«%s».core).body = qwBody %d %d :=
  stmtsEqb_sound (by decide +kernel)
''' % (d, cd, gen.key_of(n), d, cd))
    out.append('end\nend LeanVM.Guest.B1\n')
    open(B + 'QueryWindowsBody%d.lean' % k, 'w').write(gen.wrap('\n'.join(out)))
out = ['''/-
  LeanVM.Guest.B1.Bits.QueryWindowsData

  The %d specializations of `decode_query_windows` are their template, found in `coreProgram`.
  Generated by `scripts/whir-queries/genqwdata.py`; do not edit.
-/

module

%s
public import LeanVM.Guest.B1.Common.Find

/-!
# `decode_query_windows`' specializations

`queryWindowsShapes`: the deployed `(name, depth, cap depth)`; `queryWindows_data`: each is found
in the core IR with the parameters `0 .. 3` and the body `qwBody d cd` (`QueryWindowsBody*.lean`,
one kernel evaluation each).
-/

namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Guest.Core LeanVM.Guest

@[expose] public section

/-- A core function of the name with the parameters `0 .. 3` and the body. -/
abbrev QwIs (name : String) (body : List Stmt) : Prop := QwIsP coreProgram name body
''' % (N, '\n'.join('public import LeanVM.Guest.B1.Bits.QueryWindowsBody%d' % k for k in range(CHUNKS)))]
names = []
for (d, cd), n, i in shapes:
    t = 'qw_L%d_L%d' % (d, cd); names.append(t)
    out.append('''set_option maxRecDepth 100000 in
theorem %s : QwIs "%s" (qwBody %d %d) :=
  ⟨fn%% «%s», coreProgram_find?_at (j := idx%% «%s») rfl, rfl, qwBody_L%d_L%d⟩
''' % (t, n, d, cd, n, n, d, cd))
out.append('''/-- **Every deployed specialization is its template.** -/
theorem queryWindows_data : ∀ p ∈ queryWindowsShapes, QwIs p.1 (qwBody p.2.1 p.2.2) := by
  intro p hp
  simp only [queryWindowsShapes, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with %s
  exacts [%s]

end
end LeanVM.Guest.B1
''' % (' | '.join(['rfl'] * N), ', '.join(names)))
open(B + 'QueryWindowsData.lean', 'w').write(gen.wrap('\n'.join(out)))
