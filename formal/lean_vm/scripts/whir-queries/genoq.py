"""Write B1/Opening/QueriesBody{0..3}.lean and `QueriesFns.lean`'s `oqFns_all` cases."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen
D = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/B1/Opening/'
sp = gen.oq_specs()

def shape(d):
    return '(%s : OqShape)' % gen.shape(d)

HEAD = '''/-
  LeanVM.Guest.B1.Opening.%s

  %s
  Generated by `scripts/whir-queries/genoq.py`; do not edit.
-/

module

%s

namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Value
open LeanVM.Protocol.Verifier

@[expose] public section
'''
parts = [[d for d in sp if gen.chunk_of(d['name'], 4) == k] for k in range(4)]
for k, part in enumerate(parts):
    out = [HEAD % ('QueriesBody%d' % k,
                   "The bodies of the `opening_queries` specializations in the core packs `P{j}`, `j %% 4 = %d`, and of\n  their loop helpers are the templates (kernel evaluation)." % k,
                   'public import LeanVM.Guest.B1.Opening.QueriesT\npublic import LeanVM.Guest.Data.NameStrings\n'
                   + gen.pack_imports(x for d in part for x in (d['name'], d['loop'])).rstrip('\n'))]
    for d in part:
        sh = shape(d)
        loop = gen.stable[d['loop']]
        loopT = ('oqLoop1T %s.oq name%% «%s»' % (sh, loop)) if d['base'] == 1 else \
                ('oqLoop0T %s.oq name%% «%s»' % (sh, loop))
        out.append('''set_option linter.style.nameCheck false in
set_option maxRecDepth 100000 in
/-- `%s`. -/
theorem oqBody_%s : (Fn.«%s».core).body = oqMainT %s.oq name%% «%s» :=
  stmtsEqb_sound (by decide +kernel)

set_option linter.style.nameCheck false in
set_option maxRecDepth 100000 in
/-- `%s`. -/
theorem oqLoopBody_%s : (Fn.«%s».core).body = %s :=
  stmtsEqb_sound (by decide +kernel)
''' % (d['name'], gen.key_of(d['name']), gen.key_of(d['name']), sh, loop, loop, gen.key_of(d['name']), loop,
       loopT))
    out.append('end\nend LeanVM.Guest.B1\n')
    open(D + 'QueriesBody%d.lean' % k, 'w').write(gen.wrap('\n'.join(out)))
# QueriesFns.lean: from `MARK` on, each entry of `openingQueriesLoops` (in `gen.oq_specs`' order)
# found with its functions and bodies, one theorem each, and `oqFns_all`.
p = D + 'QueriesFns.lean'
MARK = '-- Generated by `scripts/whir-queries/genoq.py` from here to the end; do not edit.\n'
s = open(p).read()
i = s.index(MARK)
out = [s[:i] + MARK]
for k, d in enumerate(sp):
    out.append('''set_option linter.style.nameCheck false in
set_option maxRecDepth 100000 in
/-- Entry %d, `%s`. -/
theorem oqFns_%s : OqFns (openingQueriesLoops.getD %d oqNone) := by
  unfold OqFns
  exact ⟨fn%% «%s», fn%% «%s»,
    coreProgram_find?_at (j := idx%% «%s») rfl, rfl, oqBody_%s,
    coreProgram_find?_at (j := idx%% «%s») rfl, rfl, oqLoopBody_%s⟩
''' % (k, d['name'], gen.key_of(d['name']), k, d['name'], gen.stable[d['loop']], d['name'],
       gen.key_of(d['name']), gen.stable[d['loop']], gen.key_of(d['name'])))
out.append('''/-- **Every entry's functions are found with the templates' bodies.** -/
theorem oqFns_all : ∀ p ∈ openingQueriesLoops, OqFns p := by
  intro p hp
  obtain ⟨i, hi, rfl⟩ := List.mem_iff_getElem.mp hp
  rw [List.getElem_eq_getD oqNone]
  have hi' : i < %d := hi
  interval_cases i
  exacts [%s]

end
end LeanVM.Guest.B1
''' % (len(sp), ',\n    '.join(', '.join('oqFns_%s' % gen.key_of(d['name']) for d in sp[r:r + 7])
                                  for r in range(0, len(sp), 7))))
open(p, 'w').write(gen.wrap('\n'.join(out)))
