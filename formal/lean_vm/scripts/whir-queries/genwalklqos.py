"""Write `Guest/WalkLq{0..3}.lean`, `WalkLqOk{0..3}.lean` (`level_queries`' specializations) and
`Guest/WalkOs{0..3}.lean`, `WalkOsOk{0..3}.lean` (`open_stacked`'s arms) from the core IR: each function's
cut obligations `walk_{j}` and the kernel check they rest on, function `j` being core function `j - 1`,
in core order over four modules a family."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen
D = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/'
HEAD = '''/-
  LeanVM.Guest.%s

  %s

  Generated by `scripts/whir-queries/genwalklqos.py`; do not edit.
-/

module

%s

namespace LeanVM.Guest.End

@[expose] public section
'''


def family(prefix):
    fs = sorted((i, n) for n, i in gen.fns.items() if n.startswith(prefix))
    per = -(-len(fs) // 4)
    return [fs[k * per:(k + 1) * per] for k in range(4)]


def write(name, doc, imports, thms):
    open(D + name + '.lean', 'w').write('\n'.join([HEAD % (name, doc, imports)] + thms + ['end\nend LeanVM.Guest.End\n']))


def lq_args(name):
    q, base, _folds, _leaf, depth, cd = map(int, name[len('level_queries__L'):].split('_L')[:6])
    # At base 1 `level_queries` takes the queries in pairs, the odd one left over (`odd`), else one at a time.
    n, odd = (q // 2, q % 2) if base == 1 else (q, 0)
    return n, odd, base, depth, cd


def os_witness(i):
    """Each `level_positions` dispatch of the body: its top-level statement index and its window pointers' value."""
    stmts = [l for l in gen.bodies['core%d' % i].split('\n') if l.startswith('  .')]
    return [(k, int(re.findall(r'\.n (\d+)', l.split('] [')[1])[7])) for k, l in enumerate(stmts)
            if l.startswith('  .dispatch') and '"level_positions__L' in l]


for k, part in enumerate(family('level_queries__L')):
    write('WalkLqOk%d' % k,
          "The certificates of `level_queries`' specializations hand on, at their call of\n"
          "  `opening_queries`, the walk their windows' tag (`lqTag`) says (`lqOk`), by kernel evaluation.",
          'public import LeanVM.Guest.WalkKnownDefs',
          ['/-- `%s`. -/\ntheorem lqOk_%d : lqOk (certOf %d) %d %d %d %d %d = true := by decide +kernel\n'
           % ((n, i + 1, i + 1) + lq_args(n)) for i, n in part])
    write('WalkLq%d' % k,
          "The cut obligations (`CutsKnown`) of `level_queries`' specializations (`lq_cutsKnown`,\n"
          "  `WalkLqOk%d.lean`'s checks)." % k,
          'public import LeanVM.Guest.WalkLq\npublic import LeanVM.Guest.WalkLqOk%d' % k,
          ['/-- `%s`. -/\ntheorem walk_%d : CutsKnown %d :=\n'
           '  lq_cutsKnown (by decide) (by decide) (by decide) (by decide) (by decide) lqOk_%d\n'
           % (n, i + 1, i + 1, i + 1) for i, n in part])

for k, part in enumerate(family('open_stacked__L')):
    names = ', '.join('`%s`' % n for _, n in part)
    write('WalkOsOk%d' % k,
          "The certificates of %s assume the window table and hand on, at each level's\n"
          "  dispatch into `level_queries`, the windows that level's `level_positions` dispatch decodes\n"
          "  (`osOk`), by kernel evaluation." % names,
          'public import LeanVM.Guest.WalkOsDefs',
          ['set_option maxRecDepth 100000 in\n/-- `%s`. -/\ntheorem osOk_%d : osOk %d [%s] = true := by decide +kernel\n'
           % (n, i + 1, i + 1, ', '.join('(%d, %d)' % w for w in os_witness(i))) for i, n in part])
    write('WalkOs%d' % k,
          "The cut obligations (`CutsKnown`) of %s\n  (`os_cutsKnown`, `WalkOsOk%d.lean`'s checks)." % (names, k),
          'public import LeanVM.Guest.WalkOs\npublic import LeanVM.Guest.WalkOsOk%d' % k,
          ['/-- `%s`. -/\ntheorem walk_%d : CutsKnown %d := os_cutsKnown osOk_%d\n' % (n, i + 1, i + 1, i + 1)
           for i, n in part])
