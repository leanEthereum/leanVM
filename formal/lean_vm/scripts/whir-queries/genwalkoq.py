"""Write Guest/WalkOqOk{0..3}.lean and Guest/WalkOq{0..3}.lean: the walk certificates of
opening_queries' specializations and loops (certificate index j = core index + 1)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen
D = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/'
sp = gen.oq_specs()
parts = [[d for d in sp if gen.chunk_of(d['name'], 4) == k] for k in range(4)]  # as `genoq`'s QueriesBody
names = []
for k, part in enumerate(parts):
    ok = ['''/-
  LeanVM.Guest.WalkOqOk%d

  The certificates of `opening_queries`' specializations and loops in the core packs `P{j}`,
  `j %% 4 = %d`, hand on the walk their templates give (`mainOkS`, `loop0Ok`, `loop1Ok`), by kernel evaluation.
  Generated by `scripts/whir-queries/genwalkoq.py`; do not edit.
-/

module

public import LeanVM.Guest.WalkKnownDefs

namespace LeanVM.Guest.End

open LeanVM.Guest.B1

@[expose] public section
''' % (k, k)]
    wk = ['''/-
  LeanVM.Guest.WalkOq%d

  The cut obligations (`CutsKnown`) of `opening_queries`' specializations and loops in the core
  packs `P{j}`, `j %% 4 = %d`,
  from their templates (`B1/Opening/QueriesBody%d.lean`), the generic forms (`WalkKnown.lean`) and
  their certificates' checks (`WalkOqOk%d.lean`). Generated by `scripts/whir-queries/genwalkoq.py`; do not edit.
-/

module

public import LeanVM.Guest.WalkKnown
public import LeanVM.Guest.WalkOqOk%d
public import LeanVM.Guest.B1.Opening.QueriesBody%d

namespace LeanVM.Guest.End

open LeanVM.Guest.B1

@[expose] public section
''' % (k, k, k, k, k, k)]
    for d in part:
        s = '(%s : OqShape).oq' % gen.shape(d)
        jm, jl = d['idx'] + 1, d['loopidx'] + 1
        names += ['walk_%d' % jm, 'walk_%d' % jl]
        ok.append('/-- `%s`. -/\ntheorem walkOk_%d : mainOkS %d %s = true := by decide +kernel\n'
                  % (d['name'], jm, jm, s))
        if d['base'] == 1:
            ok.append('/-- `%s`. -/\ntheorem walkOk_%d : loop1Ok %d %s = true := by decide +kernel\n'
                      % (gen.stable[d['loop']], jl, jl, s))
        else:
            ok.append('/-- `%s`. -/\ntheorem walkOk_%d : loop0Ok %d %s = true := by decide +kernel\n'
                      % (gen.stable[d['loop']], jl, jl, s))
        wk.append('''set_option maxRecDepth 100000 in
/-- `%s`. -/
theorem walk_%d : CutsKnown %d :=
  main_cutsKnown (j := %d) oqBody_%s (by decide) walkOk_%d
''' % (d['name'], jm, jm, jm, gen.key_of(d['name']), jm))
        wk.append('''set_option maxRecDepth 100000 in
/-- `%s`. -/
theorem walk_%d : CutsKnown %d :=
  %s (j := %d) oqLoopBody_%s (by decide) walkOk_%d
''' % (gen.stable[d['loop']], jl, jl, 'loop1_cutsKnown' if d['base'] == 1 else 'loop0_cutsKnown', jl,
       gen.key_of(d['name']), jl))
    for out in (ok, wk):
        out.append('end\nend LeanVM.Guest.End\n')
    open(D + 'WalkOqOk%d.lean' % k, 'w').write('\n'.join(ok))
    open(D + 'WalkOq%d.lean' % k, 'w').write('\n'.join(wk))
print(' '.join(sorted(names, key=lambda n: int(n[5:]))))
