"""Write B1/Opening/WalkBody{0,1,2}.lean and WalkFns.lean from the guest data."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen
D = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/B1/Opening/'
ws = sorted((tuple(map(int, n[len('walk_path__L'):].split('_L'))), n, i)
            for n, i in gen.fns.items() if n.startswith('walk_path__L'))
parts = [[w for w in ws if gen.chunk_of(w[1], 3) == k] for k in range(3)]
for k, part in enumerate(parts):
    out = ['''/-
  LeanVM.Guest.B1.Opening.WalkBody%d

  The bodies of the `walk_path` specializations in the core packs `P{j}`, `j %% 3 = %d`, are the
  template (kernel evaluation). Generated by `scripts/whir-queries/genwalk.py`; do not edit.
-/

module

public import LeanVM.Guest.B1.Opening.QueriesT
%s
namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Value
open LeanVM.Protocol.Verifier

@[expose] public section
''' % (k, k, gen.pack_imports(n for _, n, _ in part))]
    for (pd, cd), n, i in part:
        out.append('''set_option maxRecDepth 100000 in
/-- `%s`. -/
theorem wpBody_L%d_L%d : (Fn.«%s».core).body = wpBodyT ⟨0, 0, %d, %d, 0, [], 0, 0⟩ :=
  stmtsEqb_sound (by decide +kernel)
''' % (n, pd, cd, gen.key_of(n), pd, cd))
    out.append('end\nend LeanVM.Guest.B1\n')
    open(D + 'WalkBody%d.lean' % k, 'w').write('\n'.join(out))
import re
qt = open(D + 'QueriesT.lean').read()
blk = qt[qt.index('def walkPathNames'):]
blk = blk[:blk.index(']')]
order = [(int(a), int(b)) for a, b in re.findall(r'\((\d+), (\d+), "walk_path', blk)]
assert len(order) == len(ws)
out = ['''/-
  LeanVM.Guest.B1.Opening.WalkFns

  Every deployed `walk_path` specialization is its template (`WalkFn`).
  Generated by `scripts/whir-queries/genwalk.py`; do not edit.
-/

module

public import LeanVM.Guest.B1.Opening.WalkPath
%s
public import LeanVM.Guest.B1.Common.Find

namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Value

@[expose] public section
''' % '\n'.join('public import LeanVM.Guest.B1.Opening.WalkBody%d' % k for k in range(len(parts)))]
for (pd, cd), n, i in ws:
    out.append('''set_option maxRecDepth 100000 in
/-- `%s` is its template. -/
theorem wpFn_L%d_L%d : WalkFn coreProgram "%s" %d %d :=
  ⟨_, coreProgram_find?_at (j := idx%% «%s») rfl, rfl, wpBody_L%d_L%d⟩
''' % (n, pd, cd, n, pd, cd, n, pd, cd))
out.append('''/-- **Every deployed `walk_path` is its template.** -/
theorem walkFn_all : ∀ p ∈ walkPathNames, WalkFn coreProgram p.2.2 p.1 p.2.1 := by
  intro p hp
  simp only [walkPathNames, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with %s
  exacts [%s]

end
end LeanVM.Guest.B1
''' % (' | '.join(['rfl'] * len(ws)),
       ', '.join('wpFn_L%d_L%d' % pc for pc in order)))
open(D + 'WalkFns.lean', 'w').write('\n'.join(out))
