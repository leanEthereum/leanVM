"""Write B1/Opening/QueriesPlacedE.lean: `opening_queries`' placed completeness with the tree's size
exact (`CompleteAtE`, `OqCompleteDE`), copied from `QueriesPlacedD0/D1/D2`'s `CompleteAtB` theorems:
their trees are exactly `oqBound` words, only their statements say `≤`."""
import os, re, sys
D = os.path.join(sys.argv[1], 'LeanVM') + '/' + 'Guest/B1/Opening/'


def theorem(src, name):
    """The text of `theorem name …` up to the next blank-line-separated declaration."""
    s = open(D + src).read()
    i = s.index('theorem ' + name + ' ')
    i = s.rindex('\n\n', 0, i) + 2
    j = s.find('\n\n', i)
    while j != -1 and s[j + 2:j + 3] in (' ', ''):
        j = s.find('\n\n', j + 2)
    return s[i:j if j != -1 else len(s)].rstrip() + '\n'


def defn(src, name):
    s = open(D + src).read()
    i = s.index('def ' + name + ' ')
    i = s.rindex('\n\n', 0, i) + 2
    j = s.index('\n\n', i)
    return s[i:j].rstrip() + '\n'


def exact(t):
    t = t.replace('CompleteAtB', 'CompleteAtE')
    t = t.replace('le_of_eq (by rw [hn]; ring)', '(by rw [hn]; ring)')
    t = t.replace('OqCompleteDB', 'OqCompleteDE')
    t = re.sub(r'\boqMain1_completeAtB\b', 'oqMain1_completeAtE', t)
    t = re.sub(r'\boqMain0_completeAtB\b', 'oqMain0_completeAtE', t)
    t = re.sub(r'\boqCompleteDB1\b', 'oqCompleteDE1', t)
    t = re.sub(r'\boqCompleteDB0\b', 'oqCompleteDE0', t)
    t = t.replace('is `CompleteAtE`', 'is `CompleteAtE`, its tree exactly its bound')
    return t


out = ['''/-
  LeanVM.Guest.B1.Opening.QueriesPlacedE

  `opening_queries` is complete by a tree of exactly `oqBound` words.
  Generated by `scripts/whir-queries/genplacedE.py` from `QueriesPlacedD0`, `D1`, `D2`; do not edit.
-/

module

public import LeanVM.Guest.B1.Opening.QueriesPlacedD2
public import LeanVM.Guest.B1.Place.HelperAt

/-!
# `opening_queries`, exact trees

`CompleteAtE … n` (`Place/HelperAt`): complete by a tree of exactly `n` words; `CompleteAtE.of_eq`
builds it from a tree whose size is shown equal to `n`. `oqMain1_completeAtE`,
`oqMain0_completeAtE`: `oqMain1_completeAtB`, `oqMain0_completeAtB` whose trees are exactly their
bounds. `OqCompleteDE`, `oqCompleteDE1`, `oqCompleteDE0`: `OqCompleteDB` and its two proofs, exact.
-/

namespace LeanVM.Guest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Value LeanVM.Guest.Memory
open LeanVM.Protocol LeanVM.Protocol.KeccakHash LeanVM.Protocol.Compile LeanVM.Protocol.Verifier
open LeanVM.Guest.B1.Main (MemL RegionL)

@[expose] public section

theorem CompleteAtE.of_eq {fs : String → ℕ} {cert : String → V → ℕ} {k : ℕ} {f : String}
    {Lin : Main.Layout} {args : List E} {Out : List E → Main.Layout → Prop} {B : ℕ}
    (h : ∀ fp, ∃ (n : ℕ) (Lown : Main.Layout) (rets : List E) (Lout : Main.Layout), Out rets Lout ∧
      Within (Lout ++ Lown) fp n ∧ DisjL (Lout ++ Lown) ∧ n = B ∧ ∀ rd, LowDef k rd →
        MemL rd (Lout ++ Lown ++ Lin) →
        RelAtIn coreProgram fs cert rd (RegionL Lin) (RegionL Lout) fp n f args rets) :
    CompleteAtE fs cert k f Lin args Out B := fun fp =>
  let ⟨_, Lown, rets, Lout, ho, hw, hd, hn, hr⟩ := h fp
  hn ▸ ⟨Lown, rets, Lout, ho, hw, hd, hr⟩

''']
for src, name in [('QueriesPlacedD1.lean', 'oqMain1_completeAtB'), ('QueriesPlacedD0.lean', 'oqMain0_completeAtB')]:
    t = exact(theorem(src, name))
    # the conclusion goes through `CompleteAtE.of_eq`: the proofs give `n`, then `n = …`
    t = t.replace(':= by\n  intro fp\n', ':= by\n  refine CompleteAtE.of_eq fun fp ↦ ?_\n', 1)
    out.append(t + '\n')
out.append(exact(defn('QueriesPlacedD2.lean', 'OqCompleteDB')) + '\n')
for name in ['oqCompleteDB1', 'oqCompleteDB0']:
    out.append(exact(theorem('QueriesPlacedD2.lean', name)) + '\n')
out.append('end\nend LeanVM.Guest.B1\n')
open(D + 'QueriesPlacedE.lean', 'w').write(''.join(out))
