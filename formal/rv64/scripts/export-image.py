"""Export an RV64 ELF image to a Lean module: its code, its initialized data, and its function symbols.

  python3 -I export-image.py ELF NAMESPACE OUT.lean

The code is the one executable segment, as 32-bit encodings from its first address. The data is every other loadable
segment, as aligned 64-bit little-endian words (riscv-zkvm's memory holds doublewords); bytes past a segment's file size
are zero. The symbols are the image's functions, `(name, address, size)`, the names demangled by `c++filt` when it is
installed and printed as Lean string literals. The output is generated: regenerate it, never edit it.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import struct
import subprocess
import sys
from pathlib import Path

PT_LOAD = 1
PF_X = 1
SHT_SYMTAB = 2
STT_FUNC = 2
CHUNK = 256  # list elements per definition: long list literals elaborate slowly


def read_elf(data: bytes):
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit("not a little-endian ELF64")
    (e_machine,) = struct.unpack_from("<H", data, 18)
    if e_machine != 243:
        sys.exit("not RISC-V")
    e_entry, e_phoff, e_shoff = struct.unpack_from("<QQQ", data, 24)
    e_phentsize, e_phnum, e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHHHH", data, 54)
    segments = []
    for i in range(e_phnum):
        p_type, p_flags, p_offset, p_vaddr, _, p_filesz, p_memsz, _ = struct.unpack_from(
            "<IIQQQQQQ", data, e_phoff + i * e_phentsize
        )
        if p_type == PT_LOAD and p_memsz > 0:
            body = data[p_offset : p_offset + p_filesz] + bytes(p_memsz - p_filesz)
            segments.append((p_flags, p_vaddr, body))
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, e_shoff + i * e_shentsize) for i in range(e_shnum)]
    symbols = []
    for sh in sections:
        if sh[1] != SHT_SYMTAB:
            continue
        strtab = sections[sh[6]]
        for j in range(sh[5] // sh[9]):
            st_name, st_info, _, _, st_value, st_size = struct.unpack_from("<IBBHQQ", data, sh[4] + j * sh[9])
            if st_info & 0xF == STT_FUNC and st_size > 0:
                start = strtab[4] + st_name
                name = data[start : data.index(b"\0", start)].decode()
                symbols.append((name, st_value, st_size))
    return e_entry, segments, sorted(set(symbols), key=lambda s: (s[1], s[0]))


def demangle(names: list[str]) -> list[str]:
    tool = shutil.which("c++filt") or shutil.which("rustfilt")
    if not tool or not names:
        return names
    out = subprocess.run([tool], input="\n".join(names), capture_output=True, text=True, check=True).stdout
    lines = out.split("\n")
    return lines[: len(names)] if len(lines) >= len(names) else names


def lean_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def chunked(name: str, typ: str, items: list[str]) -> list[str]:
    out, parts = [], []
    for k in range(0, max(len(items), 1), CHUNK):
        part = f"{name}_{k // CHUNK}"
        parts.append(part)
        body = ",\n  ".join(items[k : k + CHUNK])
        out.append(f"def {part} : List {typ} := [\n  {body}]\n")
    out.append(f"def {name} : List {typ} := List.flatten [{', '.join(parts)}]\n")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("elf")
    ap.add_argument("namespace")
    ap.add_argument("out")
    args = ap.parse_args()
    raw = Path(args.elf).read_bytes()
    entry, segments, symbols = read_elf(raw)
    code = [s for s in segments if s[0] & PF_X]
    if len(code) != 1:
        sys.exit(f"expected one executable segment, found {len(code)}")
    _, code_base, code_bytes = code[0]
    if code_base % 4 or len(code_bytes) % 4:
        sys.exit("code segment not word aligned")
    words = [struct.unpack_from("<I", code_bytes, i)[0] for i in range(0, len(code_bytes), 4)]
    data_words = []
    for flags, vaddr, body in segments:
        if flags & PF_X:
            continue
        start = vaddr - vaddr % 8
        body = bytes(vaddr - start) + body
        body += bytes(-len(body) % 8)
        for i in range(0, len(body), 8):
            data_words.append((start + i, struct.unpack_from("<Q", body, i)[0]))
    names = demangle([s[0] for s in symbols])
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        f"-- Generated by formal/rv64/scripts/export-image.py from an ELF with SHA-256 {digest}. Do not edit.\n",
        "import Rv64Verifier.Machine\n",
        f"namespace {args.namespace}\n",
        "open RiscvZkvm.Rv64\n",
        f"def entry : Word := {entry:#x}\n",
        f"def codeBase : Word := {code_base:#x}\n",
    ]
    lines += chunked("codeWords", "(BitVec 32)", [f"{w:#010x}" for w in words])
    lines.append("def code : Rv64Verifier.Code := ⟨codeBase, codeWords⟩\n")
    lines += chunked("dataWords", "(Word × Word)", [f"({a:#x}, {v:#x})" for a, v in data_words])
    lines += chunked(
        "functions",
        "(String × Word × Nat)",
        [f"({lean_string(n)}, {a:#x}, {s})" for n, (_, a, s) in zip(names, symbols)],
    )
    lines.append(f"end {args.namespace}\n")
    Path(args.out).write_text("\n".join(lines))
    print(f"{len(words)} instructions, {len(data_words)} data words, {len(symbols)} functions -> {args.out}")


if __name__ == "__main__":
    main()
