//! The compiled aggregation guest as Lean data: `formal/lean_vm/LeanVM/Guest/Data/Bytecode*.lean`, the bytecode
//! `LeanVM.Guest.guest` is assembled from. Each compiled function is a definition holding its name, entry pc, length
//! and code, in chunks of `CHUNK` instructions (`LeanVM.Guest.chunkSize`), one definition per chunk; operands are
//! frame offsets and `SET` immediates limbs, so that Lean never evaluates a power of `g`. The test regenerates the
//! modules and fails if they differ from the committed ones; `LEANVM_WRITE_GUEST=1` rewrites them.

use super::*;
use leanvm_core::cpu::{DerefMode, Op};
use std::fmt::Write as _;

const DIR: &str = "../../formal/lean_vm/LeanVM/Guest/Data";

/// Instructions per chunk definition: `LeanVM.Guest.chunkSize`.
const CHUNK: usize = 2048;

/// A data module closes after the function that takes it past this many instructions.
const MODULE: usize = 16384;

fn lean_op(op: &Op) -> String {
    match *op {
        Op::Xor { a, b, c } => format!(".xor {a} {b} {c}"),
        Op::Mul { a, b, c } => format!(".mul {a} {b} {c}"),
        Op::Set { o, k } => format!(".set {o} {} {} {}", k.c0, k.c1, k.c2),
        Op::Deref { o1, o2, o3, mode } => {
            let mode = match mode {
                DerefMode::Cell => "cell",
                DerefMode::Pc => "pc",
                DerefMode::Fp => "fp",
            };
            format!(".deref {o1} {o2} {o3} .{mode}")
        }
        Op::Jump { oc, od, of } => format!(".jump {oc} {od} {of}"),
        Op::Blake2s {
            ins: [m0, m1, m2, m3],
            cv,
            out,
            md,
        } => {
            format!(".blake2s {m0} {m1} {m2} {m3} {cv} {out} {md}")
        }
    }
}

fn header(module: &str, about: &str, imports: &str) -> String {
    format!(
        "/-\n  LeanVM.Guest.Data.{module}\n\n  Generated by `guest_bytecode_lean` \
         (crates/rec_aggregation/src/aggregation/guest_bytecode.rs); do not edit.\n  {about}\n-/\n\nmodule\n\n\
         {imports}\n\nnamespace LeanVM.Guest.Data\n\nopen LeanVM.Guest\n\nset_option maxRecDepth 20000\n\n\
         @[expose] public section\n\n"
    )
}

const FOOTER: &str = "end\nend LeanVM.Guest.Data\n";

/// The data modules, by file name.
fn modules(guest: &Program) -> Vec<(String, String)> {
    let prog = &guest.prog;
    let log_size = prog.len().trailing_zeros();
    assert_eq!(prog.len(), 1 << log_size);
    let mut pc = 0;
    for (name, entry, len) in &guest.fn_ranges {
        assert!(name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'), "{name}");
        assert_eq!(*entry as usize, pc, "{name} is not laid out after its predecessor");
        pc += *len as usize;
    }
    let code_len = pc;
    assert!(code_len < prog.len());
    for op in &prog[code_len..] {
        assert!(
            matches!(*op, Op::Set { o: 0, k } if k == F192::ZERO),
            "the padding is not `SET fp[0] = 0`"
        );
    }

    let mut files = Vec::new();
    let mut body = String::new();
    let mut size = 0;
    let close = |files: &mut Vec<(String, String)>, body: &mut String| {
        let module = format!("Bytecode{:02}", files.len());
        let text = header(
            &module,
            "Compiled functions of the aggregation guest.",
            "public import LeanVM.Guest.Code",
        ) + body
            + FOOTER;
        files.push((module, text));
        body.clear();
    };
    for (index, (name, entry, len)) in guest.fn_ranges.iter().enumerate() {
        let (entry, len) = (*entry as usize, *len as usize);
        let code = &prog[entry..entry + len];
        let chunks: Vec<String> = (0..code.len().div_ceil(CHUNK))
            .map(|c| format!("f{index}c{c}"))
            .collect();
        for (c, (chunk, ops)) in chunks.iter().zip(code.chunks(CHUNK)).enumerate() {
            let ops: Vec<String> = ops.iter().map(|op| format!("  {}", lean_op(op))).collect();
            writeln!(body, "/-- `{name}` from offset {}. -/", c * CHUNK).unwrap();
            writeln!(body, "def {chunk} : List OInstr := [\n{}]\n", ops.join(",\n")).unwrap();
        }
        writeln!(
            body,
            "/-- `{name}`: pc {entry} to {}. -/\ndef f{index} : CompiledFn :=\n  ⟨\"{name}\", {entry}, {len}, [{}]⟩\n",
            entry + len,
            chunks.join(", ")
        )
        .unwrap();
        size += len;
        if size >= MODULE {
            close(&mut files, &mut body);
            size = 0;
        }
    }
    if !body.is_empty() {
        close(&mut files, &mut body);
    }

    let imports: Vec<String> = files
        .iter()
        .map(|(m, _)| format!("public import LeanVM.Guest.Data.{m}"))
        .collect();
    let table: Vec<String> = (0..guest.fn_ranges.len()).map(|i| format!("f{i}")).collect();
    let mut body = String::new();
    writeln!(
        body,
        "/-- The log of the bytecode size. -/\ndef logSize : ℕ := {log_size}\n"
    )
    .unwrap();
    writeln!(
        body,
        "/-- The compiled functions' instructions; the padding `SET fp[0] = 0` follows. -/\ndef codeLen : ℕ := {code_len}\n"
    )
    .unwrap();
    let rows: Vec<String> = table.chunks(16).map(|row| format!("  {}", row.join(", "))).collect();
    writeln!(
        body,
        "/-- The compiled functions, in layout order. -/\ndef functions : List CompiledFn := [\n{}]\n",
        rows.join(",\n")
    )
    .unwrap();
    let text = header(
        "Bytecode",
        "The function table of the aggregation guest.",
        &imports.join("\n"),
    ) + &body
        + FOOTER;
    files.push(("Bytecode".to_string(), text));
    files
}

#[test]
fn guest_bytecode_lean() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(DIR);
    let files = modules(unified_guest());
    let committed = |dir: &std::path::Path| -> BTreeSet<String> {
        std::fs::read_dir(dir)
            .map(|entries| {
                entries
                    .filter_map(|e| e.ok()?.file_name().into_string().ok())
                    .filter(|n| n.starts_with("Bytecode") && n.ends_with(".lean"))
                    .collect()
            })
            .unwrap_or_default()
    };
    if std::env::var_os("LEANVM_WRITE_GUEST").is_some() {
        std::fs::create_dir_all(&dir).unwrap();
        for stale in committed(&dir) {
            std::fs::remove_file(dir.join(stale)).unwrap();
        }
        for (module, text) in &files {
            std::fs::write(dir.join(format!("{module}.lean")), text).unwrap();
        }
    }
    let names: BTreeSet<String> = files.iter().map(|(m, _)| format!("{m}.lean")).collect();
    let stale = names != committed(&dir)
        || files
            .iter()
            .any(|(m, text)| std::fs::read_to_string(dir.join(format!("{m}.lean"))).ok().as_ref() != Some(text));
    assert!(!stale, "{} is stale; rerun with LEANVM_WRITE_GUEST=1", dir.display());
}
