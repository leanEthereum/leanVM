#!/usr/bin/env bash
# Regenerate one libFuzzer binary per `leanvm-fuzz` target: `fuzz_targets/<name>.rs` and the `[[bin]]` list in
# `Cargo.toml`. Run after adding, renaming or removing a target.
set -euo pipefail
cd "$(dirname "$0")"
names=$(cd .. && cargo run --quiet --profile fuzz -p leanvm-fuzz -- list | awk '{print $1}')
rm -f fuzz_targets/*.rs
sed -i.bak '/^# BEGIN TARGETS/,/^# END TARGETS/d' Cargo.toml && rm -f Cargo.toml.bak
{
  echo "# BEGIN TARGETS (generated by sync-targets.sh)"
  for name in $names; do
    file=$(echo "$name" | tr '-' '_')
    printf '#![no_main]\nlibfuzzer_sys::fuzz_target!(|data: &[u8]| fuzz::libfuzzer_case("%s", data));\n' "$name" > "fuzz_targets/$file.rs"
    printf '\n[[bin]]\nname = "%s"\npath = "fuzz_targets/%s.rs"\ntest = false\ndoc = false\nbench = false\n' "$name" "$file"
  done
  echo "# END TARGETS"
} >> Cargo.toml
echo "$(echo "$names" | wc -w | tr -d ' ') targets"
